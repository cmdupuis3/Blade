"""Reads `g++ -dM -E` and `g++ -fdump-lang-raw` output for the TU generate.sh
writes and prints src/CppReservedNames.txt (gap G252). Usage:
    extract.py <macros.txt> <dump.raw> <compiler line> <skipped headers> <emitter-macros.txt>
"""
import re, sys

macros_path, raw_path, compiler, skipped, emitter_path = sys.argv[1:6]

ident = re.compile(r'^[A-Za-z_][A-Za-z0-9_]*$')
obj_macros, fn_macros = set(), set()
for line in open(macros_path, encoding='latin-1'):
    m = re.match(r'#define ([A-Za-z_][A-Za-z0-9_]*)(\(?)', line)
    if m:
        (fn_macros if m.group(2) else obj_macros).add(m.group(1))
for line in open(emitter_path, encoding='latin-1'):
    m = re.match(r'([A-Za-z_][A-Za-z0-9_]*)(\(?)$', line.strip())
    if m:
        (fn_macros if m.group(2) else obj_macros).add(m.group(1))

nodes = {}
cur = None
rec = re.compile(r'^@(\d+)\s+(\S+)\s*(.*)$')
for line in open(raw_path, encoding='latin-1'):
    m = rec.match(line)
    if m:
        cur = [m.group(2), m.group(3)]
        nodes[int(m.group(1))] = cur
    elif cur is not None:
        cur[1] += ' ' + line.strip()

def field(body, key):
    m = re.search(r'\b' + key + r':\s*@(\d+)', body)
    return int(m.group(1)) if m else None

def strg(i):
    n = nodes.get(i)
    if not n:
        return None
    m = re.search(r'strg:\s*(\S+)', n[1])
    return m.group(1) if m else None

namespaces = {}
for i, (k, b) in nodes.items():
    if k == 'namespace_decl':
        namespaces[i] = strg(field(b, 'name'))
# The global namespace is the namespace_decl named `::`; its members' scope is
# the translation_unit_decl it is attached to, so both ids stand for it.
global_ids = {i for i, n in namespaces.items() if n == '::'}
for i, (k, b) in nodes.items():
    if k == 'translation_unit_decl':
        global_ids.add(i)
runtime_ids = {i for i, n in namespaces.items() if n == 'nested_array_utilities'}
# the namespaces declared at global scope (std, blade_rt, ...): a declaration
# at namespace scope spelled like one redeclares it
global_namespaces = {n for i, n in namespaces.items()
                     if n and ident.match(n) and field(nodes[i][1], 'scpe') in global_ids}

global_functions, ns_functions, global_values, runtime_names = set(), set(), set(), set()
# ADL brings in the namespaces ASSOCIATED with an argument type: the emitted
# argument types are Blade's own (nested_array_utilities, covered by the
# using-directive rule) and the standard library's (std::tuple / function /
# complex / string / vector), whose associated namespaces are std and the
# namespaces nested in it, and __gnu_cxx (libstdc++ iterator / allocator types).
def root_of(i, fuel=64):
    while fuel > 0:
        s = field(nodes[i][1], 'scpe')
        if s is None or s in global_ids or s not in namespaces:
            return namespaces.get(i)
        i, fuel = s, fuel - 1
    return None
adl_ids = {i for i in namespaces if root_of(i) in ('std', '__gnu_cxx')}
for i, (k, b) in nodes.items():
    if k not in ('function_decl', 'template_decl', 'var_decl', 'type_decl', 'const_decl'):
        continue
    s = field(b, 'scpe')
    nm = strg(field(b, 'name'))
    if not nm or not ident.match(nm):
        continue
    if k in ('function_decl', 'template_decl'):
        if s in global_ids:
            global_functions.add(nm)
        elif s in adl_ids:
            ns_functions.add(nm)
    if s in global_ids and k in ('var_decl', 'type_decl', 'const_decl', 'template_decl'):
        global_values.add(nm)
    if s in runtime_ids:
        runtime_names.add(nm)

def section(name, doc, names):
    out = [f'[{name}] {doc}']
    names = sorted(names)
    for k in range(0, len(names), 16):
        out.append(' '.join(names[k:k + 16]))
    return '\n'.join(out)

print('# GENERATED by tools/cpp-reserved-names/generate.sh -- do not edit by hand.')
print(f'# Compiler: {compiler}')
print(f'# Headers that did not preprocess on the generating box (not covered):{skipped or " none"}')
print('# The identifiers the emitted C++ translation unit declares that a USER spelling must not take')
print('# (gap G252; read by CodeGenState.cppReservedNames, an embedded resource of Blade.dll).')
print(section('objectMacros', 'object-like macros: every use of the token expands', obj_macros))
print(section('functionMacros', 'function-like macros: a use expands when ( follows', fn_macros - obj_macros))
print(section('globalFunctions', 'functions and function templates of the GLOBAL namespace (ordinary lookup meets them)', global_functions))
print(section('namespaceFunctions', 'functions and function templates of std and __gnu_cxx and the namespaces nested in them (the ADL candidates of a standard-library argument type)', ns_functions))
print(section('globalValueNames', 'types, variables and templates of the GLOBAL namespace', global_values))
print(section('namespaceNames', 'namespaces declared at global scope', global_namespaces))
print(section('runtimeNamespaceNames', 'every name of nested_array_utilities (hoisted by its using-directive)', runtime_names))