"""Item 4 (anti_g default): EVERY antisym bench session per mirror (w3 = anti_g 1, w3g = anti_g 0 auto),
per regime: each session's blade-cpp / blade-llvm medians, then the pooled-sample medians and an
unpaired bootstrap CI of median(w3g)/median(w3) over the pooled timed rounds (4000 resamples).
Three interleaved sessions per arm were run; the pooled CI is the verdict, each session a row."""
import glob, json, os, random, statistics

rng = random.Random(20261020)


def samples(arm):
    return [s['time_s'] for s in arm['samples'] if s['kind'] == 'round' and s['ok'] and not s.get('excursion_dropped')]


def boot(a, b, n=4000):
    rs = []
    for _ in range(n):
        ra = [a[rng.randrange(len(a))] for _ in a]
        rb = [b[rng.randrange(len(b))] for _ in b]
        rs.append(statistics.median(rb) / statistics.median(ra))
    rs.sort()
    return rs[int(.025 * n)], rs[int(.975 * n) - 1]


def sessions(m):
    out = []
    for f in sorted(glob.glob(r'C:\bt_r2ab\%s\bench\results\*\session-*\session.json' % m)):
        d = json.load(open(f, encoding='utf8'))
        a = d['argv']
        # run 1 (before 20:12:35) ran beside a stray single-core process: excluded
        if 'bench' in a and a[a.index('--kernels') + 1] == 'antisym' and os.path.basename(os.path.dirname(f)) >= 'session-201235':
            out.append((os.path.basename(os.path.dirname(f)), d))
    return out


rows = ['# anti_g re-measure (generated by antig.py): w3 = anti_g 1 (default), w3g = anti_g 0 (auto)\n',
        '| regime | arm | mirror | session | n | median ms | block | flags |', '|---|---|---|---|---|---|---|---|']
pooled = {}
for m in ('w3', 'w3g'):
    for name, d in sessions(m):
        for b in d['blocks']:
            reg = b['regime']
            for arm in ('blade-cpp', 'blade-llvm', 'gfortran-expert', 'ifx-expert'):
                a = b['arms'].get(arm)
                if a is None or a['status'] != 'ok':
                    continue
                s = samples(a)
                rows.append('| %s | %s | %s | %s | %d | %.4g | %s | %s |' % (
                    reg, arm, m, name, len(s), statistics.median(s) * 1e3,
                    'indicative' if b['suppressed'] else 'live', '; '.join(b['flags']) or '-'))
                pooled.setdefault((reg, arm, m), []).extend(s)
rows.append('\n| regime | arm | w3 pooled n | w3 median ms | w3g pooled n | w3g median ms | w3g/w3 [95% CI] |')
rows.append('|---|---|---|---|---|---|---|')
for (reg, arm, m), s in sorted(pooled.items()):
    if m != 'w3' or (reg, arm, 'w3g') not in pooled:
        continue
    t = pooled[(reg, arm, 'w3g')]
    lo, hi = boot(s, t)
    rows.append('| %s | %s | %d | %.4g | %d | %.4g | %.3f [%.3f, %.3f] |' % (
        reg, arm, len(s), statistics.median(s) * 1e3, len(t), statistics.median(t) * 1e3,
        statistics.median(t) / statistics.median(s), lo, hi))
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'antig.md')
open(out, 'w', encoding='utf8').write('\n'.join(rows))
print('\n'.join(rows))
