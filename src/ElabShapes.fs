/// The ONE static-shape oracle of the domain elaborators (deep-review #62).
///
/// The math, spectra, sgs and ppl elaborators run BEFORE type inference (TypeCheck.typeCheck runs ML, sgs, PPL, math,
/// rand, spectra, display in that order, each an AST rewrite), and each one specializes a generated routine to the
/// extents of its array operands, so each needs an operand's shape at compile time. They used to carry four copies of
/// one lookup that read only DECLARED shapes, so the result of one elaborated call could not feed the next
/// (`m.matmul(S, Q)` with `Q` from `m.eigh`, `sp.ifft(sp.fft(x))`). This module answers "what is the static shape of
/// this operand" for all of them, from, in order:
///   1. a declared annotation -- a let, a parameter, a function's return type, an ascription `(e : Array<...>)`;
///   2. a form whose shape is syntactic -- an array literal, a numeric cast of a shaped value (`Float64(x)`), a
///      static range `lo..hi` / `range<I>`, a computed range map `method_for(range<..>) <@> k [|> compute]`;
///   3. the RESULT of an elaborated call -- a domain op still in surface form (`m.svd(A)`, answered by the domain
///      that owns it through `registerDomain`, so the answer does not depend on which pass runs first), a call of a
///      routine an earlier pass generated (its signature), or an intrinsic marker (`registerMarker`);
///   4. a plain alias, a destructured tuple component, a tuple projection `t[0]`, a block's value, or a value
///      imported from a user module (`import Lib as L` / `from Lib import A`) -- of any of those.
/// It never infers a function's return from its body, and an un-annotated generic parameter (`T^2`) has no static
/// shape: those refusals are legitimate and the messages built here name the annotation as the fix.
///
/// Element types: a declared one is reported as written; an array literal's is its DEFAULT width (`let a = [1.0, 2.0]`
/// is Float32, formalism 2.4) unless the literal is an argument the elaborator ascribes (`ascribeFloatLiteral`, which
/// gives it the Float64 its routine takes); a computed map's is the checker's to infer (`ElemComputed`).
module Blade.ElabShapes

open System.Collections.Concurrent
open Blade.Ast
open Blade.StaticEval

// Shapes

/// What is known about an array's element type.
type ElemInfo =
    /// Written (an annotation / ascription / generated signature / cast): the TypeExpr as written (aliases unresolved).
    | ElemDeclared of TypeExpr
    /// A literal's DEFAULT width (Float32 / Int32) and the note that explains it in a message.
    | ElemDefault of TypeExpr * string
    /// The axes are known, the element is not (cells that are computed expressions, an integer range).
    | ElemUnknown of string
    /// A computed range map (`method_for(range<..>) <@> k`): the axes are its iteration space, the element is the
    /// kernel's, which only the checker infers. (The PPL formers read it as Float64, their documented assumption.)
    | ElemComputed of string

type ArrayShape = {
    Elem: ElemInfo
    /// The index types as written (aliases NOT expanded: provenance is part of the type).
    Idxs: TypeExpr list
    /// Each axis's static extent, resolved in the context that declared it (None: not static, or not a plain axis).
    Extents: int option list
    /// The element type is a USER declaration (an annotation, an ascription, an annotated parameter or return type) --
    /// the elements the domain ops took before #62, judged by the checker as they always were. False for everything
    /// this oracle infers (a generated routine's signature, a marker's result, a cast, a literal, a range, a map).
    UserElem: bool
}

type ValShape =
    | VArray of ArrayShape
    | VTuple of Shaped list
    | VScalar

/// Ok = the shape; Error = WHY there is no static shape (a clause, not a sentence: callers wrap it).
and Shaped = Result<ValShape, string>

/// A routine generated by the running pass (not yet spliced into the declaration list).
type GenInfo = { Ret: TypeExpr option; Label: string }

/// A user module as an importer sees it.
type ModuleView = {
    Values: string -> Shaped option
    Funcs: string -> Shaped option
}

/// Reference identity on an (expression, scope) pair: the memo key of `shapeOf`.
type ShapeMemoComparer() =
    interface System.Collections.Generic.IEqualityComparer<struct (obj * obj)> with
        member _.Equals(struct (a1, b1), struct (a2, b2)) = obj.ReferenceEquals (a1, a2) && obj.ReferenceEquals (b1, b2)
        member _.GetHashCode(struct (a, b)) =
            System.Runtime.CompilerServices.RuntimeHelpers.GetHashCode a * 31
            + System.Runtime.CompilerServices.RuntimeHelpers.GetHashCode b

type Env = {
    /// `shapeOf` results by (expression, scope) identity. A domain's scratch elaboration shapes an operand, then shapes
    /// the op's result -- which shapes the same operand again (a marker's answer); without the memo a chain of nested
    /// calls costs 2^depth. One memo per environment: `withGen` (a scratch overlay) starts its own.
    Memo: System.Collections.Generic.Dictionary<struct (obj * obj), Result<ValShape, string>>
    Aliases: Map<string, TypeExpr>
    Statics: StaticEnv
    /// Module-level value bindings (annotated or inferred) plus selectively imported values; None = no such binding.
    Values: string -> Shaped option
    /// Module-level functions: the declared return's shape (Error when it is not annotated); None = no such function.
    Funcs: string -> Shaped option
    /// The running pass's generated routines.
    Gen: string -> GenInfo option
    /// Import alias -> domain path (`import math as m` -> "m" -> "math"), for every REGISTERED domain imported here.
    Domains: Map<string, string>
    /// Import alias -> user module.
    Modules: Map<string, ModuleView>
}

/// The lexical scope: parameters and local lets in force. Every binder is recorded, shaped or not, so an unshaped
/// local SHADOWS an outer name instead of silently falling through to it.
type Scope = Map<string, Shaped>

let newShapeMemo () = System.Collections.Generic.Dictionary<struct (obj * obj), Shaped>(ShapeMemoComparer())

// The domain registry

/// A domain's answer for one of its ops in SURFACE form: `env scope op args` -> the op's result shape.
type DomainShapeFn = Env -> Scope -> string -> Expr list -> Shaped
/// An intrinsic marker's answer (`__math_matmul(A, B)`): `env scope args` -> its result shape.
type MarkerShapeFn = Env -> Scope -> Expr list -> Shaped

let private domains = ConcurrentDictionary<string, DomainShapeFn>()
let private markers = ConcurrentDictionary<string, string * MarkerShapeFn>()

/// Register a domain (`import <path>`) whose surface ops this module may be asked about. Idempotent.
let registerDomain (path: string) (fn: DomainShapeFn) = domains[path] <- fn
/// Register an intrinsic marker an elaborator rewrites to, with the label a message quotes for its result. Idempotent.
let registerMarker (name: string) (label: string) (fn: MarkerShapeFn) = markers[name] <- (label, fn)

// Type resolution

/// Resolve top-level type aliases, following every link of an ACYCLIC chain (a visited set, not a fuel bound: a long
/// chain is resolved completely, a cyclic one stops where it closes). TyBounded is TRANSPARENT here, for diagnostic
/// ORDER only: a bound on an aggregate is the checker's rejection to make (BL4003, TypeCheck.boundedAggregateError), and
/// this pass must not pre-empt it with "no static array shape" about an annotation that plainly declares one. A bound on
/// a SCALAR still resolves to a non-array.
let resolveTop (aliases: Map<string, TypeExpr>) (ty: TypeExpr) : TypeExpr =
    let rec go (seen: Set<string>) (ty: TypeExpr) =
        match ty with
        | TyNamed (n, []) when not (Set.contains n seen) ->
            match Map.tryFind n aliases with
            | Some body -> go (Set.add n seen) body
            | None -> ty
        | TyBounded (baseTy, _, _) -> go seen baseTy
        | _ -> ty
    go Set.empty ty

/// The free variable names of an expression a type carries (an extent), or None when it holds a form this walk does not
/// follow (then nothing is assumed about which names it reads).
let rec private extentNames (e: Expr) : Set<string> option =
    let all (es: Expr list) =
        es |> List.fold (fun acc x -> match acc, extentNames x with Some a, Some b -> Some (Set.union a b) | _ -> None) (Some Set.empty)
    match e.Kind with
    | ExprKind.ExprLit _ -> Some Set.empty
    | ExprKind.ExprVar n -> Some (Set.singleton n)
    | ExprKind.ExprBinOp (_, _, l, r) -> all [ l; r ]
    | ExprKind.ExprUnaryOp (_, x) -> extentNames x
    | ExprKind.ExprApp (f, args) -> all (f :: args)
    | ExprKind.ExprTuple es | ExprKind.ExprArrayLit es -> all es
    | ExprKind.ExprTyped (x, _) -> extentNames x
    | ExprKind.ExprIf (c, a, b) -> all [ c; a; b ]
    | ExprKind.ExprExtents x -> extentNames x
    | _ -> None

/// An index TypeExpr's static extent, following alias chains (cycle-safe). A name that is not a source alias is a
/// provider axis path (registered by TypeEnv during checking), whose extent comes from the store's metadata. A bound in
/// an alias body does not change the extent. `shadowed` are the LOCAL binders in force where the type is written: an
/// extent expression naming one is not the module static of that name (`function f(n: Int64) = .. Idx<n> ..`, a local
/// `let n = 8`), so it has no static extent here -- evaluating it against the module statics would specialize to the
/// wrong extent.
let private staticIn (statics: StaticEnv) (shadowed: Set<string>) (e: Expr) : StaticValue option =
    let clean =
        match extentNames e with
        | Some names -> Set.isEmpty (Set.intersect names shadowed)
        | None -> Set.isEmpty shadowed
    if not clean then None
    else
        match evalExpr statics maxSteps e with
        | Ok v -> Some v
        | Error _ -> None

/// A static integer, unless the expression names a local binder (see resolveExtentIn).
let staticIntIn (statics: StaticEnv) (shadowed: Set<string>) (e: Expr) : int option =
    match staticIn statics shadowed e with
    | Some (SVInt n) -> Some (int n)
    | _ -> None

let resolveExtentIn (aliases: Map<string, TypeExpr>) (statics: StaticEnv) (shadowed: Set<string>) (ty: TypeExpr) : int option =
    // `sh`: the binders in force where the expression at hand was WRITTEN. An alias body was written at module level,
    // so following an alias resets it: `type I = Idx<n>` is the static `n` whatever a caller's locals are called.
    let rec go (seen: Set<string>) (sh: Set<string>) (ty: TypeExpr) =
        match ty with
        | TyIdx extent -> staticIntIn statics sh extent
        | TyNamed (name, []) ->
            if Set.contains name seen then None
            else
                match Map.tryFind name aliases with
                | Some body -> go (Set.add name seen) Set.empty body
                | None -> providerIndexExtent statics name
        | TyBounded (inner, _, _) -> go seen sh inner
        // An irreps axis (an ml op's result, IrrepsIdx<spec>) is one flat axis of total_dim(spec) cells -- the ml sizing
        // builtin, registered with the static evaluator by MLStatics.install before any elaboration -- and an array over
        // it is accepted where a plain Idx<n> array of that extent is (the generated routines' parameters).
        | TyIrrepsIdx spec -> staticIntIn statics sh (syn (ExprApp (syn (ExprVar "__ml_stat_total_dim"), [ spec ])))
        | _ -> None
    go Set.empty shadowed ty

/// `resolveExtentIn` at module level (no local binder in force).
let resolveExtent (aliases: Map<string, TypeExpr>) (statics: StaticEnv) (ty: TypeExpr) : int option =
    resolveExtentIn aliases statics Set.empty ty

/// The module's top-level type aliases.
let collectAliases (decls: Located<Decl> list) : Map<string, TypeExpr> =
    decls |> List.fold (fun acc d ->
        match d.Value with
        | DeclType (TyDeclAlias (name, _, body)) -> Map.add name body acc
        | _ -> acc) Map.empty

let private scalarNames =
    set [ "Float64"; "Float32"; "Float"; "Double"; "Int64"; "Int32"; "Int"; "Bool"; "Complex128"; "Complex64"; "String"; "Char" ]

/// The shape a written type denotes, with the local binders `shadowed` in force where it is written.
let rec typeShapeIn (aliases: Map<string, TypeExpr>) (statics: StaticEnv) (shadowed: Set<string>) (user: bool) (ty: TypeExpr) : Shaped =
    // Follow a whole-type alias to its body; the body was written at module level, so its extents see no local binder.
    let rec strip (seen: Set<string>) (sh: Set<string>) (ty: TypeExpr) =
        match ty with
        | TyNamed (n, []) when not (Set.contains n seen) && Map.containsKey n aliases -> strip (Set.add n seen) Set.empty aliases[n]
        | TyBounded (baseTy, _, _) -> strip seen sh baseTy
        | _ -> (ty, sh)
    let (ty, shadowed) = strip Set.empty shadowed ty
    match ty with
    | TyArray (elem, idxs) ->
        // The element AS WRITTEN (an alias stays an alias: the PPL formers decide their route from it, and emission must
        // not move); a consumer that classifies an element resolves it (resolveTop) itself.
        Ok (VArray { Elem = ElemDeclared elem
                     Idxs = idxs
                     Extents = idxs |> List.map (resolveExtentIn aliases statics shadowed)
                     UserElem = user })
    | TyTuple ts -> Ok (VTuple (ts |> List.map (typeShapeIn aliases statics shadowed user)))
    | TyInt32 | TyInt64 | TyFloat32 | TyFloat64 | TyComplex64 | TyComplex128 | TyBool | TyString | TyChar | TyUnit ->
        Ok VScalar
    | TyNamed (n, _) when Set.contains n scalarNames -> Ok VScalar
    | TyVar (_, Some k) when k > 0 ->
        Error "its declared type is a generic array type (T^r), which fixes no element type or extents"
    | TyAbstractArray _ ->
        Error "its declared type is an abstract array type (T^r), which fixes no extents"
    | _ -> Error "its declared type is not a concrete Array<...> type"

/// `typeShapeIn` at module level.
let typeShape (aliases: Map<string, TypeExpr>) (statics: StaticEnv) (user: bool) (ty: TypeExpr) : Shaped =
    typeShapeIn aliases statics Set.empty user ty

let private scopeNames (scope: Map<string, 'a>) : Set<string> = scope |> Map.toSeq |> Seq.map fst |> Set.ofSeq

/// Is this (declared) element type a scalar -- so the array's axes are all of its axes? An array-of-arrays element
/// (`Array<Array<..> like I>`) is not, and nor is anything this pass cannot classify.
let private isScalarElem (aliases: Map<string, TypeExpr>) (ty: TypeExpr) =
    match resolveTop aliases ty with
    | TyInt32 | TyInt64 | TyFloat32 | TyFloat64 | TyComplex64 | TyComplex128 | TyBool | TyString | TyChar -> true
    | TyNamed (n, _) -> Set.contains n scalarNames
    | _ -> false

/// A USER-written type (annotation, ascription, parameter) in the scope where it is written.
let private envTypeShape (env: Env) (scope: Map<string, Shaped>) (ty: TypeExpr) =
    typeShapeIn env.Aliases env.Statics (scopeNames scope) true ty

// Syntactic shapes

let private isFloatLeaf (e: Expr) =
    match e.Kind with
    | ExprKind.ExprLit (LitFloat _) -> true
    | ExprKind.ExprUnaryOp (OpNeg, { Kind = ExprKind.ExprLit (LitFloat _) }) -> true
    | _ -> false

let private isIntLeaf (e: Expr) =
    match e.Kind with
    | ExprKind.ExprLit (LitInt _) -> true
    | AstNegIntLit _ -> true
    | _ -> false

/// A rectangular array literal's extents (outermost first) and its leaves; None when ragged or empty.
let rec private literalDims (e: Expr) : (int list * Expr list) option =
    match e.Kind with
    | ExprKind.ExprArrayLit [] -> None
    | ExprKind.ExprArrayLit es ->
        let subs = es |> List.map (fun x -> match x.Kind with ExprKind.ExprArrayLit _ -> literalDims x | _ -> Some ([], [x]))
        if subs |> List.exists Option.isNone then None
        else
            let subs = subs |> List.map Option.get
            let inner = fst subs.Head
            if subs |> List.forall (fun (d, _) -> d = inner) then
                Some (es.Length :: inner, subs |> List.collect snd)
            else None
    | _ -> None

let private litIdx (n: int) = TyIdx (syn (ExprLit (LitInt (int64 n))))

let private literalShape (e: Expr) : Shaped =
    match literalDims e with
    | None -> Error "it is an empty or ragged array literal"
    | Some (dims, leaves) ->
        // Only literal cells are known to be scalars: a computed cell may itself be an array (`[a, a]` is rank 2), so
        // the literal's nesting alone does not fix its shape.
        // The default width is the checker's own rule (Types.LiteralDefaults, formalism 2.4: Float64 only outside
        // Float32's finite range at either end, Int64 only past Int32's), so `[1e100, 2e100]` is a Float64 literal.
        let floatOf (x: Expr) =
            match x.Kind with
            | ExprKind.ExprLit (LitFloat f) -> f
            | ExprKind.ExprUnaryOp (OpNeg, { Kind = ExprKind.ExprLit (LitFloat f) }) -> -f
            | _ -> 0.0
        let intOf (x: Expr) =
            match x.Kind with
            | ExprKind.ExprLit (LitInt n) -> n
            | AstNegIntLit n -> -n
            | _ -> 0L
        let shaped elem = Ok (VArray { Elem = elem; Idxs = dims |> List.map litIdx; Extents = dims |> List.map Some; UserElem = false })
        if leaves |> List.forall isFloatLeaf then
            if leaves |> List.exists (fun x -> Blade.Types.LiteralDefaults.floatDefault (floatOf x) = Blade.Types.ETFloat64) then
                shaped (ElemDeclared (TyNamed ("Float64", [])))
            else
                shaped (ElemDefault (TyNamed ("Float32", []), "an unannotated float array literal defaults to Float32 elements"))
        elif leaves |> List.forall isIntLeaf then
            if leaves |> List.exists (fun x -> Blade.Types.LiteralDefaults.intDefault (intOf x) = Blade.Types.ETInt64) then
                shaped (ElemDeclared (TyNamed ("Int64", [])))
            else
                shaped (ElemDefault (TyNamed ("Int32", []), "an unannotated integer array literal defaults to Int32 elements"))
        else Error "its cells are computed expressions, whose shape and element type are not statically known"

/// An inline array-literal ARGUMENT of float literals (as written -- an elaborator applies this to the operands of an
/// op whose generated routine has a Float64 parameter), ascribed `Array<Float64 like Idx<d0>, ...>`: an argument's width
/// is fixed by its context (formalism 2.4), and every routine the elaborators generate takes Float64 -- the ascription
/// states that context for the intrinsic markers too (`__math_matmul` has no parameter to adapt to). Anything else is
/// returned unchanged.
let ascribeFloatLiteral (e: Expr) : Expr =
    match e.Kind with
    | ExprKind.ExprArrayLit _ ->
        match literalDims e with
        | Some (dims, leaves) when leaves |> List.forall isFloatLeaf ->
            inheritSpan e (ExprTyped (e, TyArray (TyNamed ("Float64", []), dims |> List.map litIdx)))
        | _ -> e
    | _ -> e

/// Shape inference for COMPUTED arrays: `method_for(range<...>) <@> kernel [|> compute]` has no declared TyArray, but
/// its iteration space IS its shape -- one axis per range slot, halo slots shrunk to their interior (interior = n - (hi
/// - lo)). Returns the axes; None when a slot is unresolvable. (Moved from the PPL elaborator, which assumes Float64.)
let computedAxes (aliases: Map<string, TypeExpr>) (statics: StaticEnv) (shadowed: Set<string>) (value: Expr) : TypeExpr list option =
    // Interior extents of one halo slot: flat offsets -> [n - reach]; nested per-axis form -> one shrunk extent per axis.
    let haloExtents (innerTy: TypeExpr) (offsetsExpr: Expr) : int list option =
        resolveExtentIn aliases statics shadowed innerTy |> Option.bind (fun n ->
            let asInt = function SVInt v -> Some (int v) | _ -> None
            let shrunk (offs: int list) =
                if List.isEmpty offs then None
                else
                    let lo = min 0 (List.min offs)
                    let hi = max 0 (List.max offs)
                    Some (n - (hi - lo))
            match staticIn statics shadowed offsetsExpr with
            | Some (SVInt v) -> shrunk [int v] |> Option.map List.singleton
            | Some (SVTuple vs) when not vs.IsEmpty ->
                let flat = vs |> List.map asInt
                if List.forall Option.isSome flat then
                    // Flat form: one axis.
                    shrunk (flat |> List.map Option.get) |> Option.map List.singleton
                else
                    // Nested per-axis form: every entry a non-empty int array.
                    let perAxis =
                        vs |> List.map (function
                            | SVTuple xs ->
                                let os = xs |> List.map asInt
                                if List.forall Option.isSome os && not os.IsEmpty
                                then shrunk (os |> List.map Option.get) else None
                            | _ -> None)
                    if List.forall Option.isSome perAxis
                    then Some (perAxis |> List.map Option.get) else None
            | _ -> None)
    let slotExtents (ty: TypeExpr) : int list option =
        match ty with
        | TyHalo (inner, offs) -> haloExtents inner offs
        | _ -> resolveExtentIn aliases statics shadowed ty |> Option.map List.singleton
    // Unwrap |> compute and walk down the <@> application to the loop source.
    let rec sourceOf (e: Expr) : Expr option =
        match e.Kind with
        | ExprKind.ExprCompute inner -> sourceOf inner
        | ExprKind.ExprBinOp (_, OpApply, l, _) -> sourceOf l
        | ExprKind.ExprMethodFor [src] -> Some src
        | _ -> None
    sourceOf value |> Option.bind (fun src ->
        let slots =
            match src.Kind with
            | ExprKind.ExprRange idxTys -> Some idxTys
            | ExprKind.ExprHalo (inner, offs) -> Some [TyHalo (inner, offs)]
            | _ -> None
        slots |> Option.bind (fun tys ->
            if List.isEmpty tys then None else
            let exts = tys |> List.map slotExtents
            if List.forall Option.isSome exts then
                Some (exts |> List.collect Option.get |> List.map litIdx)
            else None))

/// Is this application the deferred/computed map form `computedAxes` reads?
[<TailCall>]
let rec private isMapForm (e: Expr) =
    match e.Kind with
    | ExprKind.ExprCompute inner -> isMapForm inner
    // A chain of applications (`method_for(range<..>) <@> f <@> g`) is followed down to its source, as computedAxes does.
    | ExprKind.ExprBinOp (_, OpApply, { Kind = ExprKind.ExprMethodFor _ }, _) -> true
    | ExprKind.ExprBinOp (_, OpApply, l, _) -> isMapForm l
    | _ -> false

// Labels (what a message calls an operand -- never an internal `__` name)

let private castNames = set [ "Float64"; "Float32"; "Int64"; "Int32"; "Complex128"; "Complex64" ]

let private domainOfGenerated (name: string) =
    if name.StartsWith "__math_" then "math"
    elif name.StartsWith "__spectra_" then "spectra"
    elif name.StartsWith "__sgs_" then "sgs"
    elif name.StartsWith "__ml_" then "ml"
    elif name.StartsWith "__ppl_" then "ppl"
    else ""

let rec labelOf (env: Env) (e: Expr) : string =
    match e.Kind with
    | ExprKind.ExprVar n when n.StartsWith "__" -> "an internal value"
    | ExprKind.ExprVar n -> $"'{n}'"
    | ExprKind.ExprTyped _ -> "the ascribed expression"
    | ExprKind.ExprArrayLit _ -> "the array literal"
    | ExprKind.ExprField ({ Kind = ExprKind.ExprVar a }, x) -> $"'{a}.{x}'"
    | ExprKind.ExprApp ({ Kind = ExprKind.ExprField ({ Kind = ExprKind.ExprVar a }, op) }, _) -> $"the result of '{a}.{op}'"
    | ExprKind.ExprApp ({ Kind = ExprKind.ExprVar f }, [ inner ]) when Set.contains f castNames ->
        $"the {f} cast of {labelOf env inner}"
    | ExprKind.ExprApp ({ Kind = ExprKind.ExprVar f }, _) ->
        match markers.TryGetValue f with
        | true, (label, _) -> label
        | _ ->
            match env.Gen f with
            | Some g -> g.Label
            | None when f.StartsWith "__" ->
                let d = domainOfGenerated f
                if d = "" then "the result of an internal call" else $"the result of a nested {d} call"
            | None -> $"the result of '{f}'"
    | ExprKind.ExprTupleIndex (t, { Kind = ExprKind.ExprLit (LitInt i) }) -> $"component {i} of {labelOf env t}"
    | _ -> "the argument"

// The shape of an expression

let private notFollowed =
    "it is bound to an expression whose shape is not static here (followed: annotations, array literals, casts, static ranges, computed range maps, elaborated calls, and aliases, destructured components and projections of those)"

/// Bind a pattern against a value's shape: every variable it binds enters the scope (an unshaped one as its reason).
let rec bindShape (sc: Scope) (pat: Pattern) (shape: Shaped) : Scope =
    match pat.Kind with
    | PatternKind.PatVar n -> Map.add n shape sc
    | PatternKind.PatWildcard | PatternKind.PatLit _ -> sc
    | PatternKind.PatTuple ps ->
        let comps =
            match shape with
            | Ok (VTuple cs) when cs.Length = ps.Length -> cs
            | Ok (VTuple cs) -> List.replicate ps.Length (Error $"it destructures a {cs.Length}-component tuple into {ps.Length} names")
            | Ok _ -> List.replicate ps.Length (Error "it destructures a value that is not a tuple")
            | Error why -> List.replicate ps.Length (Error why)
        List.fold2 bindShape sc ps comps
    | PatternKind.PatGuarded (p, _) -> bindShape sc p shape
    | PatternKind.PatTyped (p, _) -> bindShape sc p shape
    | PatternKind.PatCons (h, t) ->
        let why = Error "it is bound by a pattern the shape analysis does not follow"
        bindShape (bindShape sc h why) t why
    | PatternKind.PatStruct (_, fields) ->
        fields |> List.fold (fun acc (_, p) -> bindShape acc p (Error "it is bound by a struct pattern")) sc
    | PatternKind.PatVariant (_, Some p) -> bindShape sc p (Error "it is bound by a variant pattern")
    | PatternKind.PatVariant (_, None) -> sc

/// Every name a pattern binds, recorded as unshaped (match arms, loop variables): they shadow outer arrays.
let shadowPattern (sc: Scope) (pat: Pattern) (why: string) : Scope = bindShape sc pat (Error why)

let rec shapeOf (env: Env) (scope: Scope) (e: Expr) : Shaped =
    let key = struct (box e, box scope)
    match env.Memo.TryGetValue key with
    | true, s -> s
    | _ ->
        let s = shapeOfUncached env scope e
        env.Memo[key] <- s
        s

and shapeOfUncached (env: Env) (scope: Scope) (e: Expr) : Shaped =
    let lookupName (n: string) : Shaped =
        match Map.tryFind n scope with
        | Some s -> s
        | None ->
            match env.Values n with
            | Some s -> s
            | None -> Error "no array binding of that name is in scope here"
    try
        match e.Kind with
        | ExprKind.ExprVar n -> lookupName n
        | ExprKind.ExprTyped (_, ty) ->
            match envTypeShape env scope ty with
            | Ok (VArray _) as s -> s
            | Ok (VTuple _) as s -> s
            | _ -> Error "the ascription does not name an array type (Array<Float64 like Idx<...>, ...>)"
        | ExprKind.ExprArrayLit _ -> literalShape e
        | ExprKind.ExprLit _ -> Ok VScalar
        | ExprKind.ExprTuple es -> Ok (VTuple (es |> List.map (shapeOf env scope)))
        // A domain op in surface form: its owner answers, whichever pass runs first.
        | ExprKind.ExprApp ({ Kind = ExprKind.ExprField ({ Kind = ExprKind.ExprVar a }, op) }, args)
                when Map.containsKey a env.Domains && not (Map.containsKey a scope) ->
            match domains.TryGetValue env.Domains[a] with
            | true, fn -> fn env scope op args
            | _ -> Error "its domain is not registered"
        // A user module's function / value.
        | ExprKind.ExprApp ({ Kind = ExprKind.ExprField ({ Kind = ExprKind.ExprVar a }, f) }, _)
                when Map.containsKey a env.Modules && not (Map.containsKey a scope) ->
            match env.Modules[a].Funcs f with
            | Some s -> s
            | None ->
                match env.Modules[a].Values f with
                | Some _ -> Error "it is an index read of an imported array (a partial read has no static shape here)"
                | None -> Error $"module '{a}' exports no function '{f}' with an annotated array return type"
        | ExprKind.ExprField ({ Kind = ExprKind.ExprVar a }, x) when Map.containsKey a env.Modules && not (Map.containsKey a scope) ->
            match env.Modules[a].Values x with
            | Some s -> s
            | None -> Error $"module '{a}' exports no array binding '{x}'"
        | ExprKind.ExprApp ({ Kind = ExprKind.ExprVar f }, args) ->
            // GUARD: in Blade arrays ARE functions, so `A(i)` and `f(x)` are the same node -- a known value name is an
            // index read, never a call.
            if Map.containsKey f scope || (env.Values f).IsSome then
                Error "it applies a value (an index read, or a let-bound function), which has no static shape here"
            else
            match markers.TryGetValue f with
            | true, (_, fn) -> fn env scope args
            | _ ->
            match env.Funcs f with
            | Some s -> s
            | None ->
            match env.Gen f with
            | Some { Ret = Some ty } -> typeShapeIn env.Aliases env.Statics Set.empty false ty
            | Some { Ret = None } -> Error "the generated routine declares no return type"
            | None ->
            match args with
            | [ inner ] when Set.contains f castNames ->
                // A numeric cast converts the element only (shape, symmetry and units kept). It fixes the element's WIDTH,
                // not its scalarity: over cells whose element is not known to be a scalar (computed cells, a computed
                // map's kernel result -- either may be an array, so the axes seen here may not be all of them) the cast
                // claims nothing more.
                match shapeOf env scope inner with
                | Ok (VArray ({ Elem = ElemDefault _ } as s)) -> Ok (VArray { s with Elem = ElemDeclared (TyNamed (f, [])); UserElem = false })
                | Ok (VArray ({ Elem = ElemDeclared t } as s)) when isScalarElem env.Aliases t ->
                    Ok (VArray { s with Elem = ElemDeclared (TyNamed (f, [])); UserElem = false })
                | Ok (VArray s) -> Ok (VArray { s with Elem = ElemUnknown "its cells are not known to be scalars"; UserElem = false })
                | Ok _ -> Error "it casts a value that is not an array"
                | Error why -> Error why
            | _ -> Error $"'{f}' is not a function with an annotated array return type"
        | ExprKind.ExprTupleIndex (t, { Kind = ExprKind.ExprLit (LitInt i) }) ->
            match shapeOf env scope t with
            | Ok (VTuple cs) when int i >= 0 && int i < cs.Length -> cs[int i]
            | Ok (VTuple cs) -> Error $"the projection [{i}] is out of range for a {cs.Length}-component tuple"
            | Ok _ -> Error "it projects a value that is not a tuple"
            | Error why -> Error why
        | ExprKind.ExprDotDot (lo, hi) ->
            // Bounds naming a local binder are not the module statics of those names (resolveExtentIn).
            let shadowed = scopeNames scope
            match staticIntIn env.Statics shadowed lo, staticIntIn env.Statics shadowed hi with
            | Some l, Some h when h >= l ->
                Ok (VArray { Elem = ElemDefault (TyNamed ("Int64", []), "a range's elements are integers"); Idxs = [ litIdx (h - l) ]
                             Extents = [ Some (h - l) ]; UserElem = false })
            | _ -> Error "it is a range whose bounds are not static here"
        | ExprKind.ExprRange idxTys when not idxTys.IsEmpty ->
            Ok (VArray { Elem = ElemDefault (TyNamed ("Int64", []), "a range's elements are index values"); Idxs = idxTys
                         Extents = idxTys |> List.map (resolveExtentIn env.Aliases env.Statics (scopeNames scope)); UserElem = false })
        | _ when isMapForm e ->
            match computedAxes env.Aliases env.Statics (scopeNames scope) e with
            | Some idxs ->
                Ok (VArray { Elem = ElemComputed "a computed map's element type is inferred later, by the type checker"
                             Idxs = idxs; Extents = idxs |> List.map (resolveExtentIn env.Aliases env.Statics (scopeNames scope)); UserElem = false })
            | None -> Error notFollowed
        | ExprKind.ExprCompute inner -> shapeOf env scope inner
        | ExprKind.ExprBlock (stmts, Some fin) ->
            let rec go (sc: Scope) (s: Stmt) =
                match s with
                | StmtSpanned (inner, _) -> go sc inner
                | StmtLet b -> bindBinding env sc b
                | StmtForIn _ | StmtExpr _ | StmtAssign _ -> sc
            shapeOf env (stmts |> List.fold go scope) fin
        | ExprKind.ExprLet (b, body) -> shapeOf env (bindBinding env scope b) body
        | _ -> Error notFollowed
    with ex -> Error $"its shape could not be determined ({ex.Message})"

/// A let binding entering the scope: its annotation if it has one, else its value's shape.
and bindBinding (env: Env) (sc: Scope) (b: Binding) : Scope =
    let shape =
        match b.Type with
        | Some ty -> envTypeShape env sc ty
        | None -> shapeOf env sc b.Value
    bindShape sc b.Pattern shape

/// A parameter / lambda binder entering the scope: annotated or not.
let bindParam (env: Env) (sc: Scope) (name: string) (ty: TypeExpr option) : Scope =
    match ty with
    | Some t -> Map.add name (envTypeShape env sc t) sc
    | None -> Map.add name (Error "it is an unannotated parameter") sc

// The query the elaborators make

/// The array shape of an op's operand, or the coded message's text: `{what}: {label} has no static array shape --
/// {why}; {steer}`. `steer` is the domain's sentence on WHY it needs the shape and how to supply one.
let arrayShape (env: Env) (scope: Scope) (what: string) (steer: string) (e: Expr) : Result<string * ArrayShape, string> =
    let label = labelOf env e
    match shapeOf env scope e with
    | Ok (VArray s) -> Ok (label, s)
    | Ok (VTuple cs) ->
        Error $"{what}: {label} is a tuple of {cs.Length} values, not an array -- destructure it (`let (a, b) = ...`) or project one component (`t[0]`)"
    | Ok VScalar -> Error $"{what}: {label} is not an array"
    | Error why -> Error $"{what}: {label} has no static array shape -- {why}; {steer}"

/// Every axis's static extent, or the message naming the operand.
let staticExtents (what: string) (label: string) (s: ArrayShape) : Result<int list, string> =
    if s.Extents |> List.forall Option.isSome then Ok (s.Extents |> List.map Option.get)
    else Error $"{what}: every axis extent of {label} must be statically known (Idx<n> directly or through aliases)"

/// Is this element Float64 (units and aliases seen through)?
let isFloat64Elem (aliases: Map<string, TypeExpr>) (ty: TypeExpr) =
    match resolveTop aliases ty with
    | TyFloat64 | TyNamed (("Float64" | "Float" | "Double"), _) -> true
    | _ -> false

/// For an op whose generated routine takes Float64 (math, sgs): the operand must be known to be Float64 -- a literal
/// defaulted to Float32, a complex spectrum, a computed map or a declared Float32 array is refused HERE, with the fix,
/// rather than reaching the checker as a mismatch against the generated routine's parameter (whose message would
/// name the routine's internal name).
let requireFloat64 (env: Env) (what: string) (label: string) (s: ArrayShape) : Result<unit, string> =
    // A USER-declared element is the op's to accept as before #62 (the checker and the generated routine judge it:
    // a Hermitian Complex128 eigh is the synthesized Jacobi with the LAPACK gate off). Only an element this oracle
    // inferred -- which no op took before -- is required to be Float64 here.
    if s.UserElem then Ok () else
    match s.Elem with
    | ElemDeclared t when isFloat64Elem env.Aliases t -> Ok ()
    | ElemDeclared _ ->
        Error $"{what}: {label} does not have Float64 elements (the op takes Float64 arrays)"
    | ElemDefault (_, note) ->
        Error $"{what}: {label} does not have Float64 elements -- {note}; annotate it (`let x: Array<Float64 like Idx<n>, ...> = ...`)"
    | ElemUnknown why | ElemComputed why ->
        Error $"{what}: the element type of {label} is not statically known ({why}); annotate it (`let x: Array<Float64 like Idx<n>, ...> = ...`)"
// Building an environment

/// Every variable a pattern binds.
let rec patternNames (p: Pattern) : string list =
    match p.Kind with
    | PatternKind.PatVar n -> [ n ]
    | PatternKind.PatTuple ps -> ps |> List.collect patternNames
    | PatternKind.PatTyped (q, _) | PatternKind.PatGuarded (q, _) -> patternNames q
    | PatternKind.PatCons (h, t) -> patternNames h @ patternNames t
    | PatternKind.PatStruct (_, fs) -> fs |> List.collect (snd >> patternNames)
    | PatternKind.PatVariant (_, Some q) -> patternNames q
    | _ -> []

let private exprOfQualified (path: QualifiedName) = String.concat "." path

/// `env` with the import aliases `off` disabled (a module-level value binding rebound those names): their calls are no
/// longer domain ops / module members. The SHAPES of values are untouched (an alias is no lexical binder), so the value
/// that took the name keeps its own shape and a static of that name stays a static. Its own memo: results differ.
let withoutAliases (env: Env) (off: Set<string>) : Env =
    if Set.isEmpty off then env
    else
        { env with
            Domains = env.Domains |> Map.filter (fun a _ -> not (Set.contains a off))
            Modules = env.Modules |> Map.filter (fun a _ -> not (Set.contains a off))
            Memo = newShapeMemo () }

/// The shape environment of one module of `program` (its declarations `decls`, as the running pass sees them), with the
/// running pass's generated routines `gen`. Module-level bindings are shaped LAZILY (and memoized): a value's shape is
/// computed the first time an elaborator asks for it, in the environment of the module that declares it.
let rec moduleEnvWith (modules: ModuleDecl list) (depth: int) (decls: Located<Decl> list) (staticsOpt: StaticEnv option)
    (gen: string -> GenInfo option) : Env =
    let aliases = collectAliases decls
    let statics =
        match staticsOpt with
        | Some s -> s
        | None ->
            match resolveStatics decls with
            | Ok (s, _) -> s
            | Error _ -> (match resolveStatics [] with Ok (s, _) -> s | Error e -> failwith e)
    // Top-level value binders, by name: the binding and the pattern position it sits at.
    let valueDecls =
        decls |> List.choose (fun d ->
            match d.Value with
            | DeclLet b | DeclStatic b -> Some b
            | _ -> None)
    let bindingOf =
        valueDecls |> List.indexed |> List.fold (fun acc (i, b) -> patternNames b.Pattern |> List.fold (fun a n -> Map.add n (i, b) a) acc) Map.empty
    // A function an elaborator GENERATED is spliced with the zero span (no source line) under a generated-routine name
    // (`__math_3`, `__spectra_1`, `__sgs_2`, `__ml_..`); a function the user wrote always has its source span, whatever
    // its name (`__math_helper` included).
    let funcDecls =
        decls |> List.choose (fun d -> match d.Value with DeclFunction fd -> Some (fd, d.Span.StartLine = 0 && domainOfGenerated fd.Name <> "") | _ -> None)
        |> List.fold (fun acc (fd, generated) -> Map.add fd.Name (fd, generated) acc) Map.empty
    let imports =
        decls |> List.choose (fun d -> match d.Value with DeclImport (path, style) -> Some (path, style) | _ -> None)
    let domainAliases =
        imports |> List.fold (fun acc (path, style) ->
            match path, style with
            | [ p ], ImportQualified aliasOpt when domains.ContainsKey p -> Map.add (defaultArg aliasOpt p) p acc
            | _ -> acc) Map.empty
    let viewOf (path: QualifiedName) : ModuleView option =
        if depth > 8 then None
        else
            modules |> List.tryFind (fun m -> m.Name = path) |> Option.map (fun m ->
                let menv = lazy (moduleEnvWith modules (depth + 1) m.Decls None (fun _ -> None))
                { ModuleView.Values = fun n -> menv.Force().Values n
                  Funcs = fun n -> menv.Force().Funcs n })
    let moduleAliases =
        imports |> List.fold (fun acc (path, style) ->
            match style with
            | ImportQualified aliasOpt when not (domains.ContainsKey (exprOfQualified path)) ->
                match viewOf path with
                | Some view -> Map.add (defaultArg aliasOpt (exprOfQualified path)) view acc
                | None -> acc
            | _ -> acc) Map.empty
    let selective =
        imports |> List.fold (fun acc (path, style) ->
            match style with
            | ImportSelective names ->
                match viewOf path with
                | Some view -> names |> List.fold (fun a n -> Map.add n view a) acc
                | None -> acc
            | _ -> acc) Map.empty
    // A module-level VALUE binding named like an import alias shadows the alias from its declaration ON (`let sp = Ops
    // { .. }` after `import spectra as sp`: a later `sp.fft(x)` is that value's field, an earlier one -- and the
    // binding's own initializer, `let sp = sp.fft(a)` -- the domain op). Each binding is shaped with the aliases the
    // value bindings BEFORE it shadow (expandDomainModule's `offRef` is the walker's twin).
    let importAliases = Set.union (domainAliases |> Map.keys |> Set.ofSeq) (moduleAliases |> Map.keys |> Set.ofSeq)
    let disabledBefore : Set<string> array =
        let acc = ResizeArray<Set<string>>()
        valueDecls |> List.fold (fun (off: Set<string>) b ->
            acc.Add off
            patternNames b.Pattern |> List.fold (fun s n -> if Set.contains n importAliases then Set.add n s else s) off) Set.empty
        |> ignore
        acc.ToArray()
    let memo = System.Collections.Generic.Dictionary<string, Shaped>()
    // The environment the lazy lookups shape values in (set once, below, before any lookup can run).
    let self : Env option ref = ref None
    let rec values (n: string) : Shaped option =
        match memo.TryGetValue n with
        | true, s -> Some s
        | _ ->
            match Map.tryFind n bindingOf with
            | Some (i, b) ->
                // Cycle guard: a name being shaped is not yet known.
                memo[n] <- Error "its shape depends on itself"
                let sc = bindBinding (withoutAliases self.Value.Value disabledBefore[i]) Map.empty b
                let s = defaultArg (Map.tryFind n sc) (Error notFollowed)
                memo[n] <- s
                Some s
            | None ->
                match Map.tryFind n selective with
                | Some view -> view.Values n
                | None -> None
    and funcs (n: string) : Shaped option =
        match Map.tryFind n funcDecls with
        | Some (fd, generated) ->
            match fd.ReturnType with
            | Some ty ->
                // A routine an earlier pass GENERATED is no user declaration; any function the user wrote is.
                match typeShape aliases statics (not generated) ty with
                | Ok VScalar -> Some (Error $"'{n}' does not return an array")
                | s -> Some s
            | None -> Some (Error $"'{n}' has no annotated return type")
        | None ->
            match Map.tryFind n selective with
            | Some view -> view.Funcs n
            | None -> None
    let env : Env =
        { Memo = newShapeMemo ()
          Aliases = aliases
          Statics = statics
          Values = values
          Funcs = funcs
          Gen = gen
          Domains = domainAliases
          Modules = moduleAliases }
    self.Value <- Some env
    env

/// The shape environment of a module: `modules` is the program's module list (for imported bindings), `decls` the
/// module's declarations as the running pass sees them, `gen` the pass's own generated routines.
let moduleEnv (modules: ModuleDecl list) (decls: Located<Decl> list) (statics: StaticEnv) (gen: string -> GenInfo option) : Env =
    moduleEnvWith modules 0 decls (Some statics) gen

/// `env` with extra generated routines layered over its own (a domain's scratch elaboration of a surface op).
let withGen (env: Env) (gen: string -> GenInfo option) : Env =
    { env with Gen = (fun n -> match gen n with Some g -> Some g | None -> env.Gen n); Memo = newShapeMemo () }

// Generated routines (fingerprint-deduped), shared by the domain elaborators

/// One pass's generated routines: `<prefix><n>` names, deduped by fingerprint, with the label a message quotes for each
/// routine's result (so no message ever shows the internal name).
type GenState = {
    Prefix: string
    mutable Counter: int
    /// fingerprint -> generated name
    mutable Made: Map<string, string>
    /// generated decls in creation order
    mutable Decls: FunctionDecl list
    mutable Labels: Map<string, string>
}

let newGenState (prefix: string) : GenState =
    { Prefix = prefix; Counter = 0; Made = Map.empty; Decls = []; Labels = Map.empty }

let fingerprint (op: string) (parts: obj) : string = sprintf "%s|%A" op parts

/// The generated routine for `key`, made on first use; `op` names it in messages ("the result of the nested `op` call").
let ensure (st: GenState) (key: string) (op: string) (make: string -> Result<FunctionDecl, string>) : Result<string, string> =
    match Map.tryFind key st.Made with
    | Some n -> Ok n
    | None ->
        st.Counter <- st.Counter + 1
        let n = $"{st.Prefix}{st.Counter}"
        make n |> Result.map (fun decl ->
            st.Made <- Map.add key n st.Made
            st.Decls <- st.Decls @ [ decl ]
            st.Labels <- Map.add n $"the result of the nested {op} call" st.Labels
            n)

/// `ensure` for a TOTAL decl builder.
let ensureT (st: GenState) (key: string) (op: string) (make: string -> FunctionDecl) : string =
    match ensure st key op (fun n -> Ok (make n)) with
    | Ok n -> n
    | Error e -> failwith e // unreachable: make is total

/// The state's routines as the environment sees them.
let genLookup (st: GenState) : string -> GenInfo option =
    fun n ->
        st.Decls |> List.tryFind (fun fd -> fd.Name = n)
        |> Option.map (fun fd -> { Ret = fd.ReturnType; Label = defaultArg (Map.tryFind n st.Labels) "the result of a nested call" })

/// One op elaboration: `st env scope op args` -> the rewritten call (args already rewritten, inner calls first).
type ElabOpFn = GenState -> Env -> Scope -> string -> Expr list -> Result<Expr, string>

/// A domain's surface-shape answer derived from its OWN elaboration: the op is elaborated in a SCRATCH state (never
/// spliced; its own name prefix) and the shape is read off the result -- a generated routine's signature or a marker's
/// registered answer. One definition of each op's shape, the one its elaboration produces.
let scratchShape (scratchPrefix: string) (elab: ElabOpFn) : DomainShapeFn =
    fun env scope op args ->
        let st = newGenState scratchPrefix
        let env' = withGen env (genLookup st)
        match elab st env' scope op args with
        | Ok e -> shapeOf env' scope e
        | Error msg -> Error $"the op itself is refused ({msg})"

// The rewrite walker (one copy for every expression-level domain elaborator)

/// Rewrite every `<alias>.<op>(args)` with alias in `aliases` through `elab`, threading the lexical shape scope:
/// parameters and lets enter it as they come into view (a let's value is rewritten FIRST, so a nested elaborated call is
/// elaborated before the call that consumes it, and the binder's shape is its rewritten value's). Every constructor
/// holding a sub-expression is walked, and the catch-all wildcard is deliberately absent, so an unhandled case is an
/// FS0025 build warning rather than a qualified call surviving unrewritten.
let rec rewriteOps (st: GenState) (env: Env) (aliases: Set<string>) (elab: ElabOpFn) (scope: Scope) (e: Expr)
    : Result<Expr, string> =
    let r = rewriteOps st env aliases elab scope
    // Same walk under an EXTENDED lexical scope (a binder came into view).
    let rIn (sc: Scope) = rewriteOps st env aliases elab sc
    let rList es =
        es |> List.fold (fun acc x ->
            acc |> Result.bind (fun xs -> r x |> Result.map (fun x' -> xs @ [x'])))
            (Ok [])
    let rOpt (o: Expr option) =
        match o with
        | None -> Ok None
        | Some x -> r x |> Result.map Some
    match e.Kind with
    // Qualified domain op: `alias.op(...)` -> the elaborated call. Any alias-qualified call is claimed here so an unknown
    // op gets a steering error instead of an unbound-module type error downstream.
    // A LOCAL binder of the alias's name (a parameter `sp`, a `let sp = ..`, a pattern variable) shadows the import:
    // `sp.fft(x)` is then a field call on that value, never the domain op.
    | ExprKind.ExprApp ({ Kind = ExprKind.ExprField ({ Kind = ExprKind.ExprVar alias }, op) }, args)
            when Set.contains alias aliases && not (Map.containsKey alias scope) ->
        rList args |> Result.bind (fun args' -> elab st env scope op args')
    | ExprKind.ExprLit _ | ExprKind.ExprVar _ -> Ok e
    | ExprKind.ExprApp (f, args) ->
        r f |> Result.bind (fun f' -> rList args |> Result.map (fun args' -> inheritSpan e (ExprApp (f', args'))))
    | ExprKind.ExprBinOp (m, op, l, rr) ->
        r l |> Result.bind (fun l' -> r rr |> Result.map (fun r' -> inheritSpan e (ExprBinOp (m, op, l', r'))))
    | ExprKind.ExprUnaryOp (op, inner) -> r inner |> Result.map (fun i -> inheritSpan e (ExprUnaryOp (op, i)))
    | ExprKind.ExprTyped (inner, t) -> r inner |> Result.map (fun i -> inheritSpan e (ExprTyped (i, t)))
    | ExprKind.ExprAssign (l, rr) ->
        r l |> Result.bind (fun l' -> r rr |> Result.map (fun r' -> inheritSpan e (ExprAssign (l', r'))))
    | ExprKind.ExprTuple es -> rList es |> Result.map (fun es' -> inheritSpan e (ExprTuple es'))
    | ExprKind.ExprArrayLit es -> rList es |> Result.map (fun es' -> inheritSpan e (ExprArrayLit es'))
    | ExprKind.ExprDotDot (l, h) ->
        r l |> Result.bind (fun l' -> r h |> Result.map (fun h' -> inheritSpan e (ExprDotDot (l', h'))))
    | ExprKind.ExprIf (c, t, f) ->
        r c |> Result.bind (fun c' ->
        r t |> Result.bind (fun t' ->
        r f |> Result.map (fun f' -> inheritSpan e (ExprIf (c', t', f')))))
    | ExprKind.ExprLet (binding, body) ->
        // The value is rewritten in the OUTER scope; the body sees the binder, shaped by its rewritten value.
        r binding.Value |> Result.bind (fun v' ->
        let b' = { binding with Value = v' }
        rIn (bindBinding env scope b') body
        |> Result.map (fun body' -> inheritSpan e (ExprLet (b', body'))))
    | ExprKind.ExprBlock (stmts, finalE) ->
        // Statements thread the scope forward: a `let` inside the block is a shape witness for what follows.
        let rec rStmt (sc: Scope) (s: Stmt) : Result<Stmt * Scope, string> =
            match s with
            | StmtSpanned (inner, sp) -> rStmt sc inner |> Result.map (fun (i, sc') -> (StmtSpanned (i, sp), sc'))
            | StmtLet binding ->
                rIn sc binding.Value |> Result.map (fun v' ->
                    let b' = { binding with Value = v' }
                    (StmtLet b', bindBinding env sc b'))
            | StmtExpr e2 -> rIn sc e2 |> Result.map (fun x -> (StmtExpr x, sc))
            | StmtAssign (l, op, rr) ->
                rIn sc l |> Result.bind (fun l' -> rIn sc rr |> Result.map (fun r' -> (StmtAssign (l', op, r'), sc)))
            | StmtForIn (var, range, body) ->
                rIn sc range |> Result.bind (fun range' ->
                    let inner = Map.add var (Error "it is a loop variable") sc
                    body |> List.fold (fun acc bs ->
                        acc |> Result.bind (fun (ss, s0) -> rStmt s0 bs |> Result.map (fun (s', s1) -> (ss @ [s'], s1))))
                        (Ok ([], inner))
                    // Bindings made inside the loop body do not escape it.
                    |> Result.map (fun (body', _) -> (StmtForIn (var, range', body'), sc)))
        stmts |> List.fold (fun acc s ->
            acc |> Result.bind (fun (ss, sc) -> rStmt sc s |> Result.map (fun (s', sc') -> (ss @ [s'], sc'))))
            (Ok ([], scope))
        |> Result.bind (fun (stmts', sc) ->
            match finalE with
            | Some fe -> rIn sc fe |> Result.map (fun fe' -> inheritSpan e (ExprBlock (stmts', Some fe')))
            | None -> Ok (inheritSpan e (ExprBlock (stmts', None))))
    | ExprKind.ExprLambda (ps, w, body) ->
        let sc = ps |> List.fold (fun acc (p: LambdaParam) -> bindParam env acc p.Name p.Type) scope
        rIn sc body |> Result.map (fun b -> inheritSpan e (ExprLambda (ps, w, b)))
    | ExprKind.ExprMatch (scrut, cases) ->
        r scrut |> Result.bind (fun s' ->
            cases |> List.fold (fun acc c ->
                acc |> Result.bind (fun cs ->
                    // An arm's pattern variables shadow outer names.
                    let sc = shadowPattern scope c.Pattern "it is bound by a match pattern"
                    (match c.Guard with
                     | None -> Ok None
                     | Some g -> rIn sc g |> Result.map Some) |> Result.bind (fun g' ->
                    rIn sc c.Body |> Result.map (fun b -> cs @ [{ c with Guard = g'; Body = b }]))))
                (Ok [])
            |> Result.map (fun cs' -> inheritSpan e (ExprMatch (s', cs'))))
    // Recursive array (`let rec q: T = match q with ...`): the seed and inductive slices are ordinary expressions and may
    // contain qualified ops; without this arm they fell through unrewritten and reached the checker as an unbound variable.
    | ExprKind.ExprRecArray def ->
        // The arms' binders (the family, the prefix, the step ordinals) shadow outer names like any binder.
        let unshaped (sc: Scope) (n: string) = Map.add n (Error "it is bound by a recursive array's arm") sc
        let seedScope = def.SeedArm |> Option.fold (fun sc (sv, _) -> unshaped sc sv) (unshaped scope def.Name)
        let armScope = unshaped (unshaped (unshaped scope def.Name) def.PrefixVar) def.StepVar
        let rOptIn (sc: Scope) (o: Expr option) =
            match o with
            | None -> Ok None
            | Some x -> rIn sc x |> Result.map Some
        rOptIn seedScope (def.SeedArm |> Option.map snd) |> Result.bind (fun seedE ->
        rOptIn armScope def.Guard |> Result.bind (fun guardE ->
        rIn armScope def.SliceExpr |> Result.map (fun slice' ->
            let seed' = Option.map2 (fun (sv, _) se -> (sv, se)) def.SeedArm seedE
            inheritSpan e (ExprRecArray { def with SeedArm = seed'; SliceExpr = slice'; Guard = guardE }))))
    | ExprKind.ExprCompute inner -> r inner |> Result.map (fun i -> inheritSpan e (ExprCompute i))
    | ExprKind.ExprRead inner -> r inner |> Result.map (fun i -> inheritSpan e (ExprRead i))
    | ExprKind.ExprPure inner -> r inner |> Result.map (fun i -> inheritSpan e (ExprPure i))
    | ExprKind.ExprStatic inner -> r inner |> Result.map (fun i -> inheritSpan e (ExprStatic i))
    | ExprKind.ExprRank inner -> r inner |> Result.map (fun i -> inheritSpan e (ExprRank i))
    | ExprKind.ExprExtents inner -> r inner |> Result.map (fun i -> inheritSpan e (ExprExtents i))
    | ExprKind.ExprUnique inner -> r inner |> Result.map (fun i -> inheritSpan e (ExprUnique i))
    | ExprKind.ExprObjectFor k -> r k |> Result.map (fun k' -> inheritSpan e (ExprObjectFor k'))
    | ExprKind.ExprReynolds (k, anti) -> r k |> Result.map (fun k' -> inheritSpan e (ExprReynolds (k', anti)))
    | ExprKind.ExprField (obj, fld) -> r obj |> Result.map (fun o -> inheritSpan e (ExprField (o, fld)))
    | ExprKind.ExprPartialApp (op, inner, isLeft) -> r inner |> Result.map (fun i -> inheritSpan e (ExprPartialApp (op, i, isLeft)))
    | ExprKind.ExprTranspose (a, d1, d2) -> r a |> Result.map (fun a' -> inheritSpan e (ExprTranspose (a', d1, d2)))
    | ExprKind.ExprDecompact (a, d) -> r a |> Result.map (fun a' -> inheritSpan e (ExprDecompact (a', d)))
    | ExprKind.ExprHalo (t, offs) -> r offs |> Result.map (fun o -> inheritSpan e (ExprHalo (t, o)))
    | ExprKind.ExprMethodFor es -> rList es |> Result.map (fun es' -> inheritSpan e (ExprMethodFor es'))
    | ExprKind.ExprZip es -> rList es |> Result.map (fun es' -> inheritSpan e (ExprZip es'))
    | ExprKind.ExprStack es -> rList es |> Result.map (fun es' -> inheritSpan e (ExprStack es'))
    | ExprKind.ExprSequence es -> rList es |> Result.map (fun es' -> inheritSpan e (ExprSequence es'))
    | ExprKind.ExprGroupKeys es -> rList es |> Result.map (fun es' -> inheritSpan e (ExprGroupKeys es'))
    | ExprKind.ExprGroupBucket g -> r g |> Result.map (fun g' -> inheritSpan e (ExprGroupBucket g'))
    | ExprKind.ExprAlign (es, spec) -> rList es |> Result.map (fun es' -> inheritSpan e (ExprAlign (es', spec)))
    | ExprKind.ExprJoin (es, d) -> rList es |> Result.map (fun es' -> inheritSpan e (ExprJoin (es', d)))
    | ExprKind.ExprTupleIndex (t, i) ->
        r t |> Result.bind (fun t' -> r i |> Result.map (fun i' -> inheritSpan e (ExprTupleIndex (t', i'))))
    | ExprKind.ExprGuard (c, b) ->
        r c |> Result.bind (fun c' -> r b |> Result.map (fun b' -> inheritSpan e (ExprGuard (c', b'))))
    | ExprKind.ExprReplicate (c, b) ->
        r c |> Result.bind (fun c' -> r b |> Result.map (fun b' -> inheritSpan e (ExprReplicate (c', b'))))
    | ExprKind.ExprMask (a, p) ->
        r a |> Result.bind (fun a' -> r p |> Result.map (fun p' -> inheritSpan e (ExprMask (a', p'))))
    | ExprKind.ExprCompound (d, m) ->
        r d |> Result.bind (fun d' -> r m |> Result.map (fun m' -> inheritSpan e (ExprCompound (d', m'))))
    | ExprKind.ExprSparse (v, k) ->
        r v |> Result.bind (fun v' -> r k |> Result.map (fun k' -> inheritSpan e (ExprSparse (v', k'))))
    | ExprKind.ExprIntersect (a, b) ->
        r a |> Result.bind (fun a' -> r b |> Result.map (fun b' -> inheritSpan e (ExprIntersect (a', b'))))
    | ExprKind.ExprUnion (a, b) ->
        r a |> Result.bind (fun a' -> r b |> Result.map (fun b' -> inheritSpan e (ExprUnion (a', b'))))
    | ExprKind.ExprContains (a, v) ->
        r a |> Result.bind (fun a' -> r v |> Result.map (fun v' -> inheritSpan e (ExprContains (a', v'))))
    | ExprKind.ExprGroupBy (v, g) ->
        r v |> Result.bind (fun v' -> r g |> Result.map (fun g' -> inheritSpan e (ExprGroupBy (v', g'))))
    | ExprKind.ExprSort (a, k) ->
        r a |> Result.bind (fun a' -> r k |> Result.map (fun k' -> inheritSpan e (ExprSort (a', k'))))
    | ExprKind.ExprGram (l, rr) ->
        r l |> Result.bind (fun l' -> r rr |> Result.map (fun r' -> inheritSpan e (ExprGram (l', r'))))
    | ExprKind.ExprGramApply (l, rr, x) ->
        r l |> Result.bind (fun l' -> r rr |> Result.bind (fun r' -> r x |> Result.map (fun x' -> inheritSpan e (ExprGramApply (l', r', x')))))
    | ExprKind.ExprReduce (a, k, init, ax) ->
        r a |> Result.bind (fun a' ->
        r k |> Result.bind (fun k' ->
        rOpt init |> Result.map (fun init' -> inheritSpan e (ExprReduce (a', k', init', ax)))))
    | ExprKind.ExprStruct (nm, fields, spread) ->
        fields |> List.fold (fun acc (fn, fe) ->
            acc |> Result.bind (fun fs -> r fe |> Result.map (fun fe' -> fs @ [(fn, fe')])))
            (Ok [])
        |> Result.bind (fun fields' ->
        rOpt spread |> Result.map (fun spread' -> inheritSpan e (ExprStruct (nm, fields', spread'))))
    | ExprKind.ExprFor (src, cs, kern) ->
        (match src with
         | ForArrays (arrs, inClause) ->
             rList arrs |> Result.bind (fun arrs' ->
             rOpt inClause |> Result.map (fun ic' -> ForArrays (arrs', ic')))
         | ForKernel k -> r k |> Result.map ForKernel)
        |> Result.bind (fun src' ->
        rOpt kern |> Result.map (fun kern' -> inheritSpan e (ExprFor (src', cs, kern'))))
    // Leaves: no sub-expressions. Index/type arguments (range<I>, reverse<I>) carry TypeExprs, not Exprs, never rewritten.
    | ExprKind.ExprWildcard | ExprKind.ExprQualified _ | ExprKind.ExprRange _
    | ExprKind.ExprReverse _ | ExprKind.ExprArity _ | ExprKind.ExprNth
    | ExprKind.ExprZero | ExprKind.ExprSection _ -> Ok e

// Gating + program expansion (one copy for every expression-level domain elaborator)

/// Aliases bound to `path` in this decl list. Errors on a selective `from <path> import ...`, which would reintroduce the
/// global names the module system is meant to remove.
let private domainAliasesOf (path: string) (decls: Located<Decl> list) : Result<Set<string>, string> =
    decls |> List.fold (fun acc d ->
        acc |> Result.bind (fun set ->
            match d.Value with
            | DeclImport ([ p ], ImportQualified aliasOpt) when p = path ->
                Ok (Set.add (aliasOpt |> Option.defaultValue path) set)
            | DeclImport ([ p ], ImportSelective _) when p = path ->
                Error $"`{path}` supports only `import {path} [as <alias>]`; a selective `from {path} import ...` would reintroduce global names"
            | _ -> Ok set))
        (Ok Set.empty)

/// One domain's module expansion: import-gated (with no `import <path>` it is a strict no-op, so a user's own functions
/// of the same names are never touched); rewrites every function body and value binding; splices the generated
/// routines at the FRONT (they are self-contained, so every use site, top-level lets included, sees them defined).
let private expandDomainModule (path: string) (prefix: string) (elab: ElabOpFn) (modules: ModuleDecl list)
    (decls: Located<Decl> list) : Result<Located<Decl> list, string> =
    domainAliasesOf path decls |> Result.bind (fun aliases ->
    if Set.isEmpty aliases then Ok decls
    else
        let isOwnImport (d: Located<Decl>) = match d.Value with DeclImport ([ p ], _) -> p = path | _ -> false
        let declsNoImport = decls |> List.filter (not << isOwnImport)
        // Fold failures are the type checker's to report; elaboration only needs the successfully folded environment.
        match resolveStatics declsNoImport with
        | Error e -> Error $"{path} elaboration: static resolution failed: {e}"
        | Ok (statics, _) ->
            let st = newGenState prefix
            let env = moduleEnv modules decls statics (genLookup st)
            // A module-level value binding named like the alias shadows it from its declaration on (moduleEnv's rule):
            // `offRef` holds the aliases the value bindings so far rebound (disabled, not scope entries), so the walker leaves
            // `sp.fft(..)` to that value -- after it, and never in its own initializer.
            let offRef : Set<string> ref = ref Set.empty
            let envOff : Map<Set<string>, Env> ref = ref Map.empty
            let rebind (b: Binding) =
                offRef.Value <- patternNames b.Pattern |> List.fold (fun s n -> if Set.contains n aliases then Set.add n s else s) offRef.Value
            // The environment and the claimed aliases for the declaration at hand (one environment per disabled set).
            let current () =
                let off = offRef.Value
                let e =
                    match Map.tryFind off envOff.Value with
                    | Some e -> e
                    | None ->
                        let e = withoutAliases env off
                        envOff.Value <- Map.add off e envOff.Value
                        e
                (e, Set.difference aliases off)
            let mapped =
                declsNoImport |> List.fold (fun acc d ->
                    acc |> Result.bind (fun out ->
                        // Stamp the user decl's span so every syn-built node (generated bodies + synthesized call sites)
                        // attributes to this declaration's source line.
                        setSynthSpan (d.Span)
                        let mapped =
                            match d.Value with
                            | DeclFunction fd ->
                                // Parameters are the body's first scope: an annotated array parameter is a shape witness.
                                let (envD, aliasesD) = current ()
                                let pscope = fd.Params |> List.fold (fun sc p -> bindParam envD sc p.Name p.Type) Map.empty
                                rewriteOps st envD aliasesD elab pscope fd.Body
                                |> Result.map (fun b -> DeclFunction { fd with Body = b })
                            | DeclLet binding ->
                                let (envD, aliasesD) = current ()
                                let r = rewriteOps st envD aliasesD elab Map.empty binding.Value
                                rebind binding
                                r |> Result.map (fun v' -> DeclLet { binding with Value = v' })
                            | DeclStatic binding ->
                                let (envD, aliasesD) = current ()
                                let r = rewriteOps st envD aliasesD elab Map.empty binding.Value
                                rebind binding
                                r |> Result.map (fun v' -> DeclStatic { binding with Value = v' })
                            | other -> Ok other
                        mapped |> Result.map (fun value -> out @ [{ d with Value = value }])))
                    (Ok [])
            mapped |> Result.map (fun decls' ->
                if st.Decls.IsEmpty then decls'
                else
                    let gen = st.Decls |> List.map (fun fd -> { Value = DeclFunction fd; Span = noSpan })
                    gen @ decls'))

/// A domain's whole-program expansion with its coded boundary: string-errored internals -> one `code` diagnostic, whose
/// span is the ambient synthSpan (stamped per decl, so a mid-elaboration failure points at the offending declaration).
let expandDomain (path: string) (prefix: string) (code: string) (elab: ElabOpFn) (program: Program)
    : Result<Program, Blade.Diagnostics.Diagnostic list> =
    setSynthSpan noSpan
    program.Modules
    |> List.fold (fun acc m ->
        acc |> Result.bind (fun ms ->
            expandDomainModule path prefix elab program.Modules m.Decls |> Result.map (fun ds -> ms @ [{ m with Decls = ds }])))
        (Ok [])
    |> Result.map (fun ms -> { program with Modules = ms })
    |> Result.mapError (fun msg ->
        [ Blade.Diagnostics.mkError code (Blade.Diagnostics.Codes.phaseOfCode code) (synthSpan ()) msg ])
