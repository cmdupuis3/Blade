/// grad() and jvp() -- reverse- and forward-mode automatic differentiation
/// as AST-level source transforms (pre-typecheck), surfaced through the
/// `ad` module. The header below documents grad; jvp's surface, ABI, and
/// subset are documented at `synthesizeJvp` (its subset is a strict
/// superset -- forward mode needs no reverse sweep, so the discipline
/// checks below do not apply to it), and the composition driver
/// (`ad.jvp(ad.grad(f))` = HVP) at `expandModule`.
///
/// Surface form: `import ad as ad` then `ad.grad(f)` where `f` is a
/// top-level function in the same module returning a Float scalar. The pass
/// is import-gated (no `import ad` -> no-op; bare `grad(...)` is unbound,
/// same module rule as the ml/ppl surfaces). The expression rewrites to a
/// reference to a synthesized function `f__grad`, so
/// `ad.grad(f)(args..., buffers...)` and `let g = ad.grad(f)` both work:
///
///   function f__grad(p1, ..., pn,                    // originals
///                    __g_pA: mut <type of pA>, ...)   // one out-buffer per
///                                                      // Float-ARRAY param
///       -> Float                                      // the primal value
///       |  (Float, Float, ...)                        // + one gradient per
///                                                      //   Float SCALAR param
///
/// Gradient out-buffers are ACCUMULATED into (callers zero them; repeated
/// calls sum, PyTorch .grad semantics). Int / int-array params (edge lists,
/// sizes) are non-differentiable and get no buffer.
///
/// Why source-to-source, pre-typecheck: the generated derivative is itself
/// type-checked, lowered, and code-generated by the existing pipeline,
/// including the symmetry system, so adjoints of symmetric computations
/// inherit triangular storage with no AD-specific storage logic.
///
/// THE AD-ABLE SUBSET. Differentiated function bodies may contain:
///   - `let x = e` / `let mut x = e` (single-name patterns)
///   - accumulation `x += e`, `x -= e`, `a(i...) += e`, `a(i...) -= e`
///     (and their spelled-out forms `x = x + e` etc.)
///   - general (re)assignment in STRAIGHT-LINE positions; inside loops only
///     the additive-self pattern is allowed on scalars (loop-carried
///     recurrences would need taping/reversal)
///   - element writes `a(i...) = e` (construction of fresh arrays)
///   - `for k in lo..hi { ... }` to any nesting depth (int bounds,
///     non-differentiable); the ADJOINT loop runs in the SAME direction,
///     exact for the accumulation subset
///   - scalar arithmetic + - * / (and `^` by an int literal), unary minus
///   - math intrinsics (exp/log/sqrt/trig/hyperbolic; floor/ceil have zero
///     derivative). lgamma differentiates to digamma, which makes the
///     gamma/beta/poisson log-likelihoods AD-able. NOT digamma itself: its
///     derivative is trigamma, which the language does not have, so it is
///     REFUSED rather than silently differentiated to zero
///     (zeroDerivIntrinsics vs derivRule's None, below)
///   - array reads `a(i...)` at integer index expressions
///   - calls to other AD-able functions in the same module, INLINED
///     (recursion rejected by a depth cap)
///   - float array literals
///
/// Deliberately rejected (clean errors): if/match in differentiated code,
/// combinator computations AND combinator operators, tuple-pattern lets,
/// reads of an accumulator from expressions inside the loop that mutates it,
/// writes to an accumulator after straight-line code has read it,
/// array-alias lets, callees with mut params, unit-carrying and complex
/// parameters/returns (a gradient's units are <loss>/<param>, which this ABI
/// cannot express; complex needs a Wirtinger convention), calls to names
/// with no derivative rule (`abs`, `min`, imports -- silence would drop
/// their term), and user bindings spelled like the synthesized names
/// (`__g_*`, `__t_*`, `__primal` -- shadowing corrupts the sweep).
///
/// Loop-body `let`s are recomputed inside the adjoint loop (recompute-based
/// tape); function-level `let`s stay in scope across the reverse sweep, so
/// nothing else is stored. The C(n+r-1, r) triangular-tape result falls out
/// of storing intermediates in whatever (possibly symmetric) arrays the
/// forward pass already uses.
module Blade.Grad

open Blade.Ast

// Math intrinsics -- the single source of truth (TypeCheck reads these too)

/// Scalar math intrinsics recognized as plain calls (`exp(x)`) when the name
/// is not user-bound. Unary, real-valued, rendered as std::<name> in C++ --
/// except `lgamma` and `digamma`, which render as `blade_rt::<name>`
/// (CodeGen.unaryOpToCpp) because they have no bit-exact interpreter twin in
/// any shared library; see src/cpp/blade_runtime.hpp.
/// Keep in sync with StaticEval.evalBuiltin and derivRule below.
let mathIntrinsics : Set<string> =
    Set.ofList [
        "exp"; "log"; "log10"; "sqrt"
        "sin"; "cos"; "tan"
        "sinh"; "cosh"; "tanh"
        "asin"; "acos"; "atan"
        "floor"; "ceil"
        "lgamma"; "digamma"
    ]

let isMathIntrinsic (name: string) : bool = Set.contains name mathIntrinsics

/// BINARY math intrinsics -- plain two-argument calls (`atan2(y, x)`) that
/// TypeCheck rewrites to `TExprBinOp (Elementwise, OpMath2 name, ...)` when the
/// name is not user-bound. Deliberately a SEPARATE set from `mathIntrinsics`:
/// that one is documented unary and `TypeCheck.isUnaryIntrinsic` /
/// `etaExpandFunctionKernel` read it for an arity they cannot otherwise
/// recover, so widening it would eta-expand `atan2` to one parameter.
/// Real-only (neither has a std::complex overload), and their result is
/// always dimensionless -- see TypeCheck.unitRulesForOp's OpMath2 arms.
/// Keep in sync with StaticEval.evalBuiltin, `adjointOf`'s binary-intrinsic
/// arm below, and CodeGen's IRMath2 rendering.
let binaryMathIntrinsics : Set<string> =
    Set.ofList [ "atan2"; "log_base" ]

let isBinaryMathIntrinsic (name: string) : bool = Set.contains name binaryMathIntrinsics

/// Subset of the intrinsics that have std::complex overloads in <complex>
/// and so are permitted on complex operands (result is complex, same
/// width). exp/log/sqrt and the trig/hyperbolic families qualify; floor/
/// ceil do not (no complex overload, stay real-only and reject complex).
/// Differentiation of complex intrinsics is out of scope.
let complexMathIntrinsics : Set<string> =
    Set.ofList [
        "exp"; "log"; "sqrt"
        "sin"; "cos"; "tan"
        "sinh"; "cosh"; "tanh"
        "asin"; "acos"; "atan"
    ]

let isComplexMathIntrinsic (name: string) : bool = Set.contains name complexMathIntrinsics

// Expression construction helpers. Span-free derivative-synthesis builders:
// `syn` stamps each node with the ambient `synthSpan` (set to the
// differentiated decl's span in expand).
let private fLit (v: float) = syn (ExprLit (LitFloat v))
let private iLit (n: int64) = syn (ExprLit (LitInt n))
let private v (name: string) = syn (ExprVar name)
let private add a b = syn (ExprBinOp (Elementwise, OpAdd, a, b))
let private sub a b = syn (ExprBinOp (Elementwise, OpSub, a, b))
let private mul a b = syn (ExprBinOp (Elementwise, OpMul, a, b))
let private div a b = syn (ExprBinOp (Elementwise, OpDiv, a, b))
let private pow a b = syn (ExprBinOp (Elementwise, OpCaret, a, b))
let private neg a = syn (ExprUnaryOp (OpNeg, a))
let private call name args = syn (ExprApp (v name, args))

/// Intrinsics whose derivative is IDENTICALLY ZERO (a.e.), so `derivRule`
/// returning None for them means "contributes nothing", not "unknown". Split
/// out from derivRule's None because those two readings must not be confused:
/// an intrinsic with no rule that is silently treated as zero-derivative
/// yields a WRONG gradient with no diagnostic, which is worse than a refusal.
/// adjointOf refuses anything outside this set that derivRule cannot handle.
let private zeroDerivIntrinsics : Set<string> = Set.ofList [ "floor"; "ceil" ]

/// d/du of intrinsic(u), as a function of the FORWARD expression u.
/// Returns None for the zero-derivative intrinsics above AND for any
/// intrinsic with no rule yet (`digamma`: its derivative is the trigamma
/// function, which the language does not have) -- adjointOf tells the two
/// apart via zeroDerivIntrinsics and refuses the latter.
let private derivRule (name: string) (u: Expr) : Expr option =
    match name with
    | "exp" -> Some (call "exp" [u])
    | "log" -> Some (div (fLit 1.0) u)
    // d/du log10(u) = 1/(u ln 10). `log(10.0)` is left symbolic rather than
    // spelled as a decimal so the emitted derivative carries the same rounding
    // as the forward pass's std::log10 base; both back ends constant-fold it.
    | "log10" -> Some (div (fLit 1.0) (mul u (call "log" [fLit 10.0])))
    | "sqrt" -> Some (div (fLit 1.0) (mul (fLit 2.0) (call "sqrt" [u])))
    | "sin" -> Some (call "cos" [u])
    | "cos" -> Some (neg (call "sin" [u]))
    | "tan" -> Some (div (fLit 1.0) (mul (call "cos" [u]) (call "cos" [u])))
    | "sinh" -> Some (call "cosh" [u])
    | "cosh" -> Some (call "sinh" [u])
    | "tanh" -> Some (sub (fLit 1.0) (mul (call "tanh" [u]) (call "tanh" [u])))
    | "asin" -> Some (div (fLit 1.0) (call "sqrt" [sub (fLit 1.0) (mul u u)]))
    | "acos" -> Some (neg (div (fLit 1.0) (call "sqrt" [sub (fLit 1.0) (mul u u)])))
    | "atan" -> Some (div (fLit 1.0) (add (fLit 1.0) (mul u u)))
    // d/dx log Gamma(x) = psi(x). The chain rule closes here because digamma
    // is itself an intrinsic (blade_rt::digamma), so the emitted adjoint is
    // an ordinary Blade expression the rest of the pipeline already handles.
    // This is what makes gamma / beta / poisson log-likelihoods -- whose
    // normalizers are all lgamma -- differentiable, and so HMC-able.
    | "lgamma" -> Some (call "digamma" [u])
    | "floor" | "ceil" -> None
    // digamma is now the frontier: d/dx psi(x) = psi'(x) is trigamma, which
    // the language does not have, so it is REFUSED below rather than silently
    // differentiated to zero. Adding trigamma would move this line, not
    // change the shape of the rule.
    | _ -> None

// Normalized statement model

/// The statement fragment the transform reasons over, after unwrapping
/// spans and desugaring. Assignments keep their surface Expr lhs (a plain
/// var or an element application).
type private NStmt =
    | NLet of name: string * isMut: bool * value: Expr
    | NAssign of lhs: Expr * rhs: Expr
    | NFor of var: string * lo: Expr * hi: Expr * body: NStmt list

type private Ctx = {
    /// Same-module user function declarations by name.
    Decls: Map<string, FunctionDecl>
    /// Same-module transparent type aliases (unparameterized `type X = T` and
    /// mutual-group members), so `type Speed = Float<mps>` classifies as the
    /// unit-carrying Float it is instead of silently falling to NonDiff.
    TypeAliases: Map<string, TypeExpr>
    /// Module-level value binding names (DeclLet / DeclStatic): reads of these
    /// inside a differentiated body are constant data, not unknown calls.
    ModuleVals: Set<string>
    /// Fresh-suffix counter (shared across one expand run).
    mutable Fresh: int
}

let private fresh (ctx: Ctx) (prefix: string) : string =
    ctx.Fresh <- ctx.Fresh + 1
    sprintf "%s%d" prefix ctx.Fresh

/// Which transform is currently synthesizing ("grad" | "jvp") -- prefixes
/// every internal error and selects the diagnostic code at the `expand`
/// boundary. A module-level ref (like `synthSpan`): the pass is sequential.
let private errMode = ref "grad"

let private err (fname: string) (msg: string) : Result<'a, string> =
    Error (sprintf "%s(%s): %s" errMode.Value fname msg)

/// Resolve same-module transparent type aliases, depth-capped (an alias
/// cycle is a type error elsewhere; the cap just keeps this total). Defined
/// this early because extent reading, parameter classification, and the map
/// rule all need to see through `type I = Idx<3>`.
let private resolveTy (ctx: Ctx) (t: TypeExpr) : TypeExpr =
    let rec go d t =
        if d > 8 then t
        else
            match t with
            | TyNamed (n, []) ->
                (match Map.tryFind n ctx.TypeAliases with
                 | Some body -> go (d + 1) body
                 | None -> t)
            | _ -> t
    go 0 t

/// `arrayLiteralExtents` after alias resolution on the element and index
/// slots, so `Array<Float like I>` with `type I = Idx<3>` reads as extent 3.
let private resolveArrayTy (ctx: Ctx) (t: TypeExpr) : TypeExpr =
    match resolveTy ctx t with
    | TyArray (elem, idxs) -> TyArray (resolveTy ctx elem, idxs |> List.map (resolveTy ctx))
    | other -> other

// Body -> NStmt conversion

let rec private convertStmts (fname: string) (stmts: Stmt list) : Result<NStmt list, string> =
    let folder acc stmt =
        acc |> Result.bind (fun converted ->
            match unwrapStmt stmt with
            | StmtSpanned _ -> err fname "internal: unwrapStmt left a span"
            | StmtLet binding ->
                match binding.Pattern.Kind with
                | PatternKind.PatVar name ->
                    let isMut = (binding.Mutability = BindMut)
                    Ok (converted @ [NLet (name, isMut, binding.Value)])
                | _ -> err fname "tuple/struct patterns in let are not differentiable (v1); bind names individually"
            | StmtExpr { Kind = ExprKind.ExprAssign (lhs, rhs) } ->
                Ok (converted @ [NAssign (lhs, rhs)])
            | StmtAssign (lhs, op, rhs) ->
                // Defensive: the parser emits ExprAssign, but normalize
                // StmtAssign if one arrives.
                let rhs' =
                    match op with
                    | AssignEq -> rhs
                    | AssignAdd -> add lhs rhs
                    | AssignSub -> sub lhs rhs
                    | AssignMul -> mul lhs rhs
                    | AssignDiv -> div lhs rhs
                Ok (converted @ [NAssign (lhs, rhs')])
            | StmtExpr _ ->
                err fname "bare expression statements are not supported in differentiated code"
            | StmtForIn (var, { Kind = ExprKind.ExprDotDot (lo, hi) }, body) ->
                convertStmts fname body |> Result.map (fun nbody ->
                    converted @ [NFor (var, lo, hi, nbody)])
            | StmtForIn _ ->
                err fname "for-in ranges must use the a..b form in differentiated code")
    stmts |> List.fold folder (Ok [])

/// A function body is either a block or a bare expression.
let private convertBody (fname: string) (body: Expr) : Result<NStmt list * Expr, string> =
    match body.Kind with
    | ExprKind.ExprBlock (stmts, Some finalE) ->
        convertStmts fname stmts |> Result.map (fun ns -> (ns, finalE))
    | ExprKind.ExprBlock (_, None) ->
        err fname "function body has no final expression (must return a Float)"
    | _ -> Ok ([], body)

// Expression validation + variable collection over the AD-able fragment

/// The constant-fill array constructor `replicate(N, pure(lit)) |> compute`,
/// the idiomatic replacement for hand-written N-element zero literals.
/// Combinators are otherwise rejected in differentiated code (v1), but a
/// literal fill computes nothing and reads nothing, so it is admitted as
/// an array-literal equivalent wherever ExprArrayLit initializers are.
/// Captures (count expr, fill literal).
let private (|ConstFill|_|) (e: Expr) =
    match e.Kind with
    | ExprKind.ExprCompute { Kind = ExprKind.ExprReplicate (cnt, { Kind = ExprKind.ExprPure { Kind = ExprKind.ExprLit lit } }) } -> Some (cnt, lit)
    | _ -> None

/// A ConstFill of the same count with the fill value zeroed.
let private zeroFill (cnt: Expr) : Expr =
    let re k = inheritSpan cnt k
    re (ExprCompute (re (ExprReplicate (cnt, re (ExprPure (re (ExprLit (LitFloat 0.0))))))))

/// The C1 LINEAR CLOSURE: combinator forms that only REINDEX or WRAP, so
/// their tangent is the same form applied to the tangents of their
/// differentiable operands, with non-differentiable operands (masks,
/// grouping keys, counts, conditions, axis indices) reused verbatim. No
/// derivative rules and no kernel synthesis are involved -- this is
/// plumbing, and it is what lets a tangent travel through a pipeline of
/// structural operations. Returns (differentiable operands, rebuild).
///
/// `guard` belongs here because zeroing is linear: d(c ? e : 0) = c ? ė : 0.
/// `<|:>` belongs here because its selector is ALLOCATION, not value --
/// storage branching is linear in both legs (unlike `<|>`, which branches
/// on a VALUE test and is discontinuous, so it stays refused).
let private (|LinearForm|_|) (e: Expr) : (Expr list * (Expr list -> Expr)) option =
    let re k = inheritSpan e k
    match e.Kind with
    | ExprKind.ExprPure inner -> Some ([inner], fun ts -> re (ExprPure (List.head ts)))
    | ExprKind.ExprCompute inner -> Some ([inner], fun ts -> re (ExprCompute (List.head ts)))
    | ExprKind.ExprGuard (c, body) -> Some ([body], fun ts -> re (ExprGuard (c, List.head ts)))
    | ExprKind.ExprStack es -> Some (es, fun ts -> re (ExprStack ts))
    | ExprKind.ExprSequence es -> Some (es, fun ts -> re (ExprSequence ts))
    | ExprKind.ExprJoin (es, d) -> Some (es, fun ts -> re (ExprJoin (ts, d)))
    | ExprKind.ExprReplicate (cnt, body) -> Some ([body], fun ts -> re (ExprReplicate (cnt, List.head ts)))
    | ExprKind.ExprTranspose (a, d1, d2) -> Some ([a], fun ts -> re (ExprTranspose (List.head ts, d1, d2)))
    | ExprKind.ExprDecompact (a, d) -> Some ([a], fun ts -> re (ExprDecompact (List.head ts, d)))
    | ExprKind.ExprCompound (dense, mask) -> Some ([dense], fun ts -> re (ExprCompound (List.head ts, mask)))
    | ExprKind.ExprGroupBy (vals, gk) -> Some ([vals], fun ts -> re (ExprGroupBy (List.head ts, gk)))
    | ExprKind.ExprBinOp (m, OpFallback, l, r) ->
        Some ([l; r], fun ts -> re (ExprBinOp (m, OpFallback, ts.[0], ts.[1])))
    | _ -> None

/// Structural array-ness, used by the taint pass so a local bound to a
/// linear combinator is tracked as an ARRAY. Under-reporting here is a
/// silent-zero bug (an element read of an untracked array yields no
/// tangent), so the forms are listed exhaustively rather than inferred.
let rec private producesArray (arrays: Set<string>) (e: Expr) : bool =
    match e.Kind with
    | ExprKind.ExprArrayLit _ -> true
    | ExprKind.ExprVar n -> Set.contains n arrays
    | ExprKind.ExprStack _ | ExprKind.ExprSequence _ | ExprKind.ExprJoin _
    | ExprKind.ExprReplicate _ | ExprKind.ExprTranspose _ | ExprKind.ExprDecompact _
    | ExprKind.ExprCompound _ | ExprKind.ExprGroupBy _ | ExprKind.ExprMask _
    | ExprKind.ExprSort _ | ExprKind.ExprUnique _
    | ExprKind.ExprIntersect _ | ExprKind.ExprUnion _ -> true
    | ExprKind.ExprPure inner | ExprKind.ExprCompute inner
    | ExprKind.ExprGuard (_, inner) | ExprKind.ExprTyped (inner, _) -> producesArray arrays inner
    | ExprKind.ExprBinOp (_, OpFallback, l, r) -> producesArray arrays l || producesArray arrays r
    // a map application (C2) always yields an array-shaped result
    | ExprKind.ExprBinOp (_, OpApply, _, _) -> true
    // grouping-derived data arrays (2.17a): the row->bucket map and
    // per-group sizes are Int arrays read by index
    | ExprKind.ExprGroupBucket _ | ExprKind.ExprExtents _ -> true
    | _ -> false

/// Walk an expression, validating it stays inside the differentiable
/// fragment, and call `onVar` for every variable REFERENCE (not index
/// positions, which are int-typed and non-differentiable, but we still
/// visit them for taint bookkeeping of index vars; harmless).
let rec private walkExpr (fname: string) (ctx: Ctx) (onVar: string -> unit) (e: Expr) : Result<unit, string> =
    match e with
    | { Kind = ExprKind.ExprLit _ } -> Ok ()
    | { Kind = ExprKind.ExprVar name } -> onVar name; Ok ()
    | { Kind = ExprKind.ExprTyped (inner, _) } -> walkExpr fname ctx onVar inner
    | { Kind = ExprKind.ExprUnaryOp (OpNeg, inner) } -> walkExpr fname ctx onVar inner
    | { Kind = ExprKind.ExprUnaryOp (OpNot, inner) } -> walkExpr fname ctx onVar inner
    | { Kind = ExprKind.ExprUnaryOp _ } -> err fname "unsupported unary operator in differentiated code"
    // C1: the linear closure, forward mode only. Placed before the
    // combinator-operator and combinator-form refusals so `<|:>`, `pure`,
    // and `compute` reach it in jvp mode and stay refused in grad mode.
    | LinearForm (ops, _) when errMode.Value = "jvp" ->
        ops |> List.fold (fun acc o -> acc |> Result.bind (fun () -> walkExpr fname ctx onVar o)) (Ok ())
    // Grouping data is constant plumbing in BOTH modes: keys are Int/index
    // data, so a `group_keys`/`group_bucket`/`extents` binding carries no
    // derivative and the explicit-bucket gather pattern (2.17a) rides the
    // ordinary data-dependent-read machinery.
    | { Kind = ExprKind.ExprGroupKeys keys } ->
        keys |> List.fold (fun acc k -> acc |> Result.bind (fun () -> walkExpr fname ctx onVar k)) (Ok ())
    | { Kind = ExprKind.ExprGroupBucket g } -> walkExpr fname ctx onVar g
    | { Kind = ExprKind.ExprExtents a } -> walkExpr fname ctx onVar a
    // ... and their `|> compute` materializations (the emitter needs the
    // binding materialized inside a function body). Narrow on purpose: in
    // grad mode `compute` stays refused everywhere else.
    | { Kind = ExprKind.ExprCompute ({ Kind = ExprKind.ExprGroupBucket _ | ExprKind.ExprExtents _ | ExprKind.ExprGroupKeys _ } as inner) } ->
        walkExpr fname ctx onVar inner
    // Bare loop objects are LEGAL let initializers in jvp mode (the binding
    // is resolved at its application site); operands are visited for taint.
    | { Kind = ExprKind.ExprMethodFor arrs } when errMode.Value = "jvp" ->
        arrs |> List.fold (fun acc a ->
            acc |> Result.bind (fun () ->
                match a.Kind with
                | ExprKind.ExprHalo _ | ExprKind.ExprRange _ -> Ok ()
                | _ -> walkExpr fname ctx onVar a)) (Ok ())
    | { Kind = ExprKind.ExprObjectFor _ } when errMode.Value = "jvp" -> Ok ()
    // C2-C5: the rank-0 map (both spellings). Visit the operand arrays (so
    // taint sees them; virtual halo/range operands have nothing to visit)
    // and the kernel BODY; kernel params are bound by the lambda, and the
    // tangent rule substitutes indexed reads for them.
    | { Kind = ExprKind.ExprBinOp (_, OpApply, lo2, kn) } when errMode.Value = "jvp"
            && (match lo2.Kind with ExprKind.ExprMethodFor _ | ExprKind.ExprObjectFor _ | ExprKind.ExprVar _ -> true | _ -> false) ->
        let arrays, kernE =
            match lo2.Kind with
            | ExprKind.ExprObjectFor k2 ->
                (match kn.Kind with ExprKind.ExprTuple es -> es | _ -> [kn]), k2
            | ExprKind.ExprMethodFor arrs -> arrs, kn
            | _ -> [], kn
        let walkOperand (a: Expr) =
            match a.Kind with
            | ExprKind.ExprHalo _ | ExprKind.ExprRange _ -> Ok ()
            | _ -> walkExpr fname ctx onVar a
        // a var-bound loop side carries its binding's taint to the result
        (match lo2.Kind with ExprKind.ExprVar n -> onVar n | _ -> ())
        arrays |> List.fold (fun acc a -> acc |> Result.bind (fun () -> walkOperand a)) (Ok ())
        |> Result.bind (fun () ->
            match kernE.Kind with
            | ExprKind.ExprLambda (_, _, body) -> walkExpr fname ctx onVar body
            | ExprKind.ExprReynolds ({ Kind = ExprKind.ExprLambda (_, _, body) }, _) -> walkExpr fname ctx onVar body
            | ExprKind.ExprVar n -> onVar n; Ok ()
            // a var-bound object_for applied to a tuple: the right side is
            // OPERANDS, not a kernel -- walk them for taint
            | ExprKind.ExprTuple es ->
                es |> List.fold (fun acc a -> acc |> Result.bind (fun () -> walkOperand a)) (Ok ())
            | _ -> err fname "differentiating `<@>` supports lambda, reynolds(lambda), named-function, and intrinsic kernels (v1)")
    // Combinator OPERATORS. The syntactic combinator forms (lambda /
    // method_for / ...) are rejected further down, but the operator spellings
    // are ordinary BinOps and would otherwise slip through this walk when both
    // operands are plain names, dying much later in the adjoint with a generic
    // "unsupported expression form" that never says the word combinator.
    | { Kind = ExprKind.ExprBinOp (_, (OpApply | OpBind | OpParallel | OpFusion | OpArrayProd | OpFunctor | OpChoice | OpFallback | OpComposeObj | OpComposeMeth | OpCompose | OpCons), _, _) } ->
        err fname "differentiable code supports straight-line arithmetic, additive `reduce`, and rank-1 recursive arrays (v1); loop-object combinator operators (`<@>`, `>>=`, `<&>`, `<&!>`, `<*>`, `<$>`, `<|>`, `<|:>`, `>>@`, `@>>`, `>>`, `::`) are not differentiable"
    | { Kind = ExprKind.ExprBinOp (_, _, l, r) } ->
        walkExpr fname ctx onVar l |> Result.bind (fun () -> walkExpr fname ctx onVar r)
    | { Kind = ExprKind.ExprApp ({ Kind = ExprKind.ExprVar name }, args) } ->
        // intrinsic, user call (inlined earlier), or array read -- all
        // fine structurally; recurse into arguments.
        args |> List.fold (fun acc a -> acc |> Result.bind (fun () -> walkExpr fname ctx onVar a))
                          (Ok (onVar name))
    | { Kind = ExprKind.ExprApp _ } -> err fname "only named calls and array reads are supported in differentiated code"
    | { Kind = ExprKind.ExprArrayLit elems } ->
        elems |> List.fold (fun acc a -> acc |> Result.bind (fun () -> walkExpr fname ctx onVar a)) (Ok ())
    | { Kind = ExprKind.ExprIf (c, t, f) } ->
        // Forward mode admits branches: the tangent is the branch of
        // tangents under the SAME condition (exact off the boundary,
        // subgradient convention at it -- the primal is not differentiable
        // there either). Reverse mode still refuses: the adjoint would
        // need the taken branch recorded.
        if errMode.Value = "jvp" then
            walkExpr fname ctx onVar c
            |> Result.bind (fun () -> walkExpr fname ctx onVar t)
            |> Result.bind (fun () -> walkExpr fname ctx onVar f)
        else err fname "if/else is not supported in differentiated code yet"
    | { Kind = ExprKind.ExprMatch _ } -> err fname "match is not supported in differentiated code"
    | { Kind = ExprKind.ExprBlock _ } -> err fname "nested block expressions are not supported in differentiated code"
    | { Kind = ExprKind.ExprLet _ } -> err fname "expression-level let is not supported in differentiated code"
    | ConstFill _ -> Ok ()   // literal fill: computes nothing, reads nothing
    | { Kind = ExprKind.ExprReduce _ } ->
        err fname "differentiable code supports straight-line arithmetic, additive `reduce`, and rank-1 recursive arrays (v1); this reduce could not be normalized (only `reduce(A, (+)[, init])` over an array variable or inline literal is differentiable)"
    | { Kind = ExprKind.ExprRecArray _ } ->
        err fname "differentiable code supports straight-line arithmetic, additive `reduce`, and rank-1 recursive arrays (v1); a recursive array is differentiable only as a top-level `let rec` binding in the body"
    | { Kind = ExprKind.ExprLambda _ } | { Kind = ExprKind.ExprMethodFor _ } | { Kind = ExprKind.ExprObjectFor _ } | { Kind = ExprKind.ExprCompute _ } | { Kind = ExprKind.ExprPure _ } ->
        err fname "differentiable code supports straight-line arithmetic, additive `reduce`, and rank-1 recursive arrays (v1); loop-object combinators (lambda/method_for/object_for/compute/pure) are not differentiable"
    | { Kind = ExprKind.ExprTuple _ } -> err fname "tuple values are not supported in differentiated code"
    | { Kind = ExprKind.ExprField _ } -> err fname "struct field access is not supported in differentiated code"
    | _ -> err fname "unsupported expression form in differentiated code"

// Renaming (for inlining)

/// Rename variable references and binders per `ren` (total map application:
/// names not in the map pass through). Only walks the AD-able fragment plus
/// the statement forms; used on ALREADY-VALIDATED callee bodies.
let rec private renameExpr (ren: Map<string, string>) (e: Expr) : Expr =
    let rn n = Map.tryFind n ren |> Option.defaultValue n
    let re k = inheritSpan e k
    match e.Kind with
    | ExprKind.ExprLit _ -> e
    | ExprKind.ExprVar name -> re (ExprVar (rn name))
    | ExprKind.ExprTyped (inner, t) -> re (ExprTyped (renameExpr ren inner, t))
    | ExprKind.ExprUnaryOp (op, inner) -> re (ExprUnaryOp (op, renameExpr ren inner))
    | ExprKind.ExprBinOp (m, op, l, r) -> re (ExprBinOp (m, op, renameExpr ren l, renameExpr ren r))
    | ExprKind.ExprApp (f, args) -> re (ExprApp (renameExpr ren f, args |> List.map (renameExpr ren)))
    | ExprKind.ExprArrayLit elems -> re (ExprArrayLit (elems |> List.map (renameExpr ren)))
    | ExprKind.ExprAssign (l, r) -> re (ExprAssign (renameExpr ren l, renameExpr ren r))
    | ExprKind.ExprDotDot (l, h) -> re (ExprDotDot (renameExpr ren l, renameExpr ren h))
    // constant-fill constructors ride through inlined callee bodies; the
    // count may reference renamed statics-in-scope, so rename inside
    | ExprKind.ExprCompute inner -> re (ExprCompute (renameExpr ren inner))
    | ExprKind.ExprReplicate (c, b) -> re (ExprReplicate (renameExpr ren c, renameExpr ren b))
    | ExprKind.ExprPure inner -> re (ExprPure (renameExpr ren inner))
    | _ -> e

let rec private renameNStmts (ren: Map<string, string>) (stmts: NStmt list) : NStmt list =
    stmts |> List.map (fun s ->
        match s with
        | NLet (n, m, e) ->
            let n' = Map.tryFind n ren |> Option.defaultValue n
            NLet (n', m, renameExpr ren e)
        | NAssign (l, r) -> NAssign (renameExpr ren l, renameExpr ren r)
        | NFor (var, lo, hi, body) ->
            let var' = Map.tryFind var ren |> Option.defaultValue var
            NFor (var', renameExpr ren lo, renameExpr ren hi, renameNStmts ren body))

/// All names BOUND anywhere in a statement list (lets + loop vars).
let rec private boundNames (stmts: NStmt list) : string list =
    stmts |> List.collect (fun s ->
        match s with
        | NLet (n, _, _) -> [n]
        | NAssign _ -> []
        | NFor (var, _, _, body) -> var :: boundNames body)

// ANF + inlining

/// Hoist user-function calls out of nested expression positions into
/// preceding lets, so calls only appear as direct `let x = f(args)` values.
/// Intrinsics and array reads stay in place.
let rec private hoistCalls (fname: string) (ctx: Ctx) (e: Expr) : Result<NStmt list * Expr, string> =
    let recurse = hoistCalls fname ctx
    let re k = inheritSpan e k
    match e.Kind with
    | ExprKind.ExprApp ({ Kind = ExprKind.ExprVar name }, args) when Map.containsKey name ctx.Decls ->
        // hoist arguments first (post-order), then this call
        let folded =
            args |> List.fold (fun acc a ->
                acc |> Result.bind (fun (stmts, args') ->
                    recurse a |> Result.map (fun (s, a') -> (stmts @ s, args' @ [a']))))
                (Ok ([], []))
        folded |> Result.map (fun (stmts, args') ->
            // `__hc` = hoisted call. (Deliberately NOT `__t`: the `__t_` prefix
            // is reserved for forward-mode tangent names, one underscore away.)
            let tmp = fresh ctx "__hc"
            (stmts @ [NLet (tmp, false, re (ExprApp (re (ExprVar name), args')))], re (ExprVar tmp)))
    | ExprKind.ExprApp (f, args) ->
        let folded =
            args |> List.fold (fun acc a ->
                acc |> Result.bind (fun (stmts, args') ->
                    recurse a |> Result.map (fun (s, a') -> (stmts @ s, args' @ [a']))))
                (Ok ([], []))
        folded |> Result.map (fun (stmts, args') -> (stmts, re (ExprApp (f, args'))))
    | ExprKind.ExprBinOp (m, op, l, r) ->
        recurse l |> Result.bind (fun (sl, l') ->
        recurse r |> Result.map (fun (sr, r') -> (sl @ sr, re (ExprBinOp (m, op, l', r')))))
    | ExprKind.ExprUnaryOp (op, inner) ->
        recurse inner |> Result.map (fun (s, i') -> (s, re (ExprUnaryOp (op, i'))))
    | ExprKind.ExprTyped (inner, t) ->
        recurse inner |> Result.map (fun (s, i') -> (s, re (ExprTyped (i', t))))
    | ExprKind.ExprArrayLit elems ->
        let folded =
            elems |> List.fold (fun acc a ->
                acc |> Result.bind (fun (stmts, es) ->
                    recurse a |> Result.map (fun (s, e') -> (stmts @ s, es @ [e']))))
                (Ok ([], []))
        folded |> Result.map (fun (stmts, es) -> (stmts, re (ExprArrayLit es)))
    | _ -> Ok ([], e)

// Pre-normalization of the imperative-free surface constructs. Recursive
// arrays and `reduce` reach grad as ExprRecArray / ExprReduce nodes the
// NFor pipeline never learned to read. This pass is a SOURCE-TO-SOURCE
// rewrite over each differentiated function body that lowers those forms
// into the ACCUMULATION and CONSTRUCTION statement shapes grad already
// differentiates -- additive-only, keeping the BL5500 discipline. It runs
// BEFORE convertStmts, so downstream sees only familiar for-in loops,
// element writes, and additive `+=`.

/// Float-ness of a type annotation (mirrors isFloatTy, needed earlier).
let private preIsFloatTy (t: TypeExpr) : bool =
    match t with
    | TyFloat64 | TyFloat32 -> true
    | TyNamed (("Float" | "Float64" | "Float32"), []) -> true
    | _ -> false

/// Read the static per-axis extents of an `Array<Float like Idx<n>, ...>`
/// annotation. Returns (elem-is-Float, extents) when every axis is a literal
/// `Idx<n>`; None otherwise (non-literal extents / non-array type). v1 admits
/// literal extents only -- named/derived index extents are rejected upstream.
let private arrayLiteralExtents (t: TypeExpr) : (bool * int list) option =
    match t with
    | TyArray (elem, idxs) ->
        let exts =
            idxs |> List.map (fun ix ->
                match ix with
                | TyIdx { Kind = ExprKind.ExprLit (LitInt n) } -> Some (int n)
                | _ -> None)
        if not idxs.IsEmpty && exts |> List.forall Option.isSome then
            Some (preIsFloatTy elem, exts |> List.map Option.get)
        else None
    | _ -> None

/// Does `e` reference the variable `name` anywhere (over the arithmetic +
/// array-read fragment recursive-array slices live in)?
let rec private mentionsVar (name: string) (e: Expr) : bool =
    match e.Kind with
    | ExprKind.ExprVar n -> n = name
    | ExprKind.ExprLit _ -> false
    | ExprKind.ExprTyped (inner, _) | ExprKind.ExprUnaryOp (_, inner) -> mentionsVar name inner
    | ExprKind.ExprBinOp (_, _, l, r) | ExprKind.ExprDotDot (l, r) -> mentionsVar name l || mentionsVar name r
    | ExprKind.ExprApp (f, args) -> mentionsVar name f || List.exists (mentionsVar name) args
    | ExprKind.ExprArrayLit elems -> List.exists (mentionsVar name) elems
    | _ -> false

/// Substitute free references to `name` with the expression `repl` over the
/// same fragment (used to bind a recurrence's step ordinal / prefix name).
let rec private substVar (name: string) (repl: Expr) (e: Expr) : Expr =
    let re k = inheritSpan e k
    match e.Kind with
    | ExprKind.ExprVar n when n = name -> repl
    | ExprKind.ExprVar _ | ExprKind.ExprLit _ -> e
    | ExprKind.ExprTyped (inner, t) -> re (ExprTyped (substVar name repl inner, t))
    | ExprKind.ExprUnaryOp (op, inner) -> re (ExprUnaryOp (op, substVar name repl inner))
    | ExprKind.ExprBinOp (m, op, l, r) -> re (ExprBinOp (m, op, substVar name repl l, substVar name repl r))
    | ExprKind.ExprApp (f, args) -> re (ExprApp (substVar name repl f, args |> List.map (substVar name repl)))
    | ExprKind.ExprArrayLit elems -> re (ExprArrayLit (elems |> List.map (substVar name repl)))
    | ExprKind.ExprDotDot (l, h) -> re (ExprDotDot (substVar name repl l, substVar name repl h))
    | _ -> e

/// Expand a rank-1 recursive-array `let` into the buffer + element-write /
/// accumulation statements the NFor differentiation pipeline handles.
/// Returns the emitted statements and the buffer's leading extent (for the
/// ambient reduce-source extent env). The bound NAME is reused as the buffer
/// so downstream reads of it keep resolving.
///
///   * additive prefix recurrence `prefix :: prefix(n-1) + INC` (with a
///     `zero :: n` seed arm, INC prefix-free) -> a TRIANGULAR accumulation
///     `s(k) += INC[n:=m]` over `m in 1..k+1`. A same-direction adjoint loop
///     is wrong for a genuine scan, so the scan is unrolled into independent
///     scatter-adds -- semantically identical, and exactly differentiable.
///   * prefix-free construction `prefix :: f(n)` -> direct element writes.
///   * anything else (nonlinear recurrence, rank >= 2, no seed) is rejected.
let private expandRecArray (fname: string) (ctx: Ctx)
                           (name: string) (annot: TypeExpr) (def: RecArrayDef)
    : Result<Stmt list * int, string> =
    match arrayLiteralExtents (resolveArrayTy ctx annot) with
    | None ->
        err fname (sprintf "recursive array '%s': a differentiable recursive array needs an `Array<Float like Idx<n>>` annotation with a literal extent (v1)" name)
    | Some (false, _) ->
        err fname (sprintf "recursive array '%s': only Float-element recursive arrays are differentiable (v1)" name)
    | Some (true, [n]) ->
        let bufName = name
        let bufVar = syn (ExprVar bufName)
        let sAt (idxE: Expr) = syn (ExprApp (bufVar, [idxE]))
        let zeros = syn (ExprArrayLit (List.replicate n (fLit 0.0)))
        let bufLet = StmtLet { Mutability = BindMut; Pattern = synPat (PatVar bufName); Type = None; Value = zeros }
        let stepVar = def.StepVar
        let prefixVar = def.PrefixVar
        // `x` is exactly the immediate-predecessor read `prefix(stepVar - 1)`?
        let isPrevPrefixRead (x: Expr) =
            match x.Kind with
            | ExprKind.ExprApp ({ Kind = ExprKind.ExprVar p }, [idx]) when p = prefixVar ->
                (match idx.Kind with
                 | ExprKind.ExprBinOp (_, OpSub, { Kind = ExprKind.ExprVar s }, { Kind = ExprKind.ExprLit (LitInt 1L) }) -> s = stepVar
                 | _ -> false)
            | _ -> false
        let hasPrefix (e: Expr) = mentionsVar prefixVar e
        // additive-prefix slice `prefix(n-1) + REST` / `REST + prefix(n-1)`,
        // REST prefix-free -> Some REST (the per-step increment).
        let additiveRest =
            match def.SliceExpr.Kind with
            | ExprKind.ExprBinOp (_, OpAdd, a, b) when isPrevPrefixRead a && not (hasPrefix b) -> Some b
            | ExprKind.ExprBinOp (_, OpAdd, a, b) when isPrevPrefixRead b && not (hasPrefix a) -> Some a
            | _ -> None
        if errMode.Value = "jvp" && hasPrefix def.SliceExpr then
            // FORWARD lowering of a genuine recurrence: it differentiates in
            // place (the tangent recurrence mirrors it), so ANY smooth slice
            // lowers to the direct element-write loop -- no triangular
            // unroll, no additive restriction, and O(n) where grad's unroll
            // is O(n^2). Prefix reads become reads of the buffer being
            // built; v1 admits the immediate predecessor only -- deeper lags
            // rely on the implicit-zero reads a plain loop cannot supply.
            let rec onlyPrevReads (x: Expr) : bool =
                match x.Kind with
                | ExprKind.ExprApp ({ Kind = ExprKind.ExprVar p }, [idx]) when p = prefixVar ->
                    (match idx.Kind with
                     | ExprKind.ExprBinOp (_, OpSub, { Kind = ExprKind.ExprVar s }, { Kind = ExprKind.ExprLit (LitInt 1L) }) -> s = stepVar
                     | _ -> false)
                | ExprKind.ExprVar p -> p <> prefixVar
                | ExprKind.ExprLit _ -> true
                | ExprKind.ExprTyped (inner, _) | ExprKind.ExprUnaryOp (_, inner) -> onlyPrevReads inner
                | ExprKind.ExprBinOp (_, _, l, r2) | ExprKind.ExprDotDot (l, r2) -> onlyPrevReads l && onlyPrevReads r2
                | ExprKind.ExprApp (fh, args) -> onlyPrevReads fh && List.forall onlyPrevReads args
                | ExprKind.ExprArrayLit es -> List.forall onlyPrevReads es
                | ExprKind.ExprIf (c, t, f2) -> onlyPrevReads c && onlyPrevReads t && onlyPrevReads f2
                | _ -> false
            match def.SeedArm with
            | None -> err fname (sprintf "recursive array '%s': a recurrence needs a `zero :: n` seed arm to be differentiable (v1)" name)
            | Some (seedStep, seedExpr) ->
                if not (onlyPrevReads def.SliceExpr) then
                    err fname (sprintf "recursive array '%s': forward mode differentiates recurrences reading the immediate predecessor `prefix(n - 1)` only (deeper lags rely on implicit-zero reads a direct loop cannot supply, v1)" name)
                else
                    let sliceB = substVar prefixVar bufVar def.SliceExpr
                    let seedWrite = [ StmtExpr (syn (ExprAssign (sAt (iLit 0L), substVar seedStep (iLit 0L) seedExpr))) ]
                    let loop =
                        StmtForIn (stepVar,
                                   syn (ExprDotDot (iLit 1L, iLit (int64 n))),
                                   [ StmtExpr (syn (ExprAssign (sAt (v stepVar), sliceB))) ])
                    Ok (bufLet :: (seedWrite @ [loop]), n)
        else
        match additiveRest, def.SeedArm with
        | Some rest, Some (seedStep, seedExpr) ->
            let seeded = substVar seedStep (iLit 0L) seedExpr
            let isZeroSeed = (match seeded.Kind with ExprKind.ExprLit (LitFloat 0.0) -> true | _ -> false)
            let kVar = fresh ctx "__rk"
            let mVar = fresh ctx "__rm"
            let restM = substVar stepVar (v mVar) rest
            let innerLoop =
                StmtForIn (mVar,
                           syn (ExprDotDot (iLit 1L, add (v kVar) (iLit 1L))),
                           [ StmtExpr (syn (ExprAssign (sAt (v kVar), add (sAt (v kVar)) restM))) ])
            let seedCarry =
                if isZeroSeed then []
                else [ StmtExpr (syn (ExprAssign (sAt (v kVar), add (sAt (v kVar)) seeded))) ]
            let outerLoop =
                StmtForIn (kVar, syn (ExprDotDot (iLit 1L, iLit (int64 n))), seedCarry @ [innerLoop])
            let seedWrite =
                if isZeroSeed then []
                else [ StmtExpr (syn (ExprAssign (sAt (iLit 0L), seeded))) ]
            Ok (bufLet :: (seedWrite @ [outerLoop]), n)
        | None, _ when not (hasPrefix def.SliceExpr) ->
            // Pure construction (no carried state): direct element writes.
            let loopStart, seedStmts =
                match def.SeedArm with
                | Some (seedStep, seedExpr) ->
                    1L, [ StmtExpr (syn (ExprAssign (sAt (iLit 0L), substVar seedStep (iLit 0L) seedExpr))) ]
                | None -> 0L, []
            let loop =
                StmtForIn (stepVar,
                           syn (ExprDotDot (iLit loopStart, iLit (int64 n))),
                           [ StmtExpr (syn (ExprAssign (sAt (v stepVar), def.SliceExpr))) ])
            Ok (bufLet :: (seedStmts @ [loop]), n)
        | _ ->
            err fname (sprintf "recursive array '%s' is not differentiable (v1): only additive prefix recurrences `prefix :: prefix(n-1) + <increment>` (with a `zero :: n` seed arm and a prefix-free increment) and prefix-free construction are supported" name)
    | Some (true, exts) ->
        err fname (sprintf "recursive array '%s': only rank-1 (scalar-slice) recursive arrays are differentiable (v1); a rank-%d recursive array is not supported" name exts.Length)

/// Rewrite additive `reduce(SRC, (+)[, init])` occurrences inside `e` into an
/// accumulator loop (returned as a prefix of statements) plus a reference to
/// the accumulator. Reject non-additive kernels and non-array-literal /
/// non-variable sources (deferred/former reductions), the additive subset
/// matching grad v1. `extents` maps in-scope array names to their extents.
let rec private hoistReduces (fname: string) (ctx: Ctx) (extents: Map<string, int>) (e: Expr)
    : Result<Stmt list * Expr, string> =
    let re k = inheritSpan e k
    let recurse = hoistReduces fname ctx extents
    match e.Kind with
    | ExprKind.ExprReduce (src, kernel, initOpt, axesOpt) ->
        // A PARTIAL fold (`axes = n` with n < rank) produces an ARRAY, not a
        // scalar, so the accumulator-loop rewrite below does not model it.
        // Grad v1 differentiates the rank-1 fold only; an explicit axis count
        // is refused rather than silently rewritten as if it were one.
        (match axesOpt with
         | Some _ -> err fname "reduce with an explicit `axes = n` is not differentiable (v1): grad supports the rank-1 additive fold `reduce(A, (+)[, init])`"
         | None -> Ok ())
        |> Result.bind (fun () ->
        (match kernel.Kind with
         | ExprKind.ExprSection OpAdd -> Ok OpAdd
         // Forward mode folds the product section too: the tangent is a
         // paired fold updated in lockstep before the primal step -- the
         // product rule is local, no tape. Reverse keeps additive-only.
         | ExprKind.ExprSection OpMul when errMode.Value = "jvp" -> Ok OpMul
         | ExprKind.ExprSection _ ->
             err fname (if errMode.Value = "jvp"
                        then "reduce in differentiated code supports the `(+)` and `(*)` section kernels"
                        else "reduce in differentiated code supports only the additive kernel `(+)` (v1)")
         | _ -> err fname "reduce in differentiated code supports only section kernels; lambda kernels are not differentiable (v1)")
        |> Result.bind (fun secOp ->
        recurse src |> Result.bind (fun (srcPre, src') ->
        let initE =
            match initOpt with
            | Some ie -> ie
            | None -> if secOp = OpMul then fLit 1.0 else fLit 0.0
        let combine acc el = syn (ExprBinOp (Elementwise, secOp, acc, el))
        let accName = fresh ctx "__red"
        let accLet = StmtLet { Mutability = BindMut; Pattern = synPat (PatVar accName); Type = None; Value = initE }
        match src'.Kind with
        | ExprKind.ExprArrayLit elems ->
            // Inline literal: UNROLL to per-element scalar accumulations. A
            // read-loop over a bound literal would lose the cotangent --
            // grad treats array-literal lets as constant inits (nothing
            // flows back to the elements) -- so keep each active element in
            // scalar accumulation position, which grad differentiates exactly.
            let adds =
                elems |> List.map (fun el ->
                    StmtExpr (syn (ExprAssign (v accName, combine (v accName) el))))
            Ok (srcPre @ [accLet] @ adds, v accName)
        | ExprKind.ExprVar nm ->
            (match Map.tryFind nm extents with
             | Some cnt ->
                 let kVar = fresh ctx "__rik"
                 let readK = syn (ExprApp (syn (ExprVar nm), [v kVar]))
                 let loop =
                     StmtForIn (kVar,
                                syn (ExprDotDot (iLit 0L, iLit (int64 cnt))),
                                [ StmtExpr (syn (ExprAssign (v accName, combine (v accName) readK))) ])
                 Ok (srcPre @ [accLet; loop], v accName)
             | None -> err fname (sprintf "reduce source '%s' has no statically-known extent in differentiated code; reduce over a param/let array with an `Idx<n>` extent or over an inline array literal (v1)" nm))
        | _ -> err fname "reduce in differentiated code requires an array-variable or inline-array-literal source; deferred/former reductions are not differentiable (v1)")))
    | ExprKind.ExprBinOp (m, op, l, r) ->
        recurse l |> Result.bind (fun (pl, l') ->
        recurse r |> Result.map (fun (pr, r') -> (pl @ pr, re (ExprBinOp (m, op, l', r')))))
    | ExprKind.ExprUnaryOp (op, inner) ->
        recurse inner |> Result.map (fun (p, i') -> (p, re (ExprUnaryOp (op, i'))))
    | ExprKind.ExprTyped (inner, t) ->
        recurse inner |> Result.map (fun (p, i') -> (p, re (ExprTyped (i', t))))
    | ExprKind.ExprAssign (l, r) ->
        recurse r |> Result.map (fun (pr, r') -> (pr, re (ExprAssign (l, r'))))
    | ExprKind.ExprApp (f, args) ->
        args |> List.fold (fun acc a ->
            acc |> Result.bind (fun (ps, args') ->
                recurse a |> Result.map (fun (p, a') -> (ps @ p, args' @ [a']))))
            (Ok ([], []))
        |> Result.map (fun (ps, args') -> (ps, re (ExprApp (f, args'))))
    | ExprKind.ExprArrayLit elems ->
        elems |> List.fold (fun acc a ->
            acc |> Result.bind (fun (ps, es) ->
                recurse a |> Result.map (fun (p, a') -> (ps @ p, es @ [a']))))
            (Ok ([], []))
        |> Result.map (fun (ps, es) -> (ps, re (ExprArrayLit es)))
    | _ -> Ok ([], e)

/// Leading-axis extent of an initializer, when it is statically knowable
/// from the expression's own STRUCTURE rather than from an annotation.
/// Feeds the reduce-lowering's extent env, so `reduce` over a local built
/// by one of these forms recovers its loop bound (previously only inline
/// array literals did, which is why a `replicate`d or `join`ed local could
/// not be reduced in differentiated code).
let rec private staticExtentOf (ctx: Ctx) (env: Map<string, int>) (e: Expr) : int option =
    match e.Kind with
    | ExprKind.ExprArrayLit elems -> Some elems.Length
    | ExprKind.ExprVar n -> Map.tryFind n env
    | ExprKind.ExprTyped (inner, _) | ExprKind.ExprCompute inner
    | ExprKind.ExprGuard (_, inner) -> staticExtentOf ctx env inner
    // replicate(n, _) and its `pure`-filled sibling (grad's ConstFill)
    | ExprKind.ExprReplicate ({ Kind = ExprKind.ExprLit (LitInt n) }, _) -> Some (int n)
    | ExprKind.ExprSequence es | ExprKind.ExprStack es -> Some es.Length
    // join concatenates along the leading axis only when d = 0
    | ExprKind.ExprJoin (parts, 0) ->
        parts |> List.fold (fun acc p ->
            acc |> Option.bind (fun tot -> staticExtentOf ctx env p |> Option.map (fun n -> tot + n)))
            (Some 0)
    // A halo traversal's extent is the SHRUNK interior: N - (max - min)
    // over its literal offsets (shrink is the only boundary policy).
    | ExprKind.ExprHalo (inner, { Kind = ExprKind.ExprArrayLit offs }) ->
        (match resolveTy ctx inner with
         | TyIdx { Kind = ExprKind.ExprLit (LitInt n) } ->
             let lits =
                 offs |> List.map (fun o ->
                     match o.Kind with
                     | ExprKind.ExprLit (LitInt k) -> Some (int k)
                     | ExprKind.ExprUnaryOp (OpNeg, { Kind = ExprKind.ExprLit (LitInt k) }) -> Some (-(int k))
                     | _ -> None)
             if not lits.IsEmpty && lits |> List.forall Option.isSome then
                 let vs = lits |> List.map Option.get
                 Some (int n - (List.max vs - List.min vs))
             else None
         | _ -> None)
    // A map's leading extent is its FIRST operand's (C2): the loop iterates
    // the operand index spaces in order, so a reduce over the result knows
    // its bound whenever the operand does.
    | ExprKind.ExprBinOp (_, OpApply, { Kind = ExprKind.ExprMethodFor (first :: _) }, _) ->
        staticExtentOf ctx env first
    // the `object_for(k) <@> operands` spelling carries operands on the right
    | ExprKind.ExprBinOp (_, OpApply, { Kind = ExprKind.ExprObjectFor _ }, args) ->
        (match args.Kind with
         | ExprKind.ExprTuple (first :: _) -> staticExtentOf ctx env first
         | _ -> staticExtentOf ctx env args)
    // a LET-BOUND loop applied by name: the binding's extent was recorded
    // under the loop's name (method_for case); otherwise the right side is
    // the operand list (object_for case)
    | ExprKind.ExprBinOp (_, OpApply, { Kind = ExprKind.ExprVar n }, args) ->
        (match Map.tryFind n env with
         | Some e -> Some e
         | None ->
             match args.Kind with
             | ExprKind.ExprTuple (first :: _) -> staticExtentOf ctx env first
             | _ -> staticExtentOf ctx env args)
    // a bare loop binding's extent is its leading operand's
    | ExprKind.ExprMethodFor (first :: _) -> staticExtentOf ctx env first
    | _ -> None

/// The pre-pass proper: rewrite one function body's statements, expanding
/// recursive-array lets and hoisting reduces, threading an extent env so
/// reduce sources can recover their loop bound.
let private preNormalizeBody (fname: string) (ctx: Ctx) (fd: FunctionDecl) : Result<Expr, string> =
    let paramExtents =
        fd.Params |> List.choose (fun p ->
            match p.Type with
            | Some t -> (match arrayLiteralExtents (resolveArrayTy ctx t) with Some (true, [n]) -> Some (p.Name, n) | _ -> None)
            | None -> None)
        |> Map.ofList
    let stmts0, finalOpt =
        match fd.Body.Kind with
        | ExprKind.ExprBlock (ss, fe) -> ss, fe
        | _ -> [], Some fd.Body
    let rec goStmts (env: Map<string, int>) (ss: Stmt list) : Result<Map<string, int> * Stmt list, string> =
        ss |> List.fold (fun acc s ->
            acc |> Result.bind (fun (env, outp) ->
                match unwrapStmt s with
                | StmtLet { Value = { Kind = ExprKind.ExprRecArray def }; Type = Some annot; Pattern = { Kind = PatternKind.PatVar nm } } ->
                    expandRecArray fname ctx nm annot def
                    |> Result.map (fun (emitted, ext) -> (Map.add nm ext env, outp @ emitted))
                | StmtLet { Value = { Kind = ExprKind.ExprRecArray _ } } ->
                    err fname "recursive array must bind a single annotated name to be differentiable (v1)"
                | StmtLet ({ Pattern = { Kind = PatternKind.PatVar nm } } as b) ->
                    hoistReduces fname ctx env b.Value |> Result.map (fun (pre, value') ->
                        let env' =
                            let byAnn =
                                match b.Type with
                                | Some t -> (match arrayLiteralExtents (resolveArrayTy ctx t) with Some (true, [n]) -> Some n | _ -> None)
                                | None -> None
                            let byLit = staticExtentOf ctx env value'
                            match (match byAnn with Some _ -> byAnn | None -> byLit) with
                            | Some cnt -> Map.add nm cnt env
                            | None -> env
                        (env', outp @ pre @ [StmtLet { b with Value = value' }]))
                | StmtLet b ->
                    hoistReduces fname ctx env b.Value |> Result.map (fun (pre, value') ->
                        (env, outp @ pre @ [StmtLet { b with Value = value' }]))
                | StmtExpr ex ->
                    hoistReduces fname ctx env ex |> Result.map (fun (pre, ex') ->
                        (env, outp @ pre @ [StmtExpr ex']))
                | StmtAssign (lhs, op, rhs) ->
                    hoistReduces fname ctx env rhs |> Result.map (fun (pre, rhs') ->
                        (env, outp @ pre @ [StmtAssign (lhs, op, rhs')]))
                | StmtForIn (var, range, body) ->
                    goStmts env body |> Result.map (fun (_, body') ->
                        (env, outp @ [StmtForIn (var, range, body')]))
                | StmtSpanned _ -> Ok (env, outp @ [s])))
            (Ok (env, []))
    goStmts paramExtents stmts0 |> Result.bind (fun (env, stmts') ->
        match finalOpt with
        | Some fe ->
            hoistReduces fname ctx env fe |> Result.map (fun (pre, fe') ->
                inheritSpan fd.Body (ExprBlock (stmts' @ pre, Some fe')))
        | None ->
            Ok (inheritSpan fd.Body (ExprBlock (stmts', None))))

/// Normalize + inline a function body to the flat NStmt fragment:
/// all user calls inlined, all statements validated.
let rec private normalizeBody (fname: string) (ctx: Ctx) (depth: int) (fd: FunctionDecl)
    : Result<NStmt list * Expr, string> =
    if depth > 32 then
        err fname "call inlining exceeded depth 32 (recursive functions are not differentiable)"
    else
    // Lower the imperative-free surface constructs (recursive arrays, reduce)
    // into accumulation/construction statements before the NFor pipeline runs.
    preNormalizeBody fname ctx fd |> Result.bind (fun body' ->
    convertBody fname body' |> Result.bind (fun (stmts, finalE) ->
    // hoist calls inside the final expression too
    hoistCalls fname ctx finalE |> Result.bind (fun (finalHoist, finalE') ->
    let rec normStmts (ss: NStmt list) : Result<NStmt list, string> =
        ss |> List.fold (fun acc s ->
            acc |> Result.bind (fun outStmts ->
                match s with
                // DIRECT user-call let: the call is already in inlinable
                // position -- hoist only inside its ARGUMENTS, then inline.
                // (Hoisting the call itself would create `let tmp = f(..)`
                // and re-normalizing that let would hoist again, forever.)
                | NLet (name, isMut, { Kind = ExprKind.ExprApp ({ Kind = ExprKind.ExprVar callee }, args) }) when Map.containsKey callee ctx.Decls ->
                    let argsFolded =
                        args |> List.fold (fun acc2 a ->
                            acc2 |> Result.bind (fun (stmts, args') ->
                                hoistCalls fname ctx a
                                |> Result.map (fun (s2, a') -> (stmts @ s2, args' @ [a']))))
                            (Ok ([], []))
                    argsFolded |> Result.bind (fun (argHoists, args') ->
                    normStmts argHoists |> Result.bind (fun argHoists' ->
                    inlineCall fname ctx depth callee args' name isMut
                    |> Result.map (fun inlined -> outStmts @ argHoists' @ inlined)))
                | NLet (name, isMut, value) ->
                    hoistCalls fname ctx value |> Result.bind (fun (hoisted, value') ->
                    // `hoisted` contains only direct-call lets, which the
                    // arm above inlines without further hoisting.
                    normStmts hoisted |> Result.map (fun hoisted' ->
                        outStmts @ hoisted' @ [NLet (name, isMut, value')]))
                | NAssign (lhs, rhs) ->
                    hoistCalls fname ctx rhs |> Result.bind (fun (hoisted, rhs') ->
                    normStmts hoisted |> Result.map (fun hoisted' ->
                        outStmts @ hoisted' @ [NAssign (lhs, rhs')]))
                | NFor (var, lo, hi, body) ->
                    normStmts body |> Result.map (fun body' ->
                        outStmts @ [NFor (var, lo, hi, body')])))
            (Ok [])
    normStmts (stmts @ finalHoist) |> Result.map (fun ns -> (ns, finalE')))))

/// Inline `let target = callee(args)`: bind arguments to fresh param names,
/// splice the callee's own normalized body with all its binders renamed,
/// and bind the callee's final expression to `target` (or rename in place
/// when the final expression is just a local variable -- avoiding an array
/// alias, which the adjoint bookkeeping cannot track).
and private inlineCall (fname: string) (ctx: Ctx) (depth: int)
                       (callee: string) (args: Expr list)
                       (target: string) (targetMut: bool)
    : Result<NStmt list, string> =
    let fd = ctx.Decls.[callee]
    if fd.IsStatic then err fname (sprintf "cannot differentiate through static function '%s'" callee)
    elif fd.Params |> List.exists (fun p -> p.Mutability = Mutable) then
        err fname (sprintf "cannot differentiate through '%s': mut-parameter functions are not inlinable (v1)" callee)
    elif args.Length <> fd.Params.Length then
        err fname (sprintf "'%s' called with %d arguments, expects %d" callee args.Length fd.Params.Length)
    else
    normalizeBody fname ctx (depth + 1) fd |> Result.bind (fun (calleeStmts, calleeFinal) ->
        let tag = fresh ctx "__in"
        // Param binding: plain-var arguments bind by RENAMING the callee
        // param to the caller's variable (no let) -- this is what routes
        // array cotangents straight to the caller's d-buffers and avoids
        // array-alias lets, which the adjoint bookkeeping rejects.
        // Non-var arguments (scalar expressions) bind through a fresh let.
        let paramBinds =
            List.zip fd.Params args
            |> List.map (fun (p, a) ->
                match a.Kind with
                | ExprKind.ExprVar argName -> (p.Name, argName, None)
                | _ -> (p.Name, sprintf "%s_%s" tag p.Name, Some a))
        let paramRen =
            paramBinds |> List.map (fun (pn, target, _) -> (pn, target)) |> Map.ofList
        let localRen =
            boundNames calleeStmts
            |> List.distinct
            |> List.map (fun n -> (n, sprintf "%s_%s" tag n))
            |> Map.ofList
        let ren = Map.fold (fun acc k v -> Map.add k v acc) paramRen localRen
        let renStmts = renameNStmts ren calleeStmts
        let renFinal = renameExpr ren calleeFinal
        let paramLets =
            paramBinds |> List.choose (fun (_, target, argOpt) ->
                argOpt |> Option.map (fun a -> NLet (target, false, a)))
        match renFinal.Kind with
        | ExprKind.ExprVar localName when (localRen |> Map.exists (fun _ v2 -> v2 = localName)) ->
            // Final expr is a callee-local: rename that local to the target
            // name instead of emitting `let target = local` (array-alias).
            let ren2 = Map.ofList [(localName, target)]
            Ok (paramLets @ renameNStmts ren2 renStmts)
        | _ ->
            Ok (paramLets @ renStmts @ [NLet (target, targetMut, renFinal)]))

// Classification: differentiable variables, array-ness

let private isFloatTy (t: TypeExpr) : bool =
    match t with
    | TyFloat64 | TyFloat32 -> true
    | TyNamed (("Float" | "Float64" | "Float32"), []) -> true
    | _ -> false

type private ParamClass =
    | DiffArray
    | DiffScalar
    | NonDiff

/// Classify one parameter. Unit-carrying Floats and complex types get
/// EXPLICIT refusals rather than the NonDiff fall-through: silently treating
/// `y: Float<meters>` as non-differentiable drops its partial from the
/// gradient with no diagnostic -- the same wrong-answer class as an
/// unknown-derivative intrinsic, and worse than refusing.
let private classifyParam (fname: string) (ctx: Ctx) (p: ParamDecl) : Result<ParamClass, string> =
    match p.Type with
    | None -> err fname (sprintf "parameter '%s' must have a type annotation" p.Name)
    | Some t0 ->
        let refuseUnits (what: string) =
            err fname (sprintf "parameter '%s' %s: unit-carrying parameters are not differentiable (v1) -- a gradient's units are <loss>/<parameter>, which the grad ABI (buffer type = parameter type) cannot express; strip the unit at the call boundary or compute the unit-carrying part outside the differentiated function" p.Name what)
        let refuseComplex (what: string) =
            err fname (sprintf "parameter '%s' %s: complex parameters are not differentiable (v1); complex derivatives need a holomorphic/Wirtinger convention the AD subset does not define" p.Name what)
        let t = resolveTy ctx t0
        match t with
        | _ when isFloatTy t -> Ok DiffScalar
        | TyNamed (("Float" | "Float64" | "Float32"), _ :: _) ->
            // FORWARD mode supports units correctly for free: a tangent has
            // the primal's type verbatim, units included. Reverse cannot --
            // a gradient's units are <loss>/<param>, which the grad ABI
            // (buffer type = parameter type) cannot express.
            if errMode.Value = "jvp" then Ok DiffScalar else refuseUnits "carries units"
        | TyComplex64 | TyComplex128 | TyNamed (("Complex64" | "Complex128"), _) -> refuseComplex "is complex"
        | TyArray (elem, _) ->
            let el = resolveTy ctx elem
            if isFloatTy el then Ok DiffArray
            else
                (match el with
                 | TyNamed (("Float" | "Float64" | "Float32"), _ :: _) ->
                     if errMode.Value = "jvp" then Ok DiffArray else refuseUnits "is an array of unit-carrying Floats"
                 | TyComplex64 | TyComplex128 | TyNamed (("Complex64" | "Complex128"), _) -> refuseComplex "is a complex array"
                 | _ -> Ok NonDiff)
        | _ -> Ok NonDiff

/// Zero value matching an array literal's (or constant fill's) shape.
let rec private zerosLikeLiteral (e: Expr) : Expr option =
    match e with
    | { Kind = ExprKind.ExprArrayLit elems } ->
        let zs = elems |> List.map (fun el ->
            match zerosLikeLiteral el with
            | Some z -> z
            | None -> fLit 0.0)
        Some (inheritSpan e (ExprArrayLit zs))
    | ConstFill (cnt, _) -> Some (zeroFill cnt)
    | _ -> None

/// Zero value for a differentiable param's declared type (arrays need
/// literal extents in v1 -- callers allocate those buffers, so this is only
/// used for LOCAL d-vars, which come from literals instead).
let private zerosOfType (fname: string) (t: TypeExpr) : Result<Expr, string> =
    let rec go t =
        match t with
        | _ when isFloatTy t -> Ok (fLit 0.0)
        | TyArray (elem, idxs) ->
            let extents =
                idxs |> List.map (fun ix ->
                    match ix with
                    | TyIdx { Kind = ExprKind.ExprLit (LitInt n) } -> Ok (int n)
                    | _ -> err fname "differentiable arrays need literal Idx<n> extents (v1)")
            let folded =
                extents |> List.fold (fun acc r ->
                    acc |> Result.bind (fun ns -> r |> Result.map (fun n -> ns @ [n]))) (Ok [])
            folded |> Result.bind (fun ns ->
                go elem |> Result.map (fun z ->
                    ns |> List.rev |> List.fold (fun inner n -> syn (ExprArrayLit (List.replicate n inner))) z))
        | _ -> err fname "cannot build a zero cotangent for this type"
    go t

/// Partials of the two-argument intrinsics, per operand -- the binary sibling
/// of `derivRule`, whose signature (name -> Expr -> Expr option) is
/// structurally unary and has nowhere to put a second operand. Returns
/// (d/dFirst, d/dSecond) as expressions of the FORWARD operands; both AD
/// modes consume it the same way (reverse multiplies by the cotangent,
/// forward by the operand tangents).
///   atan2(y, x): d/dy =  x/(x^2+y^2),  d/dx = -y/(x^2+y^2)
///   log_base(x, b) = log x / log b:
///                    d/dx = 1/(x log b),  d/db = -log x/(b (log b)^2)
let private binaryDerivRule (name: string) (a: Expr) (b: Expr) : Expr * Expr =
    match name with
    | "atan2" ->
        let denom = add (mul a a) (mul b b)
        (div b denom, neg (div a denom))
    | _ ->  // log_base(x, b)
        let lb = call "log" [b]
        (div (fLit 1.0) (mul a lb),
         neg (div (call "log" [a]) (mul b (mul lb lb))))

// Taint analysis

/// Variables carrying differentiable (Float) dataflow, and which of those
/// are arrays. Two passes for loop-carried taint.
let private analyze (fname: string) (ctx: Ctx)
                    (diffParams: Set<string>) (arrayParams: Set<string>)
                    (stmts: NStmt list) (finalE: Expr)
    : Result<Set<string> * Set<string>, string> =
    let mutable diff = diffParams
    let mutable arrays = arrayParams
    let touches (e: Expr) : Result<bool, string> =
        let mutable hit = false
        walkExpr fname ctx (fun n -> if Set.contains n diff then hit <- true) e
        |> Result.map (fun () -> hit)
    let rec pass (ss: NStmt list) : Result<unit, string> =
        ss |> List.fold (fun acc s ->
            acc |> Result.bind (fun () ->
                match s with
                | NLet (name, _, value) ->
                    (match value with
                     | { Kind = ExprKind.ExprArrayLit _ } | ConstFill _ -> arrays <- Set.add name arrays
                     | { Kind = ExprKind.ExprVar src } when Set.contains src arrays ->
                         arrays <- Set.add name arrays
                     // C1: a local bound to a linear combinator is an array
                     // if the form produces one -- without this its element
                     // reads would silently yield no tangent.
                     | _ when producesArray arrays value -> arrays <- Set.add name arrays
                     | _ -> ())
                    // FLOAT array literals are differentiable carriers even
                    // before any diff flow reaches them (their cotangents
                    // must exist). Int-literal tables (index/offset data,
                    // e.g. ML-elaboration path tables) are not -- their
                    // reads only ever appear in index and bound positions.
                    let rec isFloatLit (e: Expr) =
                        match e.Kind with
                        | ExprKind.ExprArrayLit es -> es |> List.forall isFloatLit
                        | ExprKind.ExprLit (LitFloat _) -> true
                        | _ -> false
                    touches value |> Result.map (fun t ->
                        if t then diff <- Set.add name diff
                        match value with
                        | { Kind = ExprKind.ExprArrayLit _ } when isFloatLit value -> diff <- Set.add name diff
                        | ConstFill (_, LitFloat _) -> diff <- Set.add name diff
                        | _ -> ())
                | NAssign (lhs, rhs) ->
                    touches rhs |> Result.map (fun t ->
                        if t then
                            match lhs.Kind with
                            | ExprKind.ExprVar n -> diff <- Set.add n diff
                            | ExprKind.ExprApp ({ Kind = ExprKind.ExprVar a }, _) -> diff <- Set.add a diff
                            | _ -> ())
                | NFor (_, _, _, body) -> pass body))
            (Ok ())
    pass stmts
    |> Result.bind (fun () -> pass stmts)     // second pass: loop-carried
    |> Result.bind (fun () -> touches finalE)
    |> Result.bind (fun finalTouches ->
        if not finalTouches then
            err fname "the returned value does not depend on any differentiable parameter"
        else Ok (diff, arrays))

// Restriction checks (accumulator discipline)

/// Names assigned (either form) anywhere in a statement list.
let rec private assignedNames (stmts: NStmt list) : Set<string> =
    stmts |> List.fold (fun acc s ->
        match s with
        | NLet _ -> acc
        | NAssign ({ Kind = ExprKind.ExprVar n }, _) -> Set.add n acc
        | NAssign ({ Kind = ExprKind.ExprApp ({ Kind = ExprKind.ExprVar a }, _) }, _) -> Set.add a acc
        | NAssign _ -> acc
        | NFor (_, _, _, body) -> Set.union acc (assignedNames body)) Set.empty

/// `x = x + e` / `x = x - e` (and element forms), the additive-self
/// pattern, which the same-direction adjoint loop handles exactly.
/// Returns (sign, e) when matched: +1.0 for add; -1.0 for sub.
let private additiveSelf (lhs: Expr) (rhs: Expr) : (float * Expr) option =
    let rec sameLhs (a: Expr) (b: Expr) =
        match a, b with
        | { Kind = ExprKind.ExprVar x }, { Kind = ExprKind.ExprVar y } -> x = y
        | { Kind = ExprKind.ExprApp ({ Kind = ExprKind.ExprVar x }, ix) }, { Kind = ExprKind.ExprApp ({ Kind = ExprKind.ExprVar y }, iy) } ->
            x = y && ix.Length = iy.Length && List.forall2 sameLhs ix iy
        | { Kind = ExprKind.ExprLit l1 }, { Kind = ExprKind.ExprLit l2 } -> l1 = l2
        | { Kind = ExprKind.ExprBinOp (_, o1, a1, b1) }, { Kind = ExprKind.ExprBinOp (_, o2, a2, b2) } ->
            o1 = o2 && sameLhs a1 a2 && sameLhs b1 b2
        | { Kind = ExprKind.ExprTyped (i1, _) }, i2 | i1, { Kind = ExprKind.ExprTyped (i2, _) } -> sameLhs i1 i2
        | _ -> false
    match rhs.Kind with
    | ExprKind.ExprBinOp (_, OpAdd, l, e) when sameLhs l lhs -> Some (1.0, e)
    | ExprKind.ExprBinOp (_, OpAdd, e, l) when sameLhs l lhs -> Some (1.0, e)
    | ExprKind.ExprBinOp (_, OpSub, l, e) when sameLhs l lhs -> Some (-1.0, e)
    | _ -> None

/// Straight-line ordering discipline: the adjoint sweep re-evaluates
/// forward expressions, which see each variable's FINAL value. That is only
/// sound when no differentiable expression reads a mutable variable that is
/// written again LATER in forward order. Whole loops count as one position
/// (intra-loop ordering is checkLoopDiscipline's job). The additive-self
/// lhs occurrence is exempt (its derivative is 1 regardless of value).
let private checkWriteAfterRead (fname: string) (ctx: Ctx) (stmts: NStmt list) : Result<unit, string> =
    // last write position per var, loops opaque
    let lastWrite = System.Collections.Generic.Dictionary<string, int>()
    stmts |> List.iteri (fun i s ->
        let record n = lastWrite.[n] <- i
        match s with
        | NLet _ -> ()
        | NAssign ({ Kind = ExprKind.ExprVar n }, _) -> record n
        | NAssign ({ Kind = ExprKind.ExprApp ({ Kind = ExprKind.ExprVar a }, _) }, _) -> record a
        | NAssign _ -> ()
        | NFor (_, _, _, body) -> assignedNames body |> Set.iter record)
    let checkExprAt (i: int) (e: Expr) : Result<unit, string> =
        let mutable bad = None
        walkExpr fname ctx (fun n ->
            if bad.IsNone then
                match lastWrite.TryGetValue n with
                | true, j when j > i -> bad <- Some n
                | _ -> ()) e
        |> Result.bind (fun () ->
            match bad with
            | Some n -> err fname (sprintf "'%s' is read here but written again later; the reverse sweep re-evaluates forward expressions at FINAL values, so read-then-rewrite of a mutable is not differentiable (bind a fresh let instead)" n)
            | None -> Ok ())
    stmts |> List.mapi (fun i s -> (i, s)) |> List.fold (fun acc (i, s) ->
        acc |> Result.bind (fun () ->
            match s with
            | NLet (_, _, value) -> checkExprAt i value
            | NAssign (lhs, rhs) ->
                (match additiveSelf lhs rhs with
                 | Some (_, e) -> checkExprAt i e
                 | None -> checkExprAt i rhs)
                |> Result.bind (fun () ->
                    // index expressions of an element write
                    match lhs.Kind with
                    | ExprKind.ExprApp (_, idxs) ->
                        idxs |> List.fold (fun a ix -> a |> Result.bind (fun () -> checkExprAt i ix)) (Ok ())
                    | _ -> Ok ())
            | NFor (_, lo, hi, body) ->
                checkExprAt i lo
                |> Result.bind (fun () -> checkExprAt i hi)
                |> Result.bind (fun () ->
                    // expressions INSIDE the loop must not read vars written
                    // after the loop either
                    let rec checkBody ss =
                        ss |> List.fold (fun a s2 ->
                            a |> Result.bind (fun () ->
                                match s2 with
                                | NLet (_, _, value) -> checkExprAt i value
                                | NAssign (l2, r2) ->
                                    (match additiveSelf l2 r2 with
                                     | Some (_, e) -> checkExprAt i e
                                     | None -> checkExprAt i r2)
                                | NFor (_, l2, h2, b2) ->
                                    checkExprAt i l2
                                    |> Result.bind (fun () -> checkExprAt i h2)
                                    |> Result.bind (fun () -> checkBody b2)))
                            (Ok ())
                    checkBody body)))
        (Ok ())

/// Non-additive reassignment of a differentiable SCALAR is rejected
/// everywhere: its adjoint needs the pre-statement value, which the
/// re-evaluating reverse sweep cannot see. (Array ELEMENT writes stay legal
/// as construction; their adjoints never read the overwritten value.)
let private checkNoScalarOverwrite (fname: string) (diff: Set<string>) (stmts: NStmt list) : Result<unit, string> =
    let rec check ss =
        ss |> List.fold (fun acc s ->
            acc |> Result.bind (fun () ->
                match s with
                | NAssign (({ Kind = ExprKind.ExprVar x } as lhs), rhs) when Set.contains x diff ->
                    (match additiveSelf lhs rhs with
                     | Some _ -> Ok ()
                     | None -> err fname (sprintf "non-additive reassignment of '%s' is not differentiable (the reverse sweep sees final values); bind a fresh `let` instead" x))
                | NFor (_, _, _, body) -> check body
                | _ -> Ok ()))
            (Ok ())
    check stmts

/// Inside a loop, expressions may not READ accumulators mutated in the same
/// loop UNLESS the accumulator is DECLARED in that same loop body: the
/// adjoint loop replays the whole body, reconstructing loop-local values
/// per iteration, so reads of loop-local accumulators are exact.
/// Accumulators that OUTLIVE the loop have unrecoverable mid-iteration
/// values and stay read-banned. The additive-self lhs occurrence is exempt.
let private checkLoopDiscipline (fname: string) (ctx: Ctx) (loops: NStmt list) : Result<unit, string> =
    let rec check (ss: NStmt list) (inLoop: bool) (loopAccums: Set<string>) : Result<unit, string> =
        ss |> List.fold (fun acc s ->
            acc |> Result.bind (fun () ->
                match s with
                | NLet (_, _, value) when inLoop ->
                    let mutable bad = None
                    walkExpr fname ctx (fun n -> if Set.contains n loopAccums && bad.IsNone then bad <- Some n) value
                    |> Result.bind (fun () ->
                        match bad with
                        | Some n -> err fname (sprintf "loop-body let reads accumulator '%s' mutated in the same loop (mid-iteration values are not recoverable; restructure)" n)
                        | None -> Ok ())
                | NLet _ -> Ok ()
                | NAssign (lhs, rhs) when inLoop ->
                    match additiveSelf lhs rhs with
                    | Some (_, e) ->
                        let mutable bad = None
                        walkExpr fname ctx (fun n -> if Set.contains n loopAccums && bad.IsNone then bad <- Some n) e
                        |> Result.bind (fun () ->
                            match bad with
                            | Some n -> err fname (sprintf "accumulation reads accumulator '%s' mutated in the same loop; restructure" n)
                            | None -> Ok ())
                    | None ->
                        match lhs.Kind with
                        | ExprKind.ExprVar x ->
                            err fname (sprintf "loop-carried reassignment of '%s' is not additive (`%s = %s +/- e`); only additive accumulation is differentiable in loops (v1)" x x x)
                        | ExprKind.ExprApp ({ Kind = ExprKind.ExprVar a }, _) ->
                            // plain element write inside a loop: allowed as
                            // construction, but the rhs may not read the
                            // array being written (array recurrence)
                            let mutable bad = false
                            walkExpr fname ctx (fun n -> if n = a then bad <- true) rhs
                            |> Result.bind (fun () ->
                                if bad then err fname (sprintf "array recurrence on '%s' (element write whose rhs reads the same array) is not differentiable (v1)" a)
                                else Ok ())
                        | _ -> err fname "unsupported assignment target"
                | NAssign _ -> Ok ()
                | NFor (_, _, _, body) ->
                    // loop-local declarations are replay-reconstructed --
                    // exclude them from the read ban
                    let declared = boundNames body |> Set.ofList
                    let accums = Set.difference (assignedNames body) declared
                    check body true (if inLoop then Set.union loopAccums accums else accums)))
            (Ok ())
    check loops false Set.empty

// The reverse sweep

let private dName (n: string) = "__g_" + n

type private RevCtx = {
    Fname: string
    Ctx: Ctx
    Diff: Set<string>
    Arrays: Set<string>
    /// Every name a bare `name(args)` may legitimately refer to WITHOUT a
    /// derivative rule: params (incl. int arrays), function-local binders,
    /// and module-level value bindings. A named application outside this set
    /// (and outside the intrinsic/decl arms above) is an unknown call and is
    /// refused rather than silently zero-differentiated.
    Known: Set<string>
    /// Declared index types per array PARAMETER, so the C2 map rule can
    /// spell `range<I>` over an operand's own index space (which also keeps
    /// the emitted reads properly tagged, unlike a raw extent).
    ArrayIdxTys: Map<string, TypeExpr list>
    /// LET-BOUND LOOP OBJECTS (`let Lp = method_for(a, b)`): the idiomatic
    /// style stores the loop as a value and applies it later. The tangent
    /// walker resolves the binding at the application site; the binding
    /// itself gets no tangent (a loop object is a deferred iteration, not
    /// data).
    LoopBindings: Map<string, Expr>
}

/// Emit `d += cot`-style accumulation onto a cotangent target.
let private accum (target: Expr) (cot: Expr) : NStmt =
    NAssign (target, add target cot)

/// Bind a nontrivial cotangent expression to a temp so the adjoints of the
/// operands reference a variable, not a duplicated tree. Returns the
/// prefix statement(s) and the expression to use as the cotangent.
let private bindCot (rc: RevCtx) (cot: Expr) : NStmt list * Expr =
    match cot.Kind with
    | ExprKind.ExprLit _ | ExprKind.ExprVar _ -> [], cot
    | _ ->
        let c = fresh rc.Ctx "__c"
        [NLet (c, false, cot)], inheritSpan cot (ExprVar c)

/// Adjoint statements for expression `e` with cotangent `cot`.
/// Every returned statement accumulates into a `__g_*` target.
let rec private adjointOf (rc: RevCtx) (e: Expr) (cot: Expr) : Result<NStmt list, string> =
    match e.Kind with
    | ExprKind.ExprLit _ -> Ok []
    | ExprKind.ExprTyped (inner, _) -> adjointOf rc inner cot
    | ExprKind.ExprVar x ->
        if Set.contains x rc.Diff then Ok [accum (v (dName x)) cot] else Ok []
    | ExprKind.ExprApp ({ Kind = ExprKind.ExprVar a }, idxs) when Set.contains a rc.Arrays ->
        if Set.contains a rc.Diff then
            Ok [accum (inheritSpan e (ExprApp (v (dName a), idxs))) cot]
        else Ok []
    | ExprKind.ExprApp ({ Kind = ExprKind.ExprVar name }, [u]) when isMathIntrinsic name
                                       && not (Map.containsKey name rc.Ctx.Decls) ->
        (match derivRule name u with
         | None when Set.contains name zeroDerivIntrinsics -> Ok []   // floor/ceil
         | None ->
             // An intrinsic with no derivative rule. REFUSING is the point:
             // falling through to `Ok []` here would hand back a gradient that
             // silently drops this term (`digamma` would differentiate to zero).
             Error (sprintf "'%s' has no derivative rule, so it cannot appear in a differentiated function (its derivative is not expressible in the AD-able subset). Compute it outside the function passed to ad.grad, or pass the value in as a parameter" name)
         | Some d ->
             let pre, c = bindCot rc cot
             adjointOf rc u (mul c d) |> Result.map (fun ss -> pre @ ss))
    // BINARY intrinsics: chain rule per operand via the shared partial table.
    // Without this arm both would fall to the unknown-call refusal below.
    | ExprKind.ExprApp ({ Kind = ExprKind.ExprVar name }, [a; b]) when isBinaryMathIntrinsic name
                                       && not (Map.containsKey name rc.Ctx.Decls) ->
        let pre, c = bindCot rc cot
        let (dA, dB) = binaryDerivRule name a b
        adjointOf rc a (mul c dA) |> Result.bind (fun sa ->
        adjointOf rc b (mul c dB) |> Result.map (fun sb -> pre @ sa @ sb))
    | ExprKind.ExprApp ({ Kind = ExprKind.ExprVar name }, _) ->
        // Array read of non-diff data (a param, local, or module binding):
        // genuinely no adjoint. Anything ELSE named here is a call the
        // transform has no rule for -- `abs`, `min`, an imported function --
        // and REFUSING is the point: falling through to `Ok []` would hand
        // back a gradient that silently drops this term (the same
        // wrong-answer class as the digamma refusal above).
        if Set.contains name rc.Known then Ok []
        else
            Error (sprintf "cannot differentiate through '%s': it is not a same-module function, a math intrinsic with a derivative rule, or an array in scope, so its contribution would silently vanish from the gradient. Compute it outside the function passed to ad.grad, or pass the value in as a parameter" name)
    | ExprKind.ExprUnaryOp (OpNeg, inner) -> adjointOf rc inner (neg cot)
    | ExprKind.ExprBinOp (_, OpAdd, l, r) ->
        adjointOf rc l cot |> Result.bind (fun sl ->
        adjointOf rc r cot |> Result.map (fun sr -> sl @ sr))
    | ExprKind.ExprBinOp (_, OpSub, l, r) ->
        adjointOf rc l cot |> Result.bind (fun sl ->
        adjointOf rc r (neg cot) |> Result.map (fun sr -> sl @ sr))
    | ExprKind.ExprBinOp (_, OpMul, l, r) ->
        let pre, c = bindCot rc cot
        adjointOf rc l (mul c r) |> Result.bind (fun sl ->
        adjointOf rc r (mul c l) |> Result.map (fun sr -> pre @ sl @ sr))
    | ExprKind.ExprBinOp (_, OpDiv, l, r) ->
        let pre, c = bindCot rc cot
        adjointOf rc l (div c r) |> Result.bind (fun sl ->
        adjointOf rc r (neg (div (mul c l) (mul r r))) |> Result.map (fun sr -> pre @ sl @ sr))
    | ExprKind.ExprBinOp (_, OpCaret, b, { Kind = ExprKind.ExprLit (LitInt n) }) when int n >= 0 ->
        // Constant natural exponent: emit the closed form directly rather
        // than routing through the general rule, which would leave a
        // pow(b, 2.0 - 1.0) in the output.
        let n' = int n
        if n' = 0 then Ok []
        else
            let dterm =
                if n' = 1 then fLit 1.0
                elif n' = 2 then mul (fLit 2.0) b
                else mul (fLit (float n')) (pow b (iLit (int64 (n' - 1))))
            adjointOf rc b (mul cot dterm)
    | ExprKind.ExprBinOp (_, OpCaret, b, e) ->
        // d(b^e) = e*b^(e-1) db  +  b^e*log(b) de.
        // The base term keeps the power form instead of the equivalent
        // e*b^e/b so that b = 0 stays finite. The log term is reachable
        // only when `e` is itself active -- a constant exponent takes the
        // ExprLit/inactive-var path to Ok [] and never evaluates log(b),
        // so a negative base still differentiates.
        let pre, c = bindCot rc cot
        adjointOf rc b (mul c (mul e (pow b (sub e (fLit 1.0))))) |> Result.bind (fun sb ->
        adjointOf rc e (mul c (mul (pow b e) (call "log" [b]))) |> Result.map (fun se ->
            pre @ sb @ se))
    | ExprKind.ExprBinOp (_, (OpEq | OpNeq | OpLt | OpLe | OpGt | OpGe | OpAnd | OpOr), _, _) ->
        Ok []   // boolean-valued: no adjoint
    | ExprKind.ExprBinOp (_, OpMod, _, _) -> Ok []  // int-valued
    | ExprKind.ExprArrayLit _ ->
        err rc.Fname "array literals may only appear as let initializers in differentiated code"
    | _ -> err rc.Fname "unsupported expression form in differentiated code (adjoint)"

/// Adjoint of one forward statement (statements arrive in REVERSE order).
let rec private adjointOfStmt (rc: RevCtx) (s: NStmt) : Result<NStmt list, string> =
    match s with
    | NLet (x, _, value) ->
        if not (Set.contains x rc.Diff) then Ok []
        else
            // Array-literal init: flow each ELEMENT's adjoint from the
            // matching cotangent cell. Pure-literal elements contribute
            // nothing; nested literals recurse through curried reads.
            // (Treating the whole literal as a constant init -- the old
            // behavior -- silently dropped the gradient terms of any
            // ACTIVE element: `let a = [x, 2.0*x]` gave dx = 0.)
            let rec flowLit (cotCell: Expr) (elem: Expr) : Result<NStmt list, string> =
                let rec allLit (e: Expr) =
                    match e.Kind with
                    | ExprKind.ExprLit _ -> true
                    | ExprKind.ExprArrayLit es -> es |> List.forall allLit
                    | _ -> false
                if allLit elem then Ok []
                else
                    match elem.Kind with
                    | ExprKind.ExprArrayLit es ->
                        es |> List.mapi (fun j ej -> (j, ej))
                           |> List.fold (fun acc (j, ej) ->
                                acc |> Result.bind (fun ss ->
                                    flowLit (inheritSpan elem (ExprApp (cotCell, [iLit (int64 j)]))) ej
                                    |> Result.map (fun s2 -> ss @ s2)))
                                (Ok [])
                    | _ -> adjointOf rc elem cotCell
            (match value with
             | { Kind = ExprKind.ExprArrayLit elems } ->
                 elems |> List.mapi (fun i el -> (i, el))
                       |> List.fold (fun acc (i, el) ->
                            acc |> Result.bind (fun ss ->
                                flowLit (inheritSpan value (ExprApp (v (dName x), [iLit (int64 i)]))) el
                                |> Result.map (fun s2 -> ss @ s2)))
                            (Ok [])
             | ConstFill _ -> Ok []   // fill of a literal: nothing flows back
             | _ -> adjointOf rc value (v (dName x)))
    | NAssign (lhs, rhs) ->
        (match additiveSelf lhs rhs with
         | Some (sign, e) ->
             let cotBase =
                 match lhs.Kind with
                 | ExprKind.ExprVar x when Set.contains x rc.Diff -> Some (v (dName x))
                 | ExprKind.ExprApp ({ Kind = ExprKind.ExprVar a }, idxs) when Set.contains a rc.Diff ->
                     Some (inheritSpan lhs (ExprApp (v (dName a), idxs)))
                 | _ -> None
             match cotBase with
             | None -> Ok []
             | Some c ->
                 let cot = if sign < 0.0 then neg c else c
                 adjointOf rc e cot
         | None ->
             // general overwrite: save cotangent, zero it, then flow into rhs
             let target =
                 match lhs.Kind with
                 | ExprKind.ExprVar x when Set.contains x rc.Diff -> Some (v (dName x))
                 | ExprKind.ExprApp ({ Kind = ExprKind.ExprVar a }, idxs) when Set.contains a rc.Diff ->
                     Some (inheritSpan lhs (ExprApp (v (dName a), idxs)))
                 | _ -> None
             match target with
             | None -> Ok []
             | Some t ->
                 let c = fresh rc.Ctx "__c"
                 adjointOf rc rhs (inheritSpan lhs (ExprVar c)) |> Result.map (fun flow ->
                     [NLet (c, false, t); NAssign (t, fLit 0.0)] @ flow))
    | NFor (var, lo, hi, body) ->
        // Same-direction adjoint loop: REPLAY THE WHOLE BODY (fresh
        // per-iteration values, including loop-local arrays filled by
        // interior construction loops), declare loop-local cotangents for
        // loop-local diff lets, then run the body's adjoints reversed.
        //
        // Replaying accumulations into variables that OUTLIVE the loop
        // corrupts them -- soundly: by reverse-sweep order every adjoint
        // that reads such a variable's forward value has already run
        // (post-loop statements' adjoints precede this loop's), and the
        // discipline checks ban pre-loop reads. Lets-only replay is NOT
        // enough: a loop-local array built by an interior loop would read
        // back as its zero literal.
        let localLets = body |> List.choose (fun s ->
            match s with
            | NLet (n, _, _) when Set.contains n rc.Diff -> Some n
            | _ -> None)
        let replay = body
        let localCots =
            localLets |> List.map (fun n ->
                match body |> List.tryPick (fun s ->
                        match s with
                        // literal or constant-fill initializer: zerosLike
                        // yields the matching zero shape (None for other
                        // forms, so tryPick keeps them scalar-defaulted)
                        | NLet (m, _, init) when m = n -> zerosLikeLiteral init
                        | _ -> None) with
                | Some z -> NLet (dName n, true, z)
                | None -> NLet (dName n, true, fLit 0.0))
        let folded =
            List.rev body
            |> List.fold (fun acc s ->
                acc |> Result.bind (fun ss ->
                    adjointOfStmt rc s |> Result.map (fun s' -> ss @ s')))
                (Ok [])
        folded |> Result.map (fun bodyAdjoints ->
            [NFor (var, lo, hi, replay @ localCots @ bodyAdjoints)])

// The forward (tangent) sweep -- ad.jvp
//
// Forward mode propagates tangents IN PROGRAM ORDER beside the primal:
// every differentiable binding/assignment gets a `__t_<name>` twin computed
// from the operands' tangents via the same derivative tables the adjoint
// uses. No reverse sweep, no cotangent buffers, no replay. Tangent
// assignments are emitted BEFORE their primal assignment so they read the
// pre-assignment primal values (d(x*x) needs the old x).

/// Tangent-name prefix for the CURRENT jvp synthesis. Defaults to `__t_`;
/// composition bumps it (`__t1_`, `__t2_`, ...) because a trusted source's
/// params already include the previous round's `__t_*` names -- `tName`
/// must stay injective against them or the second round's tangent of `x`
/// would collide with the first round's tangent parameter `__t_x`.
let private tangentPrefix = ref "__t_"
let private tName (n: string) = tangentPrefix.Value + n

/// Zero-folding expression builders. Folding `0.0` operands away matters
/// twice over: the emitted tangent stays readable, and -- decisively for the
/// general power rule -- a syntactically-zero tangent SUPPRESSES the term
/// entirely, so `log(b)` is never emitted for an inactive exponent (the same
/// reachability guarantee the adjoint's inactive-path routing provides).
let private isZeroLit (e: Expr) =
    match e.Kind with
    | ExprKind.ExprLit (LitFloat 0.0) -> true
    | _ -> false
let private addZ a b = if isZeroLit a then b elif isZeroLit b then a else add a b
let private subZ a b = if isZeroLit b then a elif isZeroLit a then neg b else sub a b
let private mulZ a b = if isZeroLit a || isZeroLit b then fLit 0.0 else mul a b
let private divZ a b = if isZeroLit a then fLit 0.0 else div a b

/// Tangent of an expression, as an expression over primal names and
/// `__t_*` tangent names. Mirrors `adjointOf` case-for-case; refusals
/// match the adjoint's so both modes accept identical fragments (v1).
let rec private tangentOfExpr (rc: RevCtx) (e: Expr) : Result<Expr, string> =
    match e with
    | { Kind = ExprKind.ExprLit _ } -> Ok (fLit 0.0)
    | { Kind = ExprKind.ExprVar x } ->
        if Set.contains x rc.Diff then Ok (v (tName x)) else Ok (fLit 0.0)
    | { Kind = ExprKind.ExprTyped (inner, _) } -> tangentOfExpr rc inner
    | { Kind = ExprKind.ExprApp ({ Kind = ExprKind.ExprVar a }, idxs) } when Set.contains a rc.Arrays ->
        if Set.contains a rc.Diff then Ok (inheritSpan e (ExprApp (v (tName a), idxs)))
        else Ok (fLit 0.0)
    | { Kind = ExprKind.ExprApp ({ Kind = ExprKind.ExprVar name }, [u]) } when isMathIntrinsic name
                                       && not (Map.containsKey name rc.Ctx.Decls) ->
        (match derivRule name u with
         | None when Set.contains name zeroDerivIntrinsics -> Ok (fLit 0.0)   // floor/ceil
         | None ->
             // Through `err` (unlike the adjoint's raw Error) so the message
             // carries the jvp prefix the diagnostic boundary keys on.
             err rc.Fname (sprintf "'%s' has no derivative rule, so it cannot appear in a differentiated function (its derivative is not expressible in the AD-able subset). Compute it outside the function passed to ad.%s, or pass the value in as a parameter" name errMode.Value)
         | Some d -> tangentOfExpr rc u |> Result.map (fun tu -> mulZ d tu))
    | { Kind = ExprKind.ExprApp ({ Kind = ExprKind.ExprVar name }, [a; b]) } when isBinaryMathIntrinsic name
                                       && not (Map.containsKey name rc.Ctx.Decls) ->
        let (dA, dB) = binaryDerivRule name a b
        tangentOfExpr rc a |> Result.bind (fun ta ->
        tangentOfExpr rc b |> Result.map (fun tb -> addZ (mulZ dA ta) (mulZ dB tb)))
    | { Kind = ExprKind.ExprApp ({ Kind = ExprKind.ExprVar name }, _) } ->
        // A name that carries differentiable data but was never registered
        // as an ARRAY cannot be read as a constant: that combination means
        // the taint pass and the array tracker disagree, and returning zero
        // here is the silent-wrong-gradient failure mode. Refuse instead --
        // this fires on internal inconsistency, so it names the cause.
        if Set.contains name rc.Diff && not (Set.contains name rc.Arrays) then
            err rc.Fname (sprintf "internal: '%s' carries differentiable data but is not tracked as an array, so its element read has no tangent rule -- this is a gap in the transform's array tracking, please report it" name)
        elif Set.contains name rc.Known then Ok (fLit 0.0)   // non-diff data read
        else
            err rc.Fname (sprintf "cannot differentiate through '%s': it is not a same-module function, a math intrinsic with a derivative rule, or an array in scope, so its contribution would silently vanish from the gradient. Compute it outside the function passed to ad.%s, or pass the value in as a parameter" name errMode.Value)
    | { Kind = ExprKind.ExprUnaryOp (OpNeg, inner) } ->
        tangentOfExpr rc inner |> Result.map (fun t -> if isZeroLit t then t else neg t)
    | { Kind = ExprKind.ExprUnaryOp (OpNot, _) } -> Ok (fLit 0.0)
    | { Kind = ExprKind.ExprBinOp (_, OpAdd, l, r) } ->
        tangentOfExpr rc l |> Result.bind (fun tl ->
        tangentOfExpr rc r |> Result.map (fun tr -> addZ tl tr))
    | { Kind = ExprKind.ExprBinOp (_, OpSub, l, r) } ->
        tangentOfExpr rc l |> Result.bind (fun tl ->
        tangentOfExpr rc r |> Result.map (fun tr -> subZ tl tr))
    | { Kind = ExprKind.ExprBinOp (_, OpMul, l, r) } ->
        tangentOfExpr rc l |> Result.bind (fun tl ->
        tangentOfExpr rc r |> Result.map (fun tr -> addZ (mulZ tl r) (mulZ l tr)))
    | { Kind = ExprKind.ExprBinOp (_, OpDiv, l, r) } ->
        tangentOfExpr rc l |> Result.bind (fun tl ->
        tangentOfExpr rc r |> Result.map (fun tr ->
            subZ (divZ tl r) (divZ (mulZ l tr) (mul r r))))
    | { Kind = ExprKind.ExprBinOp (_, OpCaret, b, { Kind = ExprKind.ExprLit (LitInt n) }) } when int n >= 0 ->
        // Constant natural exponent: closed form (mirrors the adjoint arm).
        let n' = int n
        if n' = 0 then Ok (fLit 0.0)
        else
            tangentOfExpr rc b |> Result.map (fun tb ->
                let dterm =
                    if n' = 1 then fLit 1.0
                    elif n' = 2 then mul (fLit 2.0) b
                    else mul (fLit (float n')) (pow b (iLit (int64 (n' - 1))))
                mulZ dterm tb)
    | { Kind = ExprKind.ExprBinOp (_, OpCaret, bb, ee) } ->
        // d(b^e) = e*b^(e-1) db + b^e*log(b) de; mulZ suppresses the log
        // term when the exponent is inactive (see the builder note above).
        tangentOfExpr rc bb |> Result.bind (fun tb ->
        tangentOfExpr rc ee |> Result.map (fun te ->
            addZ (mulZ (mul ee (pow bb (sub ee (fLit 1.0)))) tb)
                 (mulZ (mul (pow bb ee) (call "log" [bb])) te)))
    | { Kind = ExprKind.ExprBinOp (_, (OpEq | OpNeq | OpLt | OpLe | OpGt | OpGe | OpAnd | OpOr), _, _) } ->
        Ok (fLit 0.0)   // boolean-valued: no tangent
    | { Kind = ExprKind.ExprBinOp (_, OpMod, _, _) } -> Ok (fLit 0.0)  // int-valued
    | { Kind = ExprKind.ExprExtents _ } -> Ok (fLit 0.0)  // int-valued size
    | { Kind = ExprKind.ExprIf (c, t, f) } ->
        // Branch of tangents under the same condition (see walkExpr's arm).
        tangentOfExpr rc t |> Result.bind (fun tt ->
        tangentOfExpr rc f |> Result.map (fun tf ->
            inheritSpan e (ExprIf (c, tt, tf))))
    | ConstFill (cnt, _) -> Ok (zeroFill cnt)
    // C2-C5: the rank-0 MAP. See `tangentOfMap`. A bare-name loop side
    // resolves through the let-bound loop objects first.
    | { Kind = ExprKind.ExprBinOp (bm, OpApply, lo, kern) } ->
        let loResolved =
            match lo.Kind with
            | ExprKind.ExprVar n ->
                (match Map.tryFind n rc.LoopBindings with Some b -> b | None -> lo)
            | _ -> lo
        (match loResolved.Kind with
         | ExprKind.ExprMethodFor arrays -> tangentOfMap rc e bm arrays kern
         | ExprKind.ExprObjectFor k2 ->
             // `object_for(k) <@> (A, B)` is the same map with the operand
             // list on the right; normalize and share the rule.
             let arrays =
                 match kern.Kind with
                 | ExprKind.ExprTuple es -> es
                 | _ -> [kern]
             tangentOfMap rc e bm arrays k2
         | _ ->
             err rc.Fname "differentiating `<@>` supports `method_for(<operands>) <@> <kernel>` and `object_for(<kernel>) <@> <operands>` (v1, directly or through a let-bound loop object); pipelines and section kernels are not yet differentiable")
    // C1: same form, tangent operands (see the LinearForm doc comment).
    | LinearForm (ops, rebuild) ->
        ops |> List.fold (fun acc o ->
            acc |> Result.bind (fun ts -> tangentOfExpr rc o |> Result.map (fun t -> ts @ [t])))
            (Ok [])
        |> Result.map rebuild
    | { Kind = ExprKind.ExprArrayLit _ } ->
        err rc.Fname "array literals may only appear as let initializers in differentiated code"
    | _ -> err rc.Fname "unsupported expression form in differentiated code (tangent)"

/// The C2-C5 MAP rule, shared by both spellings
/// (`method_for(ops) <@> kern` and `object_for(kern) <@> ops`).
///
/// The tangent is the SAME iteration over VIRTUAL operands, with values and
/// tangents read by index from the enclosing scope (capture-read; zip is
/// refused as one operand of a multi-array loop, so pairing is not
/// available for n >= 2):
///
///   * a named array operand becomes `range<its index types>`, its kernel
///     param becomes indexed reads `A(i...)` substituted into the body;
///   * a `halo<...>` or `range<...>` operand is already virtual -- it stays,
///     and its kernel param (window / index) is non-differentiable data;
///   * `reynolds(g[, Antisymmetric])` kernels are EXPANDED first --
///     sum_sigma sign * body[param_k := read_{sigma(k)}] -- so the ordinary
///     expression rule differentiates the symmetrized sum (correct under
///     the JOINT permutation: seeds travel with their values because the
///     substitution moves reads and, through them, tangent reads together);
///   * named-function and intrinsic kernels normalize to lambdas.
///
/// C5, the symmetric fast path: when the kernel carries a STRUCTURAL
/// `where comm(...)` covering all params and every operand is the SAME
/// rank-1 array, the tangent loop runs over `range<SymIdx<r, N>>` --
/// canonical cells only, triangular storage, the full r! saving on the
/// tangent leg. tangent_joint_swap (proofs/BladeJacobian.v) licenses
/// exactly this: the tangent of a structurally symmetric primal is
/// invariant under the joint pair swap. The declared-comm gate is
/// load-bearing (semantic_hypothesis_insufficient refutes relaxing it),
/// and `range<SymIdx>` hands the kernel PREFIX OFFSETS, so canonical
/// indices are the prefix sums of the params.
and private tangentOfMap (rc: RevCtx) (e: Expr) (bm: BinOpMode) (arrays: Expr list) (kern: Expr) : Result<Expr, string> =
    let reMap k = inheritSpan e k
    // -- kernel normalization ------------------------------------------------
    let normKern =
        match kern.Kind with
        | ExprKind.ExprLambda (ps, wc, body) -> Ok (ps, wc, body, None)
        | ExprKind.ExprReynolds ({ Kind = ExprKind.ExprLambda (ps, wc, body) }, isAnti) ->
            Ok (ps, wc, body, Some isAnti)
        | ExprKind.ExprVar f when Map.containsKey f rc.Ctx.Decls ->
            let fd = rc.Ctx.Decls.[f]
            (match fd.Body.Kind with
             | ExprKind.ExprBlock _ ->
                 err rc.Fname (sprintf "kernel '%s' has a block body; only expression-bodied named functions are differentiable as kernels (v1)" f)
             | _ ->
                 let ps =
                     fd.Params |> List.map (fun p ->
                         { Name = p.Name; Type = None; Default = None; NameSpan = noSpan })
                 Ok (ps, fd.WhereClause, fd.Body, None))
        | ExprKind.ExprVar name when isMathIntrinsic name ->
            let p = fresh rc.Ctx "__ck"
            Ok ([ { Name = p; Type = None; Default = None; NameSpan = noSpan } ],
                None, call name [v p], None)
        | _ -> err rc.Fname "differentiating `<@>` supports lambda, reynolds(lambda), named-function, and intrinsic kernels (v1)"
    normKern |> Result.bind (fun (ps, wc, body, reynoldsSign) ->
    if ps.Length <> arrays.Length || arrays.IsEmpty then
        err rc.Fname (sprintf "kernel arity %d does not match %d loop operand(s) in differentiated code" ps.Length arrays.Length)
    else
    // -- operand classification ---------------------------------------------
    // Named n -> (name, index types); Passthrough -> virtual operand kept as-is
    let classify (a: Expr) =
        match a.Kind with
        | ExprKind.ExprVar n ->
            (match Map.tryFind n rc.ArrayIdxTys with
             | Some idxTys when Set.contains n rc.Arrays -> Ok (Choice1Of2 (n, idxTys))
             | _ -> err rc.Fname "differentiating a map needs each loop operand to be a named array PARAMETER with a declared index type (v1); bind the operand to a parameter, or compute it outside the differentiated function")
        | ExprKind.ExprHalo _ | ExprKind.ExprRange _ -> Ok (Choice2Of2 a)
        | _ -> err rc.Fname "differentiating a map needs each loop operand to be a named array PARAMETER with a declared index type (v1); bind the operand to a parameter, or compute it outside the differentiated function"
    arrays |> List.fold (fun acc a ->
        acc |> Result.bind (fun cs -> classify a |> Result.map (fun c -> cs @ [c])))
        (Ok [])
    |> Result.bind (fun classes ->
    // -- C5: the symmetric fast path -----------------------------------------
    let symCase =
        if reynoldsSign.IsSome then None
        else
            let names = classes |> List.map (function Choice1Of2 (n, its) -> Some (n, its) | _ -> None)
            if names |> List.exists Option.isNone then None
            else
                let names = names |> List.map Option.get
                let r = names.Length
                let allSame = r >= 2 && (names |> List.forall (fun (n, _) -> n = fst names.Head))
                let rank1 =
                    names |> List.forall (fun (_, its) ->
                        match its with
                        | [one] -> (match resolveTy rc.Ctx one with TyIdx { Kind = ExprKind.ExprLit (LitInt _) } -> true | _ -> false)
                        | _ -> false)
                let commAll =
                    match wc with
                    | Some w ->
                        w.Commutativity |> List.exists (fun group ->
                            Set.ofList group = Set.ofList (ps |> List.map (fun p -> p.Name)))
                    | None -> false
                if allSame && rank1 && commAll then
                    let n =
                        match resolveTy rc.Ctx (snd names.Head |> List.head) with
                        | TyIdx { Kind = ExprKind.ExprLit (LitInt n) } -> int n
                        | _ -> 0
                    Some (fst names.Head, r, n)
                else None
    match symCase with
    | Some (aname, r, n) ->
        // canonical cells only: params are PREFIX OFFSETS, indices are their
        // prefix sums; no `where comm` on the emitted kernel (silently
        // discarded on range operands) and SymIdx spelled inline.
        let offNames = List.init r (fun _ -> fresh rc.Ctx "__cp")
        let canonical =
            offNames
            |> List.fold (fun (acc, prev) nm ->
                let ix = match prev with None -> v nm | Some p -> add p (v nm)
                (acc @ [ix], Some ix)) ([], None)
            |> fst
        let substituted =
            List.zip ps canonical
            |> List.fold (fun accE (p, ix) ->
                substVar p.Name (syn (ExprApp (v aname, [ix]))) accE) body
        tangentOfExpr rc substituted |> Result.map (fun tBody ->
            let symTy = TySymIdx (r, SymBaseExtent (iLit (int64 n)))
            let lamParams =
                offNames |> List.map (fun nm ->
                    { Name = nm; Type = None; Default = None; NameSpan = noSpan })
            reMap (ExprBinOp (bm, OpApply,
                              syn (ExprMethodFor [syn (ExprRange [symTy])]),
                              syn (ExprLambda (lamParams, None, tBody)))))
    | None ->
    // -- the uniform dense path ----------------------------------------------
    // reads per slot (Named) / kept params (Passthrough), then reynolds
    // expansion if requested, then the ordinary expression rule.
    let slots =
        List.zip ps classes
        |> List.map (fun (p, c) ->
            match c with
            | Choice1Of2 (nm, idxTys) ->
                let ixs = idxTys |> List.map (fun _ -> fresh rc.Ctx "__ci")
                Choice1Of2 (p, nm, idxTys, ixs)
            | Choice2Of2 a -> Choice2Of2 (p, a))
    let readOf slot =
        match slot with
        | Choice1Of2 (_, nm, _, ixs) -> Some (syn (ExprApp (v nm, ixs |> List.map v)))
        | Choice2Of2 _ -> None
    let expandedBody =
        match reynoldsSign with
        | None ->
            slots |> List.fold (fun accE slot ->
                match slot with
                | Choice1Of2 (p, _, _, _) -> substVar p.Name (readOf slot |> Option.get) accE
                | Choice2Of2 _ -> accE) body
            |> Ok
        | Some isAnti ->
            // reynolds needs every slot readable (a window has no permuted read)
            if slots |> List.exists (function Choice2Of2 _ -> true | _ -> false) then
                err rc.Fname "reynolds kernels over halo/range operands are not differentiable (v1)"
            else
                let reads = slots |> List.map (readOf >> Option.get)
                let rec perms xs =
                    match xs with
                    | [] -> [[]]
                    | _ -> xs |> List.collect (fun x ->
                            perms (List.filter ((<>) x) xs) |> List.map (fun p -> x :: p))
                let parity (p: int list) =
                    let arr = List.toArray p
                    let mutable inv = 0
                    for i in 0 .. arr.Length - 2 do
                        for j in i + 1 .. arr.Length - 1 do
                            if arr.[i] > arr.[j] then inv <- inv + 1
                    inv % 2 = 0
                let terms =
                    perms [0 .. reads.Length - 1]
                    |> List.map (fun perm ->
                        let t =
                            List.zip ps perm
                            |> List.fold (fun accE (p, srcSlot) ->
                                substVar p.Name reads.[srcSlot] accE) body
                        (parity perm, t))
                match terms with
                | [] -> Ok (fLit 0.0)
                | (firstEven, firstT) :: rest ->
                    let init = if not isAnti || firstEven then firstT else neg firstT
                    Ok (rest |> List.fold (fun accE (even, t) ->
                            if not isAnti || even then add accE t else sub accE t) init)
    expandedBody |> Result.bind (fun bodyExpanded ->
    let passthroughNames =
        slots |> List.choose (function Choice2Of2 (p, _) -> Some p.Name | _ -> None) |> Set.ofList
    let rc' = { rc with Known = Set.union rc.Known passthroughNames }
    tangentOfExpr rc' bodyExpanded |> Result.map (fun tBody ->
        let operandsOut =
            slots |> List.map (function
                | Choice1Of2 (_, _, idxTys, _) -> syn (ExprRange idxTys)
                | Choice2Of2 (_, a) -> a)
        let lamParams =
            slots |> List.collect (function
                | Choice1Of2 (_, _, _, ixs) ->
                    ixs |> List.map (fun nm -> { Name = nm; Type = None; Default = None; NameSpan = noSpan })
                | Choice2Of2 (p, _) -> [p])
        reMap (ExprBinOp (bm, OpApply,
                          syn (ExprMethodFor operandsOut),
                          syn (ExprLambda (lamParams, None, tBody))))))))

/// Elementwise tangent of a (possibly nested) array-literal initializer.
let rec private tangentOfLit (rc: RevCtx) (e: Expr) : Result<Expr, string> =
    match e.Kind with
    | ExprKind.ExprArrayLit elems ->
        elems |> List.fold (fun acc el ->
            acc |> Result.bind (fun ts ->
                tangentOfLit rc el |> Result.map (fun t -> ts @ [t])))
            (Ok [])
        |> Result.map (fun ts -> inheritSpan e (ExprArrayLit ts))
    | _ -> tangentOfExpr rc e

/// Tangent-interleaved form of one forward statement. The tangent
/// ASSIGNMENT precedes its primal so it reads pre-assignment values;
/// tangent LETS follow their primal (the tangent reads operands bound
/// earlier, never the freshly-bound name).
let rec private tangentOfStmt (rc: RevCtx) (s: NStmt) : Result<NStmt list, string> =
    match s with
    // A let-bound loop object gets no tangent binding: it is a deferred
    // iteration, not data. Its tangent materializes at the application
    // site, where the OpApply rule resolves the binding.
    | NLet (_, _, { Kind = ExprKind.ExprMethodFor _ | ExprKind.ExprObjectFor _ }) -> Ok [s]
    | NLet (x, isMut, value) ->
        if not (Set.contains x rc.Diff) then Ok [s]
        else
            (match value with
             | { Kind = ExprKind.ExprArrayLit _ } ->
                 tangentOfLit rc value |> Result.map (fun t -> [s; NLet (tName x, isMut, t)])
             | ConstFill (cnt, _) -> Ok [s; NLet (tName x, isMut, zeroFill cnt)]
             | _ -> tangentOfExpr rc value |> Result.map (fun t -> [s; NLet (tName x, isMut, t)]))
    | NAssign (lhs, rhs) ->
        let tangentLhs =
            match lhs.Kind with
            | ExprKind.ExprVar x when Set.contains x rc.Diff -> Some (v (tName x))
            | ExprKind.ExprApp ({ Kind = ExprKind.ExprVar a }, idxs) when Set.contains a rc.Diff ->
                Some (inheritSpan lhs (ExprApp (v (tName a), idxs)))
            | _ -> None
        (match tangentLhs with
         | None -> Ok [s]   // non-diff target: rhs is inactive by taint
         | Some tl ->
             tangentOfExpr rc rhs |> Result.map (fun tr -> [NAssign (tl, tr); s]))
    | NFor (var, lo, hi, body) ->
        body |> List.fold (fun acc st ->
            acc |> Result.bind (fun ss ->
                tangentOfStmt rc st |> Result.map (fun s2 -> ss @ s2)))
            (Ok [])
        |> Result.map (fun body' -> [NFor (var, lo, hi, body')])

// NStmt -> Stmt conversion

let rec private toStmts (ns: NStmt list) : Stmt list =
    ns |> List.map (fun s ->
        match s with
        | NLet (n, isMut, value) ->
            StmtLet { Pattern = synPat (PatVar n)
                      Type = None
                      Value = value
                      Mutability = if isMut then BindMut else BindLet }
        | NAssign (lhs, rhs) -> StmtExpr (mkExpr (mergeSpan lhs.Span rhs.Span) (ExprAssign (lhs, rhs)))
        | NFor (var, lo, hi, body) -> StmtForIn (var, mkExpr (mergeSpan lo.Span hi.Span) (ExprDotDot (lo, hi)), toStmts body))

// Synthesize f__grad

let private gradSuffix = "__grad"

let private synthesize (ctx: Ctx) (fd: FunctionDecl) : Result<FunctionDecl, string> =
    errMode.Value <- "grad"
    let fname = fd.Name
    // The synthesized name must be free: splicing a second `f__grad` beside a
    // user function of that name would silently shadow one of them.
    (if Map.containsKey (fname + gradSuffix) ctx.Decls then
        err fname (sprintf "a function named '%s%s' already exists in this module; grad would synthesize a colliding declaration -- rename it" fname gradSuffix)
     else Ok ())
    |> Result.bind (fun () ->
    // Return type must be a Float scalar (checked syntactically; the
    // typechecker re-verifies the generated function anyway). Unit-carrying
    // losses get their own message: the refusal is about gradient UNITS
    // (<loss>/<param>), not about the return being a non-Float.
    match fd.ReturnType |> Option.map (resolveTy ctx) with
    | Some t when isFloatTy t -> Ok ()
    | Some (TyNamed (("Float" | "Float64" | "Float32"), _ :: _)) ->
        err fname "grad requires a dimensionless Float return: the loss carries units, and gradient units <loss>/<parameter> are not expressible in the grad ABI (v1); divide the loss by a unit constant at the boundary"
    | Some _ -> err fname "grad requires a function returning Float (scalar loss)"
    | None -> err fname "grad requires an explicit `-> Float` return annotation"
    |> Result.bind (fun () ->
    // classify parameters
    let classesR =
        fd.Params |> List.fold (fun acc p ->
            acc |> Result.bind (fun cs ->
                classifyParam fname ctx p |> Result.map (fun c -> cs @ [(p, c)])))
            (Ok [])
    classesR |> Result.bind (fun classes ->
    let diffParams =
        classes |> List.choose (fun (p, c) ->
            match c with DiffArray | DiffScalar -> Some p.Name | NonDiff -> None)
        |> Set.ofList
    let arrayParams =
        classes |> List.choose (fun (p, c) ->
            match c with DiffArray -> Some p.Name | _ -> None)
        |> Set.ofList
    let scalarDiff =
        classes |> List.choose (fun (p, c) ->
            match c with DiffScalar -> Some p.Name | _ -> None)
    if Set.isEmpty diffParams then
        err fname "no differentiable (Float or Float-array) parameters"
    else
    // normalize + inline
    normalizeBody fname ctx 0 fd |> Result.bind (fun (stmts, finalE) ->
    // Reserved-name gate. The transform's deterministic synthesized names
    // (`__g_<x>` cotangents, `__t_<x>` forward-mode tangents, `__primal`)
    // would silently SHADOW a same-named user binding: the synthesized
    // zero-initialized declaration wins, and every derivative expression that
    // should read the user's value reads the zeroed cotangent instead --
    // a wrong gradient with no diagnostic. (Inlined callee locals are
    // exempt by construction: renaming gives them an `__in<N>_` prefix.)
    let reservedName (n: string) =
        n = "__primal" || n.StartsWith "__g_" || n.StartsWith "__t_"
    match (fd.Params |> List.map (fun p -> p.Name)) @ boundNames stmts |> List.tryFind reservedName with
    | Some n ->
        err fname (sprintf "binding or parameter '%s' collides with a reserved AD name (`__g_*`, `__t_*`, and `__primal` are synthesized by the transform and would shadow it); rename it" n)
    | None ->
    // validate every expression in the fragment
    let validateAll =
        let rec valStmts ss =
            ss |> List.fold (fun acc s ->
                acc |> Result.bind (fun () ->
                    match s with
                    | NLet (_, _, e) -> walkExpr fname ctx ignore e
                    | NAssign (l, r) ->
                        walkExpr fname ctx ignore l
                        |> Result.bind (fun () -> walkExpr fname ctx ignore r)
                    | NFor (_, lo, hi, body) ->
                        walkExpr fname ctx ignore lo
                        |> Result.bind (fun () -> walkExpr fname ctx ignore hi)
                        |> Result.bind (fun () -> valStmts body)))
                (Ok ())
        valStmts stmts |> Result.bind (fun () -> walkExpr fname ctx ignore finalE)
    validateAll |> Result.bind (fun () ->
    checkLoopDiscipline fname ctx stmts |> Result.bind (fun () ->
    checkWriteAfterRead fname ctx stmts |> Result.bind (fun () ->
    analyze fname ctx diffParams arrayParams stmts finalE |> Result.bind (fun (diff, arrays) ->
    checkNoScalarOverwrite fname diff stmts |> Result.bind (fun () ->
    let known =
        Set.unionMany [
            fd.Params |> List.map (fun p -> p.Name) |> Set.ofList
            boundNames stmts |> Set.ofList
            ctx.ModuleVals ]
    let arrayIdxTys =
        fd.Params |> List.choose (fun p ->
            match p.Type |> Option.map (resolveTy ctx) with
            | Some (TyArray (_, idxTys)) when not idxTys.IsEmpty -> Some (p.Name, idxTys)
            | _ -> None)
        |> Map.ofList
    let rc = { Fname = fname; Ctx = ctx; Diff = diff; Arrays = arrays; Known = known
               ArrayIdxTys = arrayIdxTys; LoopBindings = Map.empty }

    // cotangent declarations for function-level diff LOCALS (params' array
    // cotangents are mut parameters; scalar-param cotangents are locals)
    let localDecls =
        stmts |> List.choose (fun s ->
            match s with
            | NLet (n, _, value) when Set.contains n diff ->
                if Set.contains n arrays then
                    match value with
                    | { Kind = ExprKind.ExprArrayLit _ } | ConstFill _ ->
                        zerosLikeLiteral value |> Option.map (fun z -> NLet (dName n, true, z))
                    | _ -> None   // rejected below
                else Some (NLet (dName n, true, fLit 0.0))
            | _ -> None)
    // reject function-level diff array locals not initialized by literals
    let badArrayLocal =
        stmts |> List.tryPick (fun s ->
            match s with
            | NLet (n, _, value) when Set.contains n diff && Set.contains n arrays ->
                (match value with
                 | { Kind = ExprKind.ExprArrayLit _ } | ConstFill _ -> None
                 | { Kind = ExprKind.ExprVar _ } -> Some n   // alias -- cotangent identity untrackable
                 | _ -> Some n)
            | _ -> None)
    match badArrayLocal with
    | Some n -> err fname (sprintf "differentiable array local '%s' must be initialized by an array literal (aliases are not differentiable)" n)
    | None ->
    let scalarCots = scalarDiff |> List.map (fun p -> NLet (dName p, true, fLit 0.0))

    // seed: adjoint of the final expression with cotangent 1.0
    adjointOf rc finalE (fLit 1.0) |> Result.bind (fun seed ->
    // reverse sweep over the statements
    let folded =
        List.rev stmts
        |> List.fold (fun acc s ->
            acc |> Result.bind (fun ss ->
                adjointOfStmt rc s |> Result.map (fun s' -> ss @ s')))
            (Ok [])
    folded |> Result.map (fun reverse ->

    // assemble: forward + primal + cot decls + seed + reverse + return
    let primalName = "__primal"
    let fwd = toStmts stmts @ [ StmtLet { Pattern = synPat (PatVar primalName)
                                          Type = None
                                          Value = finalE
                                          Mutability = BindLet } ]
    let cotDecls = toStmts (localDecls @ scalarCots)
    let revStmts = toStmts (seed @ reverse)
    let retExpr =
        match scalarDiff with
        | [] -> v primalName
        | ss -> syn (ExprTuple (v primalName :: (ss |> List.map (fun p -> v (dName p)))))
    let retTy =
        match scalarDiff with
        | [] -> fd.ReturnType
        | ss -> Some (TyTuple ((Option.defaultValue TyFloat64 fd.ReturnType)
                               :: (ss |> List.map (fun _ -> TyNamed ("Float", [])))))
    let gradParams =
        fd.Params
        @ (classes |> List.choose (fun (p, c) ->
             match c with
             | DiffArray -> Some { Name = dName p.Name; Type = p.Type; Mutability = Mutable; Default = None; NameSpan = noSpan }
             | _ -> None))
    { Name = fname + gradSuffix
      TypeParams = fd.TypeParams
      Params = gradParams
      WhereClause = None
      ReturnType = retTy
      Body = inheritSpan fd.Body (ExprBlock (fwd @ cotDecls @ revStmts, Some retExpr))
      IsStatic = false
      NameSpan = noSpan })))))))))))

// Synthesize f__jvp -- forward mode at grad parity (v1)
//
// Same admissible subset, enforced by running the SAME discipline checks,
// so the jvp-vs-grad differential gate covers every accepted program (F2
// widens by deleting check calls, not rewriting the transform). The ABI
// differs where the mode does: tangent INPUTS -- one per differentiable
// param, appended in original param order, each typed with the primal
// param's annotation VERBATIM (tangents live in the same space, units
// included; bare Float is unit-polymorphic so substitution would defeat
// unit checking) -- and a `(primal, tangent)` tuple return. No mut
// buffers: forward mode does not accumulate, and `wrt` selection is just
// a zero seed.

let private jvpSuffix = "__jvp"

let private synthesizeJvp (ctx: Ctx) (trusted: bool) (fd: FunctionDecl) : Result<FunctionDecl, string> =
    errMode.Value <- "jvp"
    let fname = fd.Name
    let isFloatish (t: TypeExpr) =
        isFloatTy t || (match t with TyNamed (("Float" | "Float64" | "Float32"), _ :: _) -> true | _ -> false)
    (if Map.containsKey (fname + jvpSuffix) ctx.Decls then
        err fname (sprintf "a function named '%s%s' already exists in this module; jvp would synthesize a colliding declaration -- rename it" fname jvpSuffix)
     else Ok ())
    |> Result.bind (fun () ->
    match fd.ReturnType |> Option.map (resolveTy ctx) with
    | Some t when isFloatish t -> Ok ()   // units included: the tangent carries the same
    // All-Float tuples: the shape of a synthesized source's return
    // (f__grad's `(primal, dscalars...)`), differentiated for the
    // composition routes. The jvp return interleaves flat:
    // components, then their tangents.
    | Some (TyTuple ts) when ts |> List.forall (fun t -> isFloatish (resolveTy ctx t)) -> Ok ()
    | Some _ -> err fname "jvp requires a function returning Float (or an all-Float tuple) (v1)"
    | None -> err fname "jvp requires an explicit `-> Float` return annotation"
    |> Result.bind (fun () ->
    let classesR =
        fd.Params |> List.fold (fun acc p ->
            acc |> Result.bind (fun cs ->
                classifyParam fname ctx p |> Result.map (fun c -> cs @ [(p, c)])))
            (Ok [])
    classesR |> Result.bind (fun classes ->
    let diffParams =
        classes |> List.choose (fun (p, c) ->
            match c with DiffArray | DiffScalar -> Some p.Name | NonDiff -> None)
        |> Set.ofList
    let arrayParams =
        classes |> List.choose (fun (p, c) ->
            match c with DiffArray -> Some p.Name | _ -> None)
        |> Set.ofList
    if Set.isEmpty diffParams then
        err fname "no differentiable (Float or Float-array) parameters"
    else
    normalizeBody fname ctx 0 fd |> Result.bind (fun (stmts, finalE) ->
    // Reserved-name gate (same rationale as grad's: synthesized names
    // shadow same-named user bindings silently). A TRUSTED source -- one
    // this pass itself synthesized, in a composition chain -- binds
    // reserved names by construction and skips the gate.
    let reservedName (n: string) =
        n = "__primal" || n.StartsWith "__g_" || n.StartsWith "__t_"
    let allNames = (fd.Params |> List.map (fun p -> p.Name)) @ boundNames stmts
    let reservedHit =
        if trusted then None
        else allNames |> List.tryFind reservedName
    // Pick the first depth-indexed tangent prefix no existing name uses
    // (composition rounds each get their own; see tangentPrefix).
    tangentPrefix.Value <-
        (let rec pick k =
            let cand = if k = 0 then "__t_" else sprintf "__t%d_" k
            if allNames |> List.exists (fun n -> n.StartsWith cand) then pick (k + 1) else cand
         pick 0)
    match reservedHit with
    | Some n ->
        err fname (sprintf "binding or parameter '%s' collides with a reserved AD name (`__g_*`, `__t_*`, and `__primal` are synthesized by the transform and would shadow it); rename it" n)
    | None ->
    // Tuple-returning sources (f__grad's `(primal, dscalars...)`) sweep
    // per component; the surrogate keeps taint/validation walks off the
    // tuple node itself.
    let finalComps =
        match finalE.Kind with
        | ExprKind.ExprTuple es -> es
        | _ -> [finalE]
    let finalSurrogate = finalComps |> List.reduce add
    let validateAll =
        let rec valStmts ss =
            ss |> List.fold (fun acc s ->
                acc |> Result.bind (fun () ->
                    match s with
                    | NLet (_, _, e) -> walkExpr fname ctx ignore e
                    | NAssign (l, r) ->
                        walkExpr fname ctx ignore l
                        |> Result.bind (fun () -> walkExpr fname ctx ignore r)
                    | NFor (_, lo, hi, body) ->
                        walkExpr fname ctx ignore lo
                        |> Result.bind (fun () -> walkExpr fname ctx ignore hi)
                        |> Result.bind (fun () -> valStmts body)))
                (Ok ())
        valStmts stmts |> Result.bind (fun () -> walkExpr fname ctx ignore finalSurrogate)
    validateAll |> Result.bind (fun () ->
    // F2: grad's three discipline checks (write-after-read, scalar
    // overwrite, loop discipline) exist ONLY to keep the reverse sweep's
    // final-value re-evaluation sound (their own doc comments say so).
    // Forward tangents flow in program order beside the primal -- every
    // tangent assignment is emitted before its primal and reads
    // pre-assignment values -- so overwrites, loop-carried recurrences,
    // and accumulator reads all differentiate exactly and none of the
    // checks run here.
    analyze fname ctx diffParams arrayParams stmts finalSurrogate |> Result.bind (fun (diff, arrays) ->
    // No array-local literal restriction here (C1): grad needs one because
    // it must synthesize a ZERO COTANGENT BUFFER of the right shape and can
    // only read a shape off a literal -- and an alias makes cotangent
    // identity untrackable. Forward mode builds no buffers: the tangent of
    // a local IS the tangent expression of its initializer, so aliases and
    // linear combinators differentiate directly, and an initializer with no
    // tangent rule is refused by the sweep itself.
    let known =
        Set.unionMany [
            fd.Params |> List.map (fun p -> p.Name) |> Set.ofList
            boundNames stmts |> Set.ofList
            ctx.ModuleVals ]
    let arrayIdxTys =
        fd.Params |> List.choose (fun p ->
            match p.Type |> Option.map (resolveTy ctx) with
            | Some (TyArray (_, idxTys)) when not idxTys.IsEmpty -> Some (p.Name, idxTys)
            | _ -> None)
        |> Map.ofList
    // let-bound loop objects, resolved at their application sites
    let rec collectLoopBindings (acc: Map<string, Expr>) (ss: NStmt list) =
        ss |> List.fold (fun m st ->
            match st with
            | NLet (n, _, ({ Kind = ExprKind.ExprMethodFor _ | ExprKind.ExprObjectFor _ } as value)) ->
                if Map.containsKey n m then m else Map.add n value m
            | NFor (_, _, _, body) -> collectLoopBindings m body
            | _ -> m) acc
    let rc = { Fname = fname; Ctx = ctx; Diff = diff; Arrays = arrays; Known = known
               ArrayIdxTys = arrayIdxTys; LoopBindings = collectLoopBindings Map.empty stmts }

    // tangent-interleaved body + (primal, tangent) return
    let sweptR =
        stmts |> List.fold (fun acc s ->
            acc |> Result.bind (fun ss ->
                tangentOfStmt rc s |> Result.map (fun s2 -> ss @ s2)))
            (Ok [])
    sweptR |> Result.bind (fun swept ->
    finalComps
    |> List.fold (fun acc c ->
        acc |> Result.bind (fun ts ->
            tangentOfExpr rc c |> Result.map (fun t -> ts @ [t])))
        (Ok [])
    |> Result.map (fun tangentComps ->
    // Return: components then their tangents, flat -- `(p, t)` for the
    // scalar case, `(p, ds..., tp, tds...)` for a tuple-returning source.
    // Direct tuple of pure expressions; no intermediate lets (a trusted
    // source already binds `__primal`, so a fresh let would shadow it).
    let retExpr = syn (ExprTuple (finalComps @ tangentComps))
    let retTys =
        match fd.ReturnType |> Option.map (resolveTy ctx) with
        | Some (TyTuple ts) -> ts @ ts
        | rt -> let s = Option.defaultValue TyFloat64 rt in [s; s]
    let jvpParams =
        fd.Params
        @ (classes |> List.choose (fun (p, c) ->
             match c with
             | DiffArray | DiffScalar ->
                 Some { Name = tName p.Name; Type = p.Type; Mutability = p.Mutability; Default = None; NameSpan = noSpan }
             | NonDiff -> None))
    { Name = fname + jvpSuffix
      TypeParams = fd.TypeParams
      Params = jvpParams
      WhereClause = None
      ReturnType = Some (TyTuple retTys)
      Body = inheritSpan fd.Body (ExprBlock (toStmts swept, Some retExpr))
      IsStatic = false
      NameSpan = noSpan }))))))))

// Call-site rewriting + program expansion

/// Rewrite alias.grad(f) / alias.jvp(f) call sites in an expression.
/// Requests are recorded in DISCOVERY order (post-order, so an inner
/// ad.grad(f) precedes the outer ad.jvp(...) that consumes its result),
/// and `anticipated` carries the names the pass itself will synthesize --
/// which is what makes composition (`ad.jvp(ad.grad(f))`, the HVP route;
/// `ad.jvp(ad.jvp(f))`, second-order forward) legal arguments.
let rec private rewriteExpr (requestsOrdered: ResizeArray<string * string>)
                            (anticipated: System.Collections.Generic.HashSet<string>)
                            (declNames: Set<string>) (aliases: Set<string>) (e: Expr) : Result<Expr, string> =
    let r = rewriteExpr requestsOrdered anticipated declNames aliases
    let rList es =
        es |> List.fold (fun acc x ->
            acc |> Result.bind (fun xs -> r x |> Result.map (fun x' -> xs @ [x'])))
            (Ok [])
    let re k = inheritSpan e k
    match e.Kind with
    // Qualified: `alias.grad(f)` / `alias.jvp(f)` with alias bound by
    // `import ad`. Bare `grad(...)` is not recognized -- the AD surface is
    // a module, not a language-wide name (same rule as the ml/ppl surfaces).
    | ExprKind.ExprApp ({ Kind = ExprKind.ExprField ({ Kind = ExprKind.ExprVar alias }, (("grad" | "jvp") as which)) }, args) when Set.contains alias aliases ->
        (match args with
         | [arg0] ->
             // Rewrite the argument FIRST so composition works: the inner
             // form becomes a bare synthesized-name reference before this
             // arm inspects it.
             r arg0 |> Result.bind (fun arg0' ->
                 match arg0'.Kind with
                 | ExprKind.ExprVar fname when Set.contains fname declNames || anticipated.Contains fname ->
                     let suffix = if which = "grad" then gradSuffix else jvpSuffix
                     requestsOrdered.Add (which, fname)
                     anticipated.Add (fname + suffix) |> ignore
                     Ok (re (ExprVar (fname + suffix)))
                 | ExprKind.ExprVar fname ->
                     Error (sprintf "%s: '%s' is not a top-level function in this module (%s differentiates same-module named functions)" which fname which)
                 | _ -> Error (sprintf "%s: argument must be a named top-level function (e.g. ad.%s(loss))" which which))
         | _ -> Error (sprintf "%s: expects exactly one argument, the function to differentiate" which))
    | ExprKind.ExprLit _ | ExprKind.ExprVar _ -> Ok e
    | ExprKind.ExprApp (f, args) ->
        r f |> Result.bind (fun f' -> rList args |> Result.map (fun args' -> re (ExprApp (f', args'))))
    | ExprKind.ExprBinOp (m, op, l, rr) ->
        r l |> Result.bind (fun l' -> r rr |> Result.map (fun r' -> re (ExprBinOp (m, op, l', r'))))
    | ExprKind.ExprUnaryOp (op, inner) -> r inner |> Result.map (fun i -> re (ExprUnaryOp (op, i)))
    | ExprKind.ExprTyped (inner, t) -> r inner |> Result.map (fun i -> re (ExprTyped (i, t)))
    | ExprKind.ExprAssign (l, rr) ->
        r l |> Result.bind (fun l' -> r rr |> Result.map (fun r' -> re (ExprAssign (l', r'))))
    | ExprKind.ExprTuple es -> rList es |> Result.map (fun es' -> re (ExprTuple es'))
    | ExprKind.ExprArrayLit es -> rList es |> Result.map (fun es' -> re (ExprArrayLit es'))
    | ExprKind.ExprDotDot (l, h) ->
        r l |> Result.bind (fun l' -> r h |> Result.map (fun h' -> re (ExprDotDot (l', h'))))
    | ExprKind.ExprIf (c, t, f) ->
        r c |> Result.bind (fun c' ->
        r t |> Result.bind (fun t' ->
        r f |> Result.map (fun f' -> re (ExprIf (c', t', f')))))
    | ExprKind.ExprLet (binding, body) ->
        r binding.Value |> Result.bind (fun v' ->
        r body |> Result.map (fun b' -> re (ExprLet ({ binding with Value = v' }, b'))))
    | ExprKind.ExprBlock (stmts, finalE) ->
        let rec rStmt (s: Stmt) : Result<Stmt, string> =
            match s with
            | StmtSpanned (inner, sp) -> rStmt inner |> Result.map (fun i -> StmtSpanned (i, sp))
            | StmtLet binding -> r binding.Value |> Result.map (fun v' -> StmtLet { binding with Value = v' })
            | StmtExpr e2 -> r e2 |> Result.map StmtExpr
            | StmtAssign (l, op, rr) ->
                r l |> Result.bind (fun l' -> r rr |> Result.map (fun r' -> StmtAssign (l', op, r')))
            | StmtForIn (var, range, body) ->
                r range |> Result.bind (fun range' ->
                    body |> List.fold (fun acc bs ->
                        acc |> Result.bind (fun ss -> rStmt bs |> Result.map (fun s' -> ss @ [s'])))
                        (Ok [])
                    |> Result.map (fun body' -> StmtForIn (var, range', body')))
        stmts |> List.fold (fun acc s ->
            acc |> Result.bind (fun ss -> rStmt s |> Result.map (fun s' -> ss @ [s'])))
            (Ok [])
        |> Result.bind (fun stmts' ->
            match finalE with
            | Some fe -> r fe |> Result.map (fun fe' -> re (ExprBlock (stmts', Some fe')))
            | None -> Ok (re (ExprBlock (stmts', None))))
    | ExprKind.ExprLambda (ps, w, body) -> r body |> Result.map (fun b -> re (ExprLambda (ps, w, b)))
    | ExprKind.ExprMatch (scrut, cases) ->
        r scrut |> Result.bind (fun s' ->
            cases |> List.fold (fun acc c ->
                acc |> Result.bind (fun cs ->
                    r c.Body |> Result.map (fun b -> cs @ [{ c with Body = b }])))
                (Ok [])
            |> Result.map (fun cs' -> re (ExprMatch (s', cs'))))
    | _ -> Ok e   // exotic containers: grad not expected inside

/// `import ad [as _]` -- the module this transform is surfaced through.
let private isAdImport (d: Located<Decl>) =
    match d.Value with
    | DeclImport (["ad"], _) -> true
    | _ -> false

/// Aliases bound to `ad` in this decl list. Errors on a selective
/// `from ad import ...` (it would reintroduce a global name).
let private adAliasesOf (decls: Located<Decl> list) : Result<Set<string>, string> =
    decls |> List.fold (fun acc d ->
        acc |> Result.bind (fun set ->
            match d.Value with
            | DeclImport (["ad"], ImportQualified aliasOpt) ->
                Ok (Set.add (aliasOpt |> Option.defaultValue "ad") set)
            | DeclImport (["ad"], ImportSelective _) ->
                Error "`ad` supports only `import ad [as <alias>]`; a selective `from ad import ...` would reintroduce global names"
            | _ -> Ok set))
        (Ok Set.empty)

/// Expand alias.grad() over one module's declarations. Import-gated: with no
/// `import ad`, the pass is a no-op and bare `grad(...)` is simply unbound.
let private expandModule (decls: Located<Decl> list) : Result<Located<Decl> list, string> =
    adAliasesOf decls |> Result.bind (fun aliases ->
    if Set.isEmpty aliases then Ok decls
    else
    let decls = decls |> List.filter (not << isAdImport)
    let funcDecls =
        decls |> List.choose (fun d ->
            match d.Value with
            | DeclFunction fd -> Some (fd.Name, fd)
            | _ -> None)
        |> Map.ofList
    // Transparent same-module type aliases, so parameter classification can
    // see through `type Speed = Float<mps>`.
    let typeAliases =
        decls |> List.collect (fun d ->
            match d.Value with
            | DeclType (TyDeclAlias (n, [], body)) -> [(n, body)]
            | DeclType (TyDeclMutualGroup (members, _)) -> members
            | _ -> [])
        |> Map.ofList
    // Module-level value binding names: constant data for the adjoint's
    // known-name check (tuple patterns contribute each bound name).
    let rec patNames (p: Pattern) : string list =
        match p.Kind with
        | PatternKind.PatVar n -> [n]
        | PatternKind.PatTuple ps -> ps |> List.collect patNames
        | _ -> []
    let moduleVals =
        decls |> List.collect (fun d ->
            match d.Value with
            | DeclLet b | DeclStatic b -> patNames b.Pattern
            | _ -> [])
        |> Set.ofList
    // Source span per differentiable function, for stamping synthSpan so
    // syn-based derivative builders carry the differentiated decl's location.
    let funcSpans =
        decls |> List.choose (fun d ->
            match d.Value with
            | DeclFunction fd -> Some (fd.Name, d.Span)
            | _ -> None)
        |> Map.ofList
    let declNames = funcDecls |> Map.toSeq |> Seq.map fst |> Set.ofSeq
    let requestsOrdered = ResizeArray<string * string>()
    let anticipated = System.Collections.Generic.HashSet<string>()
    // rewrite call sites everywhere
    let rewritten =
        decls |> List.fold (fun acc d ->
            acc |> Result.bind (fun ds ->
                let mapped =
                    match d.Value with
                    | DeclFunction fd ->
                        rewriteExpr requestsOrdered anticipated declNames aliases fd.Body
                        |> Result.map (fun b -> DeclFunction { fd with Body = b })
                    | DeclLet binding ->
                        rewriteExpr requestsOrdered anticipated declNames aliases binding.Value
                        |> Result.map (fun v' -> DeclLet { binding with Value = v' })
                    | DeclStatic binding ->
                        rewriteExpr requestsOrdered anticipated declNames aliases binding.Value
                        |> Result.map (fun v' -> DeclStatic { binding with Value = v' })
                    | other -> Ok other
                mapped |> Result.map (fun value -> ds @ [{ d with Value = value }])))
            (Ok [])
    rewritten |> Result.bind (fun decls' ->
        if requestsOrdered.Count = 0 then Ok decls'
        else
            let ctx = { Decls = funcDecls; TypeAliases = typeAliases; ModuleVals = moduleVals; Fresh = 0 }
            // Synthesize in DISCOVERY order against a GROWING decl map:
            // inner requests precede the outer requests that consume them,
            // so by the time `ad.jvp(ad.grad(f))` synthesizes the outer
            // half, f__grad is an ordinary available declaration.
            let mutable available = funcDecls
            let madeOrder = ResizeArray<string>()
            let madeMap = System.Collections.Generic.Dictionary<string, FunctionDecl * string>()
            let synthResult =
                requestsOrdered
                |> Seq.distinct
                |> Seq.fold (fun acc (mode, fname) ->
                    acc |> Result.bind (fun () ->
                        let suffix = if mode = "grad" then gradSuffix else jvpSuffix
                        let synthName = fname + suffix
                        if madeMap.ContainsKey synthName then Ok ()
                        else
                        match Map.tryFind fname available with
                        | None ->
                            Error (sprintf "%s: '%s' is not available to differentiate (compose ad.grad/ad.jvp within one expression)" mode fname)
                        | Some fd ->
                            // Stamp the ambient synthesis span with the
                            // ROOT source decl's span (composition chains
                            // inherit it) before building the derivative.
                            Blade.Ast.synthSpan <- (Map.tryFind fname funcSpans |> Option.defaultValue Blade.Ast.synthSpan)
                            let ctx2 = { ctx with Decls = available }
                            // A synthesized source is trusted: it binds
                            // reserved names by construction, and the
                            // shadowing hazard the reserved gate guards
                            // against is a user-code phenomenon.
                            let trusted = not (Map.containsKey fname funcDecls)
                            let result =
                                if mode = "grad" then synthesize ctx2 fd
                                else synthesizeJvp ctx2 trusted fd
                            result |> Result.map (fun gd ->
                                available <- Map.add synthName gd available
                                madeOrder.Add synthName
                                madeMap.[synthName] <- (gd, fname))))
                    (Ok ())
            // On failure, LEAVE synthSpan stamped (the `expand` boundary
            // reads it for the diagnostic). Reset on success only.
            match synthResult with
            | Error e -> Error e
            | Ok () ->
                Blade.Ast.synthSpan <- noSpan
                // Splice each synthesized decl after its ROOT source decl,
                // in synthesis order (f, f__grad, f__grad__jvp, ...).
                let rootOf (synthName: string) =
                    let rec go n =
                        match madeMap.TryGetValue n with
                        | true, (_, src) -> if Map.containsKey src funcDecls then src else go src
                        | _ -> n
                    go synthName
                Ok (decls' |> List.collect (fun d ->
                    match d.Value with
                    | DeclFunction fd ->
                        let mine =
                            madeOrder
                            |> Seq.filter (fun sn -> rootOf sn = fd.Name)
                            |> Seq.map (fun sn -> { d with Value = DeclFunction (fst madeMap.[sn]) })
                            |> List.ofSeq
                        d :: mine
                    | _ -> [d]))))

/// Entry point: expand grad() across a program. Errors are compile errors.
let private expandStr (program: Program) : Result<Program, string> =
    program.Modules
    |> List.fold (fun acc m ->
        acc |> Result.bind (fun ms ->
            expandModule m.Decls |> Result.map (fun ds -> ms @ [{ m with Decls = ds }])))
        (Ok [])
    |> Result.map (fun ms -> { program with Modules = ms })

/// Boundary: string-errored internals -> coded diagnostics. The span is the
/// ambient synthSpan -- stamped per-decl by expandStr, so a mid-elaboration
/// failure points at the offending declaration.
let expand (program: Program) : Result<Program, Blade.Diagnostics.Diagnostic list> =
    Blade.Ast.synthSpan <- Blade.Ast.noSpan
    let result =
        expandStr program
        |> Result.mapError (fun msg ->
            // jvp-phase messages carry the "jvp(" prefix (errMode) or the
            // "jvp:" rewrite prefix; everything else is grad's.
            let code = if msg.StartsWith "jvp" then "BL5501" else "BL5500"
            [ Blade.Diagnostics.mkError code (Blade.Diagnostics.Codes.phaseOfCode code) Blade.Ast.synthSpan msg ])
    // Reset AFTER the diagnostic is built (the span is the failing decl's),
    // so no stamp leaks into later passes.
    Blade.Ast.synthSpan <- Blade.Ast.noSpan
    result
