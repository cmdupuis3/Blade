(* ===================================================================== *)
(* BladeDeduceExact.v -- WHAT SYMMETRY DEDUCTION IS EXACT FOR            *)
(* (docs/plans/plan-uniform-optimality.md, T4; implementation            *)
(* src/Deduce.fs).                                                       *)
(*                                                                       *)
(* BladeDeduce proves every rule that ever ANSWERS sound.  This file     *)
(* asks the converse: when the deduction says nothing, was there really  *)
(* nothing to say?  It answers in BladeOrbitWork's term model, where a   *)
(* kernel body is a term over its parameters and the operator symbols    *)
(* are uninterpreted up to a declared commutativity.                     *)
(*                                                                       *)
(*   uniform_equality_exact   two bodies agree under EVERY               *)
(*                            interpretation respecting the declared     *)
(*                            laws, on all data, iff they are equal      *)
(*                            modulo those laws (teq).  Soundness is an  *)
(*                            induction; completeness is the free model, *)
(*                            which is faithful (free_faithful).         *)
(*   uniform_symmetry_is_     so the uniform symmetry group of a body is *)
(*     automorphism           its syntactic automorphism group modulo    *)
(*                            the laws, and membership is decidable by a *)
(*                            structural walk (teqb).                    *)
(*   mirror_spec              src/Deduce.fs's mirrorEq, modelled node    *)
(*                            for node, IS that walk composed with the   *)
(*                            swap: mirror i j l r = teqb (swap l) r.    *)
(*   parfix_exact             the deduction rule answers PInv on a       *)
(*                            transposition EXACTLY when that            *)
(*                            transposition is a uniform symmetry.       *)
(*   deduced_group_sound,     the group the compiler grants is the one   *)
(*   deduced_is_maximal,      GENERATED by the adjacent transpositions   *)
(*   deduced_group_largest    it certifies; it is sound, and it contains *)
(*                            every group generated by adjacent          *)
(*                            transpositions inside the symmetry group   *)
(*                            -- the largest contiguous-block Young      *)
(*                            subgroup.                                  *)
(*   young_generated          such a subgroup IS generated by its        *)
(*                            interior adjacent transpositions, in the   *)
(*                            tower's list semantics: BladeDeduce's      *)
(*                            adjacent_transpositions_generate, from one *)
(*                            block to a shape.                          *)
(*                                                                       *)
(* THE FINDING.  par models the rule in the order it shipped until       *)
(* 2026-09-19: mirror first, and a mirror hit answered from the op's     *)
(* swap class alone.  Under a non-commuting op that class is "no claim", *)
(* and the rule stopped there without looking at the operands.           *)
(*                                                                       *)
(*   par_sound, par_le_parfix the old order was sound and below the      *)
(*                            exact rule;                                *)
(*   shipped_rule_incomplete  (x + y) / (y + x) is a uniform symmetry    *)
(*                            the old order missed.                      *)
(*                                                                       *)
(* The compiler confirmed it (no BL4010 on that body, and a false        *)
(* `anticomm` pin on it accepted where BL4013 should refuse), parityOf   *)
(* now falls through to the chain rule, and tests/corpus/symmetry/049-   *)
(* 051 pin the three behaviours.  parfix is the rule as it now stands.   *)
(*                                                                       *)
(* WHAT STAYS OUT OF REACH, each a closed witness:                       *)
(*                                                                       *)
(*   nonadjacent_symmetry_    g(h(a, c), b): the transposition (0 2) is  *)
(*     missed                 a symmetry, no adjacent one is.  Reachable *)
(*                            only by reordering the parameters.         *)
(*   wreath_symmetry_missed   g(h(a, b), h(c, d)): the deduced group is  *)
(*                            S_2 x S_2, the symmetry group contains the *)
(*                            block swap too -- BladeWreath's wreath     *)
(*                            product, of order 8.                       *)
(*                                                                       *)
(* Both are consequences of the design, not defects: n - 1 adjacent      *)
(* checks buy exactly the contiguous-block Young subgroups, and the      *)
(* theorems above say the deduction gets ALL of those.                   *)
(*                                                                       *)
(* Scope.  The UNSIGNED fragment: variables, unary and binary operator   *)
(* symbols, commutativity as the only law.  PNeg (the sign chain rule),  *)
(* PConj, call summaries, reduce, if/match and let-flattening are not    *)
(* modelled; BladeDeduce covers their soundness and nothing here speaks  *)
(* to their completeness.  Associativity is deliberately NOT a law: it   *)
(* is not licensed for floating point, and the free model agrees.        *)
(*                                                                       *)
(* Imports BladeOptimal, BladeOrbitWork.  Coq 8.18, stdlib only.         *)
(* ===================================================================== *)

From Blade Require Import BladeOptimal BladeOrbitWork.
Require Import List Arith Lia Bool Permutation.
