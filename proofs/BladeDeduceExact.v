Definition comm01 (s : nat) : bool := s =? 0.

(* GAP 1 (closed 2026-09-19) -- a precision bug in the old order.        *)
(* (x + y) / (y + x): the two operands mirror each other, the op does    *)
(* not commute, and the old rule answered PBottom from the mirror hit    *)
(* without looking at the operands -- each invariant on its own.         *)
Definition gap_body : tm :=
  App2 1 (App2 0 (Leaf 0) (Leaf 1)) (App2 0 (Leaf 1) (Leaf 0)).

Example shipped_rule_misses :
  par comm01 0 1 gap_body = PBottom /\
  parfix comm01 0 1 gap_body = PInv.
Proof. vm_compute. split; reflexivity. Qed.

Theorem shipped_rule_incomplete :
  usym comm01 (sw 0 1) gap_body /\ par comm01 0 1 gap_body <> PInv.
Proof.
  split.
  - apply parfix_exact; [lia | reflexivity].
  - vm_compute. discriminate.
Qed.

(* GAP 2 -- a symmetry that is not a product of ADJACENT ones.           *)
(* g(h(a, c), b), h commutative: the transposition (0 2) is a uniform    *)
(* symmetry, neither adjacent transposition is, so the deduced group is  *)
(* trivial.  Reachable only by reordering the parameters.                *)
Definition skip_body : tm := App2 1 (App2 0 (Leaf 0) (Leaf 2)) (Leaf 1).

Theorem nonadjacent_symmetry_missed :
  usym comm01 (sw 0 2) skip_body /\
  ~ deduced comm01 skip_body 0 /\ ~ deduced comm01 skip_body 1.
Proof.
  split; [| split].
  - apply uniform_symmetry_is_automorphism. reflexivity.
  - unfold deduced. vm_compute. discriminate.
  - unfold deduced. vm_compute. discriminate.
Qed.

(* GAP 3 -- a symmetry group that is not Young.  g(h(a, b), h(c, d)),    *)
(* both commutative: the deduced group is S_2 x S_2 (order 4), but the   *)
(* block swap (0 2)(1 3) is a uniform symmetry too -- the wreath product *)
(* of order 8 that BladeWreath proves sound on the input side.           *)
Definition wreath_body : tm :=
  App2 0 (App2 0 (Leaf 0) (Leaf 1)) (App2 0 (Leaf 2) (Leaf 3)).

Definition block_swap (x : nat) : nat :=
  match x with 0 => 2 | 1 => 3 | 2 => 0 | 3 => 1 | _ => x end.

Theorem wreath_symmetry_missed :
  deduced comm01 wreath_body 0 /\ deduced comm01 wreath_body 2 /\
  ~ deduced comm01 wreath_body 1 /\
  usym comm01 block_swap wreath_body.
Proof.
  repeat split.
  - unfold deduced. vm_compute. discriminate.
  - apply uniform_symmetry_is_automorphism. reflexivity.
Qed.

(* ===================================================================== *)
(* PART E.  YOUNG SUBGROUPS ARE GENERATED BY THEIR ADJACENT              *)
(* TRANSPOSITIONS, in the tower's list semantics: BladeDeduce's          *)
(* adjacent_transpositions_generate, from one block to a shape.  A list  *)
(* function that cannot see a swap at any INTERIOR position of any block *)
(* cannot see any blockwise permutation.                                 *)
(* ===================================================================== *)

Section YoungGeneration.
  Variables T W : Type.
  Variable f : list T -> W.
  Variable P : nat -> Prop.
  Hypothesis Hpos : forall pre (a b : T) post, P (length pre) ->
    f (pre ++ a :: b :: post) = f (pre ++ b :: a :: post).

  Lemma block_perm : forall blk blk', Permutation blk blk' ->
    forall pre post,
    (forall i, length pre <= i -> S i < length pre + length blk -> P i) ->
    f (pre ++ blk ++ post) = f (pre ++ blk' ++ post).
  Proof.
    intros blk blk' HP.
    induction HP as [| x l1 l2 HP IH | x y l1 | l1 l2 l3 HP1 IH1 HP2 IH2];
      intros pre post Hin.
    - reflexivity.
    - change (pre ++ (x :: l1) ++ post) with (pre ++ [x] ++ l1 ++ post).
      change (pre ++ (x :: l2) ++ post) with (pre ++ [x] ++ l2 ++ post).
      rewrite !(app_assoc pre [x]). apply IH.
      intros i H1 H2. rewrite app_length in H1, H2. simpl in H1, H2.
      apply Hin; simpl; lia.
    - simpl. apply Hpos. apply Hin; simpl; lia.
    - rewrite IH1 by exact Hin. apply IH2.
      intros i H1 H2. apply Hin; [exact H1 |].
      rewrite (Permutation_length HP1). exact H2.
  Qed.

  Inductive bperm : list nat -> list T -> list T -> Prop :=
  | bperm_nil : forall l, bperm [] l l
  | bperm_cons : forall n bs b b' r r',
      length b = n -> Permutation b b' -> bperm bs r r' ->
      bperm (n :: bs) (b ++ r) (b' ++ r').

  Fixpoint interior (off : nat) (bs : list nat) (i : nat) : Prop :=
    match bs with
    | [] => False
    | n :: bs' => (off <= i /\ S i < off + n) \/ interior (off + n) bs' i
    end.

  Lemma young_generated_ctx : forall bs l l', bperm bs l l' ->
    forall pre, (forall i, interior (length pre) bs i -> P i) ->
    f (pre ++ l) = f (pre ++ l').
  Proof.
    intros bs l l' H.
    induction H as [l | n bs b b' r r' Hn HP _ IH]; intros pre Hin.
    - reflexivity.
    - rewrite (block_perm b b' HP pre r).
      + rewrite !app_assoc. apply IH.
        intros i Hi. apply Hin. right.
        rewrite app_length, <- (Permutation_length HP), Hn in Hi. exact Hi.
      + intros i H1 H2. apply Hin. left. rewrite Hn in H2. split; assumption.
  Qed.

  Theorem young_generated : forall bs l l',
    (forall i, interior 0 bs i -> P i) -> bperm bs l l' -> f l = f l'.
  Proof.
    intros bs l l' Hin H. exact (young_generated_ctx bs l l' H [] Hin).
  Qed.
End YoungGeneration.
